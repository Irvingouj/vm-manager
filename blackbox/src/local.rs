//! What the tests of "Local loop: run the Application on the Builder's
//! machine and send a request as a test User" share (CONTRACT.md, "The
//! local loop: one request as a test User"):
//!
//! - [`Local`], a Builder's [`Machine`] on which `vibe request` and `vibe local
//!   ...` run with the user's own data folder (`XDG_DATA_HOME`) and `TMPDIR`
//!   inside the machine, the harness's own Postgres given as
//!   `VIBE_LOCAL_POSTGRES_BIN` (so that nothing is downloaded) unless a test
//!   says otherwise, and a mark in the environment of every run, so that
//!   every process a run started can be found again from `/proc` (by that
//!   mark, or by a working directory inside the project's `.vibe/local/` or
//!   the machine's `TMPDIR`). Whatever is still running when it is dropped
//!   is killed;
//! - what `vibe request --json` printed, its shape checked ([`Requested`]);
//! - the Postgres of a local run seen from outside while it runs: its
//!   `postmaster.pid` under `.vibe/local/` gives its process, its data folder,
//!   its port and the address it listens on ([`Postmaster`]);
//! - a mirror of Maven's layout, served by the harness on 127.0.0.1, that
//!   hands over zonky's real archive of Postgres 18 (fetched once into the
//!   harness's cache), a cut-short one, other bytes, nothing, or more than
//!   256 MiB, and records every path asked for ([`Mirror`]);
//! - a project made by `vibe new` whose Manifest declares `devops` and whose
//!   one handler does what each path says ([`handler`], [`local_project`]),
//!   and `vibe.dev.json` read and written ([`dev_json`], [`write_dev_json`]);
//! - a search of every file under a folder for bytes ([`files_holding`]).

