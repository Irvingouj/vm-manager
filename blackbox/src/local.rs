/// The handler of the local tests. Paths:
///
/// - `/incidents` (with `devops`): `incidents.id` and `.title` of `devops`
///   read as the User through the pulled definition: `{ user, incidents }`;
/// - `/columns` (with `devops`): every column of `incidents`: `{ rows }`;
/// - `/devops-notes` (with `devops`): `notes.id` and `.body` of `devops`
///   read as the User: `{ notes }`;
/// - `/add-incident` (with `devops`): inserts incident 1000 with the body as
///   its title (the handle cast so that it writes whatever is declared),
///   then reads them all: `{ incidents }`;
/// - `/notes` (with the own `notes`): `POST` inserts the body as a note,
///   then every method answers `{ notes }` (as the User);
/// - `/fail`: throws [`FAILURE`];
/// - `/print`: prints `handling print` (log) and `a warning line` (warn);
/// - `/bytes`: the four bytes `ff fe 00 41`;
/// - `/big?n=<n>`: `n` times `a`;
/// - `/headers`: `x-many: 1`, `x-many: 2`, `X-One: a`;
/// - `/echo`: `{ method, headers, body, search }` of the request;
/// - `/text`: [`TEXT_BODY`];
/// - `/slow?ms=<ms>`: answers after `ms` milliseconds;
/// - `/me`: `{ id, groups }` of the User;
/// - anything else: `{ user }`.
///
/// A refusal is answered `403` with `{ refusal, fix }`. It prints
/// [`LOADING_LINE`] while it loads.
pub fn handler(devops: bool, own_notes: bool) -> String {
    let mut imports = String::from(
        "import { defineApp, Refused } from \"@vm/sdk\";\nimport manifest from \"../manifest.ts\";\n",
    );
    let mut routes = String::new();
    if devops {
        imports.push_str(
            "import { incidents, notes as devopsNotes } from \"../resources/devops/schema.ts\";\n",
        );
        routes.push_str(
            r#"      case "/incidents": {
        const rows = await ctx.user().db("devops").select({ id: incidents.id, title: incidents.title }).from(incidents);
        return Response.json({ user: ctx.user().id, incidents: rows });
      }
      case "/columns": {
        const rows = await ctx.user().db("devops").select().from(incidents);
        return Response.json({ rows });
      }
      case "/devops-notes": {
        const rows = await ctx.user().db("devops").select({ id: devopsNotes.id, body: devopsNotes.body }).from(devopsNotes);
        return Response.json({ notes: rows });
      }
      case "/add-incident": {
        const title = await request.text();
        const writer = ctx.user().db("devops") as any;
        await writer.insert(incidents).values({ id: 1000, title, open: true, severity: 1, reportedAt: "2026-11-15 10:00:00+00" });
        const rows = await ctx.user().db("devops").select({ id: incidents.id, title: incidents.title }).from(incidents);
        return Response.json({ incidents: rows });
      }
"#,
        );
    }
    if own_notes {
        imports.push_str("import { notes } from \"./db/schema.ts\";\n");
        routes.push_str(
            r#"      case "/notes": {
        if (request.method === "POST") {
          await ctx.user().ownDb().insert(notes).values({ body: await request.text() });
        }
        const rows = await ctx.user().ownDb().select().from(notes);
        return Response.json({ notes: rows });
      }
"#,
        );
    }
    format!(
        r#"{imports}
console.log("{LOADING_LINE}");

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export default defineApp(manifest, {{
  async fetch(request, ctx) {{
    const url = new URL(request.url);
    try {{
      switch (url.pathname) {{
{routes}      case "/fail":
        throw new Error("{FAILURE}");
      case "/print":
        console.log("handling print");
        console.warn("a warning line");
        return new Response("printed");
      case "/bytes":
        return new Response(new Uint8Array([0xff, 0xfe, 0x00, 0x41]));
      case "/big":
        return new Response("a".repeat(Number(url.searchParams.get("n") ?? "0")));
      case "/headers": {{
        const headers = new Headers();
        headers.append("x-many", "1");
        headers.append("x-many", "2");
        headers.set("X-One", "a");
        headers.append("set-cookie", "first=1; Path=/");
        headers.append("set-cookie", "second=2, with a comma; Path=/");
        return new Response("headers", {{ headers }});
      }}
      case "/echo": {{
        const headers: Record<string, string> = {{}};
        request.headers.forEach((value, name) => {{
          headers[name] = value;
        }});
        return Response.json({{ method: request.method, headers, body: await request.text(), search: url.search }});
      }}
      case "/text":
        return new Response({text});
      case "/slow":
        await sleep(Number(url.searchParams.get("ms") ?? "0"));
        return new Response("slow");
      case "/me":
        return Response.json({{ id: ctx.user().id, groups: ctx.user().groups }});
      default:
        return Response.json({{ user: ctx.user().id }});
      }}
    }} catch (error) {{
      if (error instanceof Refused) {{
        return Response.json({{ refusal: error.refusal, fix: error.fix }}, {{ status: 403 }});
      }}
      throw error;
    }}
  }},
}});
"#,
        text = serde_json::to_string(TEXT_BODY).unwrap_or_default(),
    )
}

/// A project made by `vibe new <name>` on `machine` (under the repository's
/// `target/`, so that its packages resolve), with a Manifest declaring these
/// Resources and [`handler`] as `src/index.ts` (reading `devops` when it is
/// declared). Nothing pulled yet.
pub fn local_project(machine: &Machine, name: &str, declared: &[(&str, &str)]) -> TempProject {
    let project = new_project_in_repository(machine, name);
    project.write("manifest.ts", &declaring(name, declared));
    let devops = declared.iter().any(|(r, _)| *r == "devops");
    project.write("src/index.ts", &handler(devops, false));
    project
}

/// The Resource the local tests pull: the harness's usual shared database
/// (`incidents`, `kinds`, `notes`, ...).
pub const DEVOPS: &str = "devops";

/// An installation with `devops` registered over a shared database of the
/// test's own (with its read and write logins) and the Builders' Group
/// granted a level on it; a [`Local`] machine signed in to it as dana (in
/// [`crate::deploy::BUILDERS`]); and a project made by `vibe new` declaring
/// `devops`, with [`handler`] as its code, pulled.
pub struct Board {
    pub local: Local,
    pub project: TempProject,
    pub scenario: crate::scenario::Scenario,
}

impl Board {
    /// `devops` declared at `declared` and the Builders granted `held`
    /// (`structure`, `read` or `write`).
    pub fn start(declared: &str, held: &str) -> Self {
        Self::named(APP, declared, held)
    }

    /// As [`Board::start`], the Application named `name`.
    pub fn named(name: &str, declared: &str, held: &str) -> Self {
        Self::on(Local::new(), name, declared, held, "")
    }

    /// As [`Board::named`], on this machine, with `setup` run by the
    /// shared database's superuser before the pull (a view, say). `%READER%`
    /// and `%WRITER%` in it are replaced by the roles of the Resource's
    /// logins.
    pub fn on(local: Local, name: &str, declared: &str, held: &str, setup: &str) -> Self {
        let scenario = crate::scenario::Scenario::start();
        if !setup.is_empty() {
            let sql = setup
                .replace("%READER%", &scenario.db.reader.role)
                .replace("%WRITER%", &scenario.db.writer.role);
            scenario.db.superuser().batch(&sql);
        }
        scenario.register_writable(DEVOPS);
        scenario.grant(DEVOPS, crate::deploy::BUILDERS, held);
        local.machine.sign_in(&scenario.vm, &crate::deploy::dana());
        let project = local_project(&local.machine, name, &[(DEVOPS, declared)]);
        local.pull_ok(&project.dir, DEVOPS);
        Self {
            local,
            project,
            scenario,
        }
    }

    pub fn dir(&self) -> &Path {
        &self.project.dir
    }

    /// `vibe request <path> --as <user> --json <extra>` on the project.
    pub fn request(&self, path: &str, user: &str, extra: &[&str]) -> Run {
        self.local.request(&self.project.dir, path, user, extra)
    }

    /// As [`Board::request`], which must end with `0`.
    pub fn request_ok(&self, path: &str, user: &str, extra: &[&str]) -> Requested {
        self.local.request_ok(&self.project.dir, path, user, extra)
    }
}

