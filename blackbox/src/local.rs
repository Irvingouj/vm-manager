/// The directory of the harness's own Postgres programs (`postgres`,
/// `initdb`, `pg_ctl`), of the version `VIBE_TEST_PG_VERSION` chose: what the
/// tests give `VIBE_LOCAL_POSTGRES_BIN`.
pub fn local_postgres_bin() -> String {
    crate::postgres::binaries()
        .bin
        .to_str()
        .unwrap_or_else(|| panic!("the harness's Postgres is at a path that is not UTF-8"))
        .to_owned()
}

/// Where the user's own data folder is, as a run is told.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DataHome {
    /// `XDG_DATA_HOME` is an absolute path (`<machine>/data`).
    Absolute,
    /// `XDG_DATA_HOME` is not set.
    Unset,
    /// `XDG_DATA_HOME` holds this relative path.
    Relative(String),
}

/// A Builder's machine for the local loop. See the module's text.
pub struct Local {
    pub machine: Machine,
    mark: String,
    bin: Option<String>,
    mirror: Option<String>,
    data_home: DataHome,
    watched: Mutex<Vec<PathBuf>>,
}

impl Default for Local {
    fn default() -> Self {
        Self::new()
    }
}

impl Local {
    /// A machine whose runs get `XDG_DATA_HOME=<machine>/data`,
    /// `TMPDIR=<machine>/tmp` and `VIBE_LOCAL_POSTGRES_BIN` the harness's own
    /// Postgres.
    pub fn new() -> Self {
        let machine = Machine::new();
        for dir in [machine.root().join("tmp"), machine.root().join("data")] {
            fs::create_dir_all(&dir)
                .unwrap_or_else(|e| panic!("cannot make {}: {e}", dir.display()));
        }
        Self {
            machine,
            mark: token(),
            bin: Some(local_postgres_bin()),
            mirror: None,
            data_home: DataHome::Absolute,
            watched: Mutex::new(Vec::new()),
        }
    }

    /// Runs get no `VIBE_LOCAL_POSTGRES_BIN` (a test of the download gives a
    /// [`Mirror`] too, so that nothing is fetched from the Internet).
    #[must_use]
    pub fn without_bin(mut self) -> Self {
        self.bin = None;
        self
    }

    /// Runs get `VIBE_LOCAL_POSTGRES_BIN=<dir>`.
    #[must_use]
    pub fn with_bin(mut self, dir: &str) -> Self {
        self.bin = Some(dir.to_owned());
        self
    }

    /// Runs get `VIBE_LOCAL_POSTGRES_MIRROR=<base URL>`.
    #[must_use]
    pub fn with_mirror(mut self, base_url: &str) -> Self {
        self.mirror = Some(base_url.to_owned());
        self
    }

    /// Runs get this `XDG_DATA_HOME`.
    #[must_use]
    pub fn with_data_home(mut self, data_home: DataHome) -> Self {
        self.data_home = data_home;
        self
    }

    /// The machine's `TMPDIR`.
    pub fn tmp(&self) -> PathBuf {
        self.machine.root().join("tmp")
    }

    /// The absolute `XDG_DATA_HOME` of [`DataHome::Absolute`].
    pub fn data_home_dir(&self) -> PathBuf {
        self.machine.root().join("data")
    }

    /// The folder CONTRACT.md says the Postgres programs are looked for and
    /// downloaded into: `$XDG_DATA_HOME/vibe/postgres/` when that is
    /// absolute, else `$HOME/.local/share/vibe/postgres/`.
    pub fn postgres_folder(&self) -> PathBuf {
        match self.data_home {
            DataHome::Absolute => self.data_home_dir().join("vibe").join("postgres"),
            DataHome::Unset | DataHome::Relative(_) => self
                .machine
                .home()
                .join(".local")
                .join("share")
                .join("vibe")
                .join("postgres"),
        }
    }

    /// The environment every run gets, besides the machine's own.
    pub fn env(&self) -> Vec<(String, String)> {
        let mut env = vec![
            (
                "TMPDIR".to_owned(),
                self.tmp().to_string_lossy().into_owned(),
            ),
            (MARK.to_owned(), self.mark.clone()),
        ];
        match &self.data_home {
            DataHome::Absolute => env.push((
                "XDG_DATA_HOME".to_owned(),
                self.data_home_dir().to_string_lossy().into_owned(),
            )),
            DataHome::Unset => {}
            DataHome::Relative(path) => env.push(("XDG_DATA_HOME".to_owned(), path.clone())),
        }
        if let Some(bin) = &self.bin {
            env.push(("VIBE_LOCAL_POSTGRES_BIN".to_owned(), bin.clone()));
        }
        if let Some(mirror) = &self.mirror {
            env.push(("VIBE_LOCAL_POSTGRES_MIRROR".to_owned(), mirror.clone()));
        }
        env
    }

    fn all_env<'a>(
        &self,
        own: &'a [(String, String)],
        extra: &'a [(&'a str, &'a str)],
    ) -> Vec<(&'a str, &'a str)> {
        let mut all: Vec<(&str, &str)> = own
            .iter()
            .filter(|(name, _)| !extra.iter().any(|(n, _)| n == name))
            .map(|(n, v)| (n.as_str(), v.as_str()))
            .collect();
        all.extend_from_slice(extra);
        all
    }

    /// Notes a project, so that the processes whose working directory is
    /// inside its `.vibe/local/` count as the runs'.
    pub fn watch(&self, dir: &Path) {
        let mut watched = self
            .watched
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        if !watched.iter().any(|d| d == dir) {
            watched.push(dir.to_path_buf());
        }
    }

    /// Runs `vibe <args>` with the machine's environment, this one's, and
    /// these variables (which replace this one's of the same name).
    pub fn run(&self, args: &[&str], extra: &[(&str, &str)]) -> Run {
        let own = self.env();
        let env = self.all_env(&own, extra);
        self.machine.run_into_files(args, &env, LOCAL_TIMEOUT)
    }

    /// Starts `vibe <args>` as [`Local::run`] does and returns at once.
    pub fn spawn(&self, args: &[&str], extra: &[(&str, &str)]) -> Running {
        let own = self.env();
        let env = self.all_env(&own, extra);
        self.machine
            .spawn_into_files(&self.machine.cwd(), args, &env)
    }

    /// `vibe request <path> --as <user> --project <dir> --json <extra>`.
    pub fn request(&self, dir: &Path, path: &str, user: &str, extra: &[&str]) -> Run {
        self.watch(dir);
        let args = request_args(dir, path, user, true, extra);
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        self.run(&refs, &[])
    }

    /// As [`Local::request`], with these environment variables.
    pub fn request_with_env(
        &self,
        dir: &Path,
        path: &str,
        user: &str,
        extra: &[&str],
        env: &[(&str, &str)],
    ) -> Run {
        self.watch(dir);
        let args = request_args(dir, path, user, true, extra);
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        self.run(&refs, env)
    }

    /// `vibe request <path> --as <user> --project <dir> <extra>`, in words.
    pub fn request_in_words(&self, dir: &Path, path: &str, user: &str, extra: &[&str]) -> Run {
        self.watch(dir);
        let args = request_args(dir, path, user, false, extra);
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        self.run(&refs, &[])
    }

    /// As [`Local::request`], which must end with `0`; what it printed.
    pub fn request_ok(&self, dir: &Path, path: &str, user: &str, extra: &[&str]) -> Requested {
        Requested::of(&self.request(dir, path, user, extra))
    }

    /// Starts `vibe request <path> --as <user> --project <dir> --json
    /// <extra>` and returns at once.
    pub fn spawn_request(&self, dir: &Path, path: &str, user: &str, extra: &[&str]) -> Running {
        self.watch(dir);
        let args = request_args(dir, path, user, true, extra);
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        self.spawn(&refs, &[])
    }

    /// `vibe local operation-log --project <dir> --json <extra>`.
    pub fn operation_log(&self, dir: &Path, extra: &[&str]) -> Run {
        self.watch(dir);
        let mut args = vec!["local", "operation-log", "--project", utf8(dir), "--json"];
        args.extend_from_slice(extra);
        self.run(&args, &[])
    }

    /// `vibe local change-history --project <dir> --json <extra>`.
    pub fn change_history(&self, dir: &Path, extra: &[&str]) -> Run {
        self.watch(dir);
        let mut args = vec!["local", "change-history", "--project", utf8(dir), "--json"];
        args.extend_from_slice(extra);
        self.run(&args, &[])
    }

    /// `vibe pull <resource> --project <dir> --json`.
    pub fn pull(&self, dir: &Path, resource: &str) -> Run {
        self.machine
            .run(&["pull", resource, "--project", utf8(dir), "--json"])
    }

    /// As [`Local::pull`], which must end with `0`; what it printed.
    pub fn pull_ok(&self, dir: &Path, resource: &str) -> Value {
        self.pull(dir, resource).ok_json()
    }

    /// Every process the runs of this machine started that is still
    /// running: those whose environment holds this machine's mark, and
    /// those whose working directory is inside a watched project's
    /// `.vibe/local/` or the machine's `TMPDIR`. Never the test's own.
    pub fn processes(&self) -> Vec<Process> {
        let watched: Vec<PathBuf> = self
            .watched
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .iter()
            .map(|d| d.join(".vibe").join("local"))
            .collect();
        let tmp = self.tmp();
        let needle = format!("{MARK}={}", self.mark);
        let me = std::process::id();
        let mut found = Vec::new();
        let Ok(entries) = fs::read_dir("/proc") else {
            return found;
        };
        for entry in entries.flatten() {
            let Some(pid) = entry
                .file_name()
                .to_str()
                .and_then(|n| n.parse::<u32>().ok())
            else {
                continue;
            };
            if pid == me || !crate::project::is_running(pid) {
                continue;
            }
            let dir = entry.path();
            let marked = fs::read(dir.join("environ"))
                .is_ok_and(|bytes| bytes.split(|b| *b == 0).any(|v| v == needle.as_bytes()));
            let cwd = fs::read_link(dir.join("cwd")).unwrap_or_default();
            let inside = !cwd.as_os_str().is_empty()
                && (cwd.starts_with(&tmp) || watched.iter().any(|w| cwd.starts_with(w)));
            if marked || inside {
                let cmdline = fs::read(dir.join("cmdline"))
                    .map(|b| {
                        String::from_utf8_lossy(&b)
                            .replace('\0', " ")
                            .trim()
                            .to_owned()
                    })
                    .unwrap_or_default();
                found.push(Process { pid, cmdline, cwd });
            }
        }
        found
    }

    /// The processes of [`Local::processes`] still running after waiting up
    /// to `grace` for them to end.
    pub fn processes_after(&self, grace: Duration) -> Vec<Process> {
        let deadline = Instant::now() + grace;
        loop {
            let found = self.processes();
            if found.is_empty() || Instant::now() >= deadline {
                return found;
            }
            thread::sleep(Duration::from_millis(50));
        }
    }
}

impl Drop for Local {
    fn drop(&mut self) {
        let pids: Vec<u32> = self.processes().iter().map(|p| p.pid).collect();
        kill_all(&pids);
    }
}

/// A process found by [`Local::processes`].
#[derive(Clone, Debug)]
pub struct Process {
    pub pid: u32,
    pub cmdline: String,
    pub cwd: PathBuf,
}

fn utf8(dir: &Path) -> &str {
    dir.to_str().unwrap_or_else(|| panic!("not UTF-8: {dir:?}"))
}

/// The arguments of `vibe request <path> --as <user> --project <dir>
/// [--json] <extra>`.
pub fn request_args(dir: &Path, path: &str, user: &str, json: bool, extra: &[&str]) -> Vec<String> {
    let mut args: Vec<String> = vec![
        "request".to_owned(),
        path.to_owned(),
        "--as".to_owned(),
        user.to_owned(),
        "--project".to_owned(),
        utf8(dir).to_owned(),
    ];
    if json {
        args.push("--json".to_owned());
    }
    args.extend(extra.iter().map(|a| (*a).to_owned()));
    args
}

/// What `vibe request --json` printed when it ended with `0`.
#[derive(Clone, Debug)]
pub struct Requested {
    pub run: Run,
    pub body: Value,
}

impl Requested {
    /// Fails unless the run ended with `0` and printed the object of
    /// CONTRACT.md's "What it prints": every field there with its type and
    /// no other.
    pub fn of(run: &Run) -> Self {
        let body = run.ok_json();
        let describe = || run.describe();
        let mut keys: Vec<&str> = body
            .as_object()
            .map(|o| o.keys().map(String::as_str).collect())
            .unwrap_or_default();
        keys.sort_unstable();
        assert_eq!(
            keys,
            REQUESTED_KEYS,
            "expected exactly the fields of the contract's object\n{}",
            describe()
        );
        for key in ["as", "method", "path", "application", "request_id"] {
            assert!(
                body[key].as_str().is_some_and(|s| !s.is_empty()),
                "expected `{key}` a string that is not empty\n{}",
                describe()
            );
        }
        for key in ["version", "status"] {
            assert!(
                body[key].is_u64(),
                "expected `{key}` a number\n{}",
                describe()
            );
        }
        let headers = body["headers"]
            .as_object()
            .unwrap_or_else(|| panic!("expected `headers` an object\n{}", describe()));
        for (name, values) in headers {
            assert_eq!(
                name,
                &name.to_lowercase(),
                "expected each header's name in lower case\n{}",
                describe()
            );
            assert!(
                values
                    .as_array()
                    .is_some_and(|v| v.iter().all(Value::is_string)),
                "expected each header's values an array of strings, got {name}: {values}\n{}",
                describe()
            );
        }
        assert!(
            body["body"].is_string() || body["body"].is_null(),
            "expected `body` a string or null\n{}",
            describe()
        );
        assert!(
            body["body_base64"].is_string() || body["body_base64"].is_null(),
            "expected `body_base64` a string or null\n{}",
            describe()
        );
        assert!(
            body["body"].is_null() != body["body_base64"].is_null(),
            "expected exactly one of `body` and `body_base64` to hold the body\n{}",
            describe()
        );
        assert!(
            body["body_truncated"].is_boolean(),
            "expected `body_truncated` a boolean\n{}",
            describe()
        );
        for item in body["printed"]
            .as_array()
            .unwrap_or_else(|| panic!("expected `printed` an array\n{}", describe()))
        {
            let mut inner: Vec<&str> = item
                .as_object()
                .map(|o| o.keys().map(String::as_str).collect())
                .unwrap_or_default();
            inner.sort_unstable();
            assert_eq!(
                inner,
                ["level", "loading", "message"],
                "expected each of `printed` to be {{ level, message, loading }}\n{}",
                describe()
            );
        }
        for key in ["uncaught", "migrations_applied"] {
            assert!(
                body[key]
                    .as_array()
                    .is_some_and(|v| v.iter().all(Value::is_string)),
                "expected `{key}` an array of strings\n{}",
                describe()
            );
        }
        assert!(
            body["operations"].is_array(),
            "expected `operations` an array\n{}",
            describe()
        );
        for item in body["standins"]
            .as_array()
            .unwrap_or_else(|| panic!("expected `standins` an array\n{}", describe()))
        {
            assert!(
                item["resource"].is_string() && item["made"].is_boolean(),
                "expected each of `standins` to be {{ resource, made }}, got {item}\n{}",
                describe()
            );
        }
        for item in body["test_rows"]
            .as_array()
            .unwrap_or_else(|| panic!("expected `test_rows` an array\n{}", describe()))
        {
            let mut inner: Vec<&str> = item
                .as_object()
                .map(|o| o.keys().map(String::as_str).collect())
                .unwrap_or_default();
            inner.sort_unstable();
            assert!(
                inner == ["file", "rows"] && item["file"].is_string() && item["rows"].is_u64(),
                "expected each of `test_rows` to be {{ file, rows }}, got {item}\n{}",
                describe()
            );
        }
        for key in ["warnings", "notes"] {
            for item in body[key]
                .as_array()
                .unwrap_or_else(|| panic!("expected `{key}` an array\n{}", describe()))
            {
                for field in ["reason", "message"] {
                    assert!(
                        item[field].as_str().is_some_and(|s| !s.trim().is_empty()),
                        "expected each of `{key}` to have a `{field}`, got {item}\n{}",
                        describe()
                    );
                }
            }
        }
        Self {
            run: run.clone(),
            body,
        }
    }

    pub fn describe(&self) -> String {
        self.run.describe()
    }

    pub fn status(&self) -> u64 {
        self.body["status"].as_u64().unwrap_or_default()
    }

    pub fn version(&self) -> u64 {
        self.body["version"].as_u64().unwrap_or_default()
    }

    pub fn request_id(&self) -> String {
        self.body["request_id"]
            .as_str()
            .unwrap_or_default()
            .to_owned()
    }

    /// `body`, which must be text.
    pub fn text(&self) -> String {
        self.body["body"]
            .as_str()
            .unwrap_or_else(|| panic!("expected the body as text\n{}", self.describe()))
            .to_owned()
    }

    /// `body` read as JSON.
    pub fn json(&self) -> Value {
        serde_json::from_str(&self.text())
            .unwrap_or_else(|e| panic!("expected the body to be JSON ({e})\n{}", self.describe()))
    }

    pub fn operations(&self) -> Vec<Value> {
        self.body["operations"]
            .as_array()
            .cloned()
            .unwrap_or_default()
    }

    pub fn migrations_applied(&self) -> Vec<String> {
        self.body["migrations_applied"]
            .as_array()
            .map(|v| {
                v.iter()
                    .filter_map(|s| s.as_str().map(str::to_owned))
                    .collect()
            })
            .unwrap_or_default()
    }

    /// `test_rows`: what this run loaded.
    pub fn test_rows(&self) -> Value {
        self.body["test_rows"].clone()
    }

    pub fn standins(&self) -> Vec<Value> {
        self.body["standins"]
            .as_array()
            .cloned()
            .unwrap_or_default()
    }

    /// The warnings with this reason.
    pub fn warnings_for(&self, reason: &str) -> Vec<Value> {
        self.list_for("warnings", reason)
    }

    /// The notes with this reason.
    pub fn notes_for(&self, reason: &str) -> Vec<Value> {
        self.list_for("notes", reason)
    }

    fn list_for(&self, list: &str, reason: &str) -> Vec<Value> {
        self.body[list]
            .as_array()
            .map(|items| {
                items
                    .iter()
                    .filter(|w| w["reason"] == reason)
                    .cloned()
                    .collect()
            })
            .unwrap_or_default()
    }
}

/// The Postgres of a local run, as its `postmaster.pid` says while it runs.
#[derive(Clone, Debug)]
pub struct Postmaster {
    /// The `postmaster.pid` file.
    pub file: PathBuf,
    pub pid: u32,
    /// The data folder, as the file names it.
    pub data: PathBuf,
    pub port: u16,
    /// The first address it listens on.
    pub listen: String,
}

/// Every `postmaster.pid` under `dir`, at any depth (no link followed).
fn postmaster_files(dir: &Path, found: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        match fs::symlink_metadata(&path) {
            Ok(meta) if meta.is_dir() => postmaster_files(&path, found),
            Ok(meta) if meta.is_file() && entry.file_name() == "postmaster.pid" => {
                found.push(path);
            }
            _ => {}
        }
    }
}

/// The Postgres of the project in `dir` while it runs: read from the
/// `postmaster.pid` under its `.vibe/local/`, when that file is there and
/// says what it listens on (Postgres writes the port and address once it
/// listens).
pub fn postmaster_of(dir: &Path) -> Option<Postmaster> {
    let mut files = Vec::new();
    postmaster_files(&dir.join(".vibe").join("local"), &mut files);
    files.into_iter().find_map(|file| {
        let text = fs::read_to_string(&file).ok()?;
        let lines: Vec<&str> = text.lines().collect();
        let pid = lines.first()?.trim().parse().ok()?;
        let data = PathBuf::from(lines.get(1)?.trim());
        let port = lines.get(3)?.trim().parse().ok()?;
        let listen = lines.get(5)?.trim().to_owned();
        if listen.is_empty() {
            return None;
        }
        Some(Postmaster {
            file,
            pid,
            data,
            port,
            listen,
        })
    })
}

/// Waits until the project's Postgres listens ([`postmaster_of`]), at most
/// `limit`.
pub fn wait_for_postmaster(
    dir: &Path,
    running: &mut crate::tool::Running,
    limit: Duration,
) -> Option<Postmaster> {
    let deadline = Instant::now() + limit;
    loop {
        if let Some(found) = postmaster_of(dir).filter(|p| crate::project::is_running(p.pid)) {
            return Some(found);
        }
        // A run that has ended will start no Postgres: waiting longer
        // would only make a failing test slow.
        if Instant::now() >= deadline || running.has_ended() {
            return None;
        }
        thread::sleep(Duration::from_millis(50));
    }
}

/// Whether something accepts a connection on 127.0.0.1 at `port`.
pub fn port_open(port: u16) -> bool {
    let address = SocketAddr::from(([127, 0, 0, 1], port));
    TcpStream::connect_timeout(&address, Duration::from_secs(2)).is_ok()
}

/// What a [`Mirror`] hands over for the archive's path.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Serving {
    /// zonky's real archive of Postgres 18 for this machine.
    Archive,
    /// The archive's length announced, half of it sent, then the
    /// connection closed.
    CutShort,
    /// As many bytes as the archive, one of them changed.
    OtherBytes,
    /// `404` for every path.
    Missing,
    /// `200` with 300 MiB announced and sent (zeros), more than the 256 MiB
    /// a download may be.
    Huge,
}

/// The bytes of the archive a mirror hands over, read once.
fn archive() -> &'static [u8] {
    static ARCHIVE: OnceLock<Vec<u8>> = OnceLock::new();
    ARCHIVE.get_or_init(|| crate::postgres::archive_bytes(18))
}

/// The path of zonky's archive of Postgres 18 for this machine, as a
/// [`Mirror`] serves it: `/maven2/io/zonky/...jar`.
pub fn archive_path() -> String {
    let archive = crate::postgres::archive_of(18).unwrap_or_else(|| {
        panic!(
            "the harness knows no archive of Postgres 18 for {} {}",
            std::env::consts::OS,
            std::env::consts::ARCH
        )
    });
    assert_eq!(
        archive.version, "18.6.0",
        "the harness's own check: CONTRACT.md has 18.6.0 downloaded"
    );
    format!("/maven2/{}", archive.maven_path)
}

/// A mirror of Maven's layout on 127.0.0.1 (see [`Serving`]). Stopped and
/// joined when dropped.
pub struct Mirror {
    address: SocketAddr,
    requests: Arc<Mutex<Vec<String>>>,
    stop: Arc<AtomicBool>,
    thread: Option<thread::JoinHandle<()>>,
}

impl Mirror {
    pub fn start(serving: Serving) -> Self {
        // Read before the first connection, so that a download is not
        // slowed by the harness's own.
        if serving != Serving::Missing && serving != Serving::Huge {
            let _read_now = archive();
        }
        let listener = TcpListener::bind("127.0.0.1:0").expect("cannot bind 127.0.0.1:0");
        listener
            .set_nonblocking(true)
            .expect("cannot make the listener non-blocking");
        let address = listener.local_addr().expect("the listener has an address");
        let requests = Arc::new(Mutex::new(Vec::new()));
        let stop = Arc::new(AtomicBool::new(false));
        let stopping = Arc::clone(&stop);
        let seen = Arc::clone(&requests);
        let thread = thread::spawn(move || {
            while !stopping.load(Ordering::Relaxed) {
                match listener.accept() {
                    Ok((stream, _)) => serve(stream, serving, &seen),
                    Err(_) => thread::sleep(Duration::from_millis(10)),
                }
            }
        });
        Self {
            address,
            requests,
            stop,
            thread: Some(thread),
        }
    }

    /// The base URL to give `VIBE_LOCAL_POSTGRES_MIRROR`.
    pub fn base_url(&self) -> String {
        format!("http://{}/maven2", self.address)
    }

    /// Every path asked for, in order.
    pub fn requests(&self) -> Vec<String> {
        self.requests
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .clone()
    }
}

impl Drop for Mirror {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Relaxed);
        if let Some(thread) = self.thread.take() {
            drop(thread.join());
        }
    }
}

fn serve(mut stream: TcpStream, serving: Serving, seen: &Mutex<Vec<String>>) {
    drop(stream.set_nonblocking(false));
    drop(stream.set_read_timeout(Some(Duration::from_secs(5))));
    drop(stream.set_write_timeout(Some(Duration::from_secs(30))));
    let mut head = Vec::new();
    let mut chunk = [0_u8; 1024];
    while !head.windows(4).any(|w| w == b"\r\n\r\n") && head.len() < 64 * 1024 {
        match stream.read(&mut chunk) {
            Ok(0) | Err(_) => break,
            Ok(n) => head.extend_from_slice(chunk.get(..n).unwrap_or_default()),
        }
    }
    let text = String::from_utf8_lossy(&head);
    let path = text
        .lines()
        .next()
        .and_then(|line| line.split_whitespace().nth(1))
        .unwrap_or_default()
        .to_owned();
    seen.lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .push(path.clone());
    let wanted = path == archive_path();
    let not_found =
        || b"HTTP/1.1 404 Not Found\r\ncontent-length: 0\r\nconnection: close\r\n\r\n".to_vec();
    let head_of = |length: u64| {
        format!(
            "HTTP/1.1 200 OK\r\ncontent-type: application/java-archive\r\ncontent-length: {length}\r\nconnection: close\r\n\r\n"
        )
        .into_bytes()
    };
    match serving {
        Serving::Missing => drop(stream.write_all(&not_found())),
        _ if !wanted => drop(stream.write_all(&not_found())),
        Serving::Archive => {
            let bytes = archive();
            drop(stream.write_all(&head_of(len_u64(bytes.len()))));
            drop(stream.write_all(bytes));
        }
        Serving::CutShort => {
            let bytes = archive();
            drop(stream.write_all(&head_of(len_u64(bytes.len()))));
            drop(stream.write_all(bytes.get(..bytes.len() / 2).unwrap_or_default()));
        }
        Serving::OtherBytes => {
            let mut bytes = archive().to_vec();
            let middle = bytes.len() / 2;
            if let Some(b) = bytes.get_mut(middle) {
                *b = b.wrapping_add(1);
            }
            drop(stream.write_all(&head_of(len_u64(bytes.len()))));
            drop(stream.write_all(&bytes));
        }
        Serving::Huge => {
            let total: u64 = 300 * 1024 * 1024;
            if stream.write_all(&head_of(total)).is_ok() {
                let zeros = vec![0_u8; 1024 * 1024];
                let mut sent: u64 = 0;
                while sent < total && stream.write_all(&zeros).is_ok() {
                    sent += len_u64(zeros.len());
                }
            }
        }
    }
    drop(stream.flush());
}

fn len_u64(n: usize) -> u64 {
    u64::try_from(n).unwrap_or(u64::MAX)
}

