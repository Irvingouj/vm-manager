/// What [`catalog_reads`] found.
#[derive(Debug, Default)]
pub struct CatalogReads {
    /// The statements the login sent that read something (not transaction
    /// control, not `SET`).
    pub reads: Vec<String>,
    /// Every text the login sent, transaction control and settings
    /// included.
    pub texts: Vec<String>,
    /// What breaks the contract, one line each.
    pub problems: Vec<String>,
}

/// Words a statement reading only the structure never holds.
const STATISTICS: [&str; 8] = [
    "pg_statistic",
    "pg_stats",
    "pg_stat_",
    "reltuples",
    "relpages",
    "pg_relation_size",
    "pg_total_relation_size",
    "pg_table_size",
];

/// Reads the server log of `db` and checks every statement `role` sent to
/// it: what it reads (by the plan the harness's superuser gets for it),
/// that it reads only `pg_catalog` and no statistics, that its text names
/// none of `own_names` (the database's own tables and functions) as a
/// value written into it and none of `information_schema`, that it is in a
/// read-only transaction, and that no setting is changed but the session's
/// own (no `SET ROLE`, no `SET SESSION AUTHORIZATION`).
pub fn catalog_reads(db: &SharedDatabase, role: &str, own_names: &[String]) -> CatalogReads {
    catalog_reads_since(db, role, own_names, 0)
}

/// How many entries the shared database server's log holds now: a mark to
/// give to [`catalog_reads_since`] and [`statements_sent_since`], so that
/// what follows a registration (which connects every login and probes the
/// read and the structure login) can be told from what it sent.
pub fn log_mark(db: &SharedDatabase) -> usize {
    entries(db.server()).len()
}

/// How many statements `role` sent to `db` after the log held `mark`
/// entries.
pub fn statements_sent_since(db: &SharedDatabase, role: &str, mark: usize) -> usize {
    let all = entries(db.server());
    sent_by(all.get(mark..).unwrap_or_default(), db.name(), role).len()
}

/// As [`catalog_reads`], of the statements sent after the log held `mark`
/// entries ([`log_mark`]).
pub fn catalog_reads_since(
    db: &SharedDatabase,
    role: &str,
    own_names: &[String],
    mark: usize,
) -> CatalogReads {
    let all = entries(db.server());
    let sent = sent_by(all.get(mark..).unwrap_or_default(), db.name(), role);
    let mut found = CatalogReads::default();
    let superuser = db.superuser();
    let mut pids: Vec<&str> = sent.iter().map(|s| s.pid.as_str()).collect();
    pids.sort_unstable();
    pids.dedup();
    for pid in pids {
        let mut in_transaction: Option<bool> = None;
        let mut session_read_only = false;
        let mut search_path: Option<String> = None;
        for s in sent.iter().filter(|s| s.pid == pid) {
            let pieces = crate::server_log::split_statements(&s.sql);
            let single = pieces.len() == 1;
            for statement in pieces {
                found.texts.push(statement.clone());
                let upper = statement.to_ascii_uppercase();
                let words: Vec<&str> = upper.split_whitespace().collect();
                let first = words.first().copied().unwrap_or_default();
                if begins_transaction(&statement) {
                    in_transaction = Some(upper.contains("READ ONLY") || session_read_only);
                    continue;
                }
                if ends_transaction(&statement) {
                    in_transaction = None;
                    continue;
                }
                if matches!(
                    first,
                    "SAVEPOINT" | "RELEASE" | "DISCARD" | "DEALLOCATE" | "SHOW"
                ) {
                    continue;
                }
                if first == "SET" || first == "RESET" {
                    let compact = words.join(" ");
                    if compact.starts_with("SET ROLE")
                        || compact.starts_with("SET SESSION AUTHORIZATION")
                        || compact.starts_with("RESET ROLE")
                        || compact.starts_with("SET SESSION ROLE")
                        || compact.starts_with("SET LOCAL ROLE")
                    {
                        found.problems.push(format!("changes role: {statement}"));
                    }
                    if compact.contains("READ ONLY")
                        || (compact.contains("TRANSACTION_READ_ONLY")
                            && (compact.contains("ON") || compact.contains("TRUE")))
                    {
                        if compact.contains("SESSION CHARACTERISTICS")
                            || compact.contains("DEFAULT_TRANSACTION_READ_ONLY")
                        {
                            session_read_only = true;
                        } else if in_transaction.is_some() {
                            in_transaction = Some(true);
                        }
                    }
                    if compact.contains("SEARCH_PATH") {
                        search_path = Some(statement.clone());
                    }
                    continue;
                }
                found.reads.push(statement.clone());
                let read_only = in_transaction.unwrap_or(session_read_only);
                if !read_only {
                    found.problems.push(format!(
                        "not in a read-only transaction (backend {pid}): {statement}"
                    ));
                }
                if !matches!(first, "SELECT" | "WITH" | "VALUES" | "TABLE") {
                    found
                        .problems
                        .push(format!("not a read of the catalogs: {statement}"));
                    continue;
                }
                let lower = statement.to_ascii_lowercase();
                for word in STATISTICS {
                    if lower.contains(word) {
                        found
                            .problems
                            .push(format!("reads statistics ({word}): {statement}"));
                    }
                }
                if lower.contains("information_schema") {
                    found.problems.push(format!(
                        "reads information_schema, not pg_catalog: {statement}"
                    ));
                }
                for name in own_names {
                    if statement.contains(&format!("'{name}'")) {
                        found.problems.push(format!(
                            "writes the database's own name {name:?} into its text, not as a parameter: {statement}"
                        ));
                    }
                }
                let to_explain = if single {
                    s.clone()
                } else {
                    Sent {
                        pid: s.pid.clone(),
                        sql: statement.clone(),
                        params: Vec::new(),
                    }
                };
                match explain(&superuser, &to_explain, search_path.as_deref()) {
                    Ok(relations) => {
                        for (schema, relation) in relations {
                            if schema != "pg_catalog" {
                                found.problems.push(format!(
                                    "reads {schema}.{relation}, not a catalog: {statement}"
                                ));
                            } else if relation.starts_with("pg_statistic") {
                                found.problems.push(format!(
                                    "reads the statistics ({relation}): {statement}"
                                ));
                            }
                        }
                    }
                    Err(problem) => found.problems.push(format!(
                        "the harness cannot tell what it reads ({problem}): {statement}"
                    )),
                }
            }
        }
    }
    found
}

/// The (schema, relation) pairs the plan of `sent` scans, as the harness's
/// superuser explains it in the session's `search_path`: with
/// `GENERIC_PLAN` when it has parameters, else with its parameters
/// written in.
fn explain(
    superuser: &Sql,
    sent: &Sent,
    search_path: Option<&str>,
) -> Result<Vec<(String, String)>, String> {
    superuser.batch("RESET search_path");
    if let Some(set) = search_path {
        superuser.try_batch(set)?;
    }
    let has_params = sent.sql.contains('$');
    let mut attempts = Vec::new();
    if has_params {
        attempts.push(format!(
            "EXPLAIN (VERBOSE, GENERIC_PLAN, FORMAT JSON) {}",
            sent.sql
        ));
    }
    attempts.push(format!("EXPLAIN (VERBOSE, FORMAT JSON) {}", sent.as_sql()));
    let mut last = String::new();
    for attempt in attempts {
        match superuser.try_batch(&attempt) {
            Ok(rows) => {
                superuser.batch("RESET search_path");
                let text = rows
                    .into_iter()
                    .next()
                    .and_then(|r| r.into_iter().next().flatten())
                    .unwrap_or_default();
                let plan: Value = serde_json::from_str(&text)
                    .map_err(|e| format!("the plan is not JSON: {e}"))?;
                let mut relations = Vec::new();
                relations_in(&plan, &mut relations);
                return Ok(relations);
            }
            Err(problem) => last = problem,
        }
    }
    superuser.batch("RESET search_path");
    Err(last)
}

fn relations_in(plan: &Value, found: &mut Vec<(String, String)>) {
    match plan {
        Value::Object(map) => {
            if let Some(relation) = map.get("Relation Name").and_then(Value::as_str) {
                let schema = map
                    .get("Schema")
                    .and_then(Value::as_str)
                    .unwrap_or("(no schema)");
                found.push((schema.to_owned(), relation.to_owned()));
            }
            for value in map.values() {
                relations_in(value, found);
            }
        }
        Value::Array(items) => {
            for item in items {
                relations_in(item, found);
            }
        }
        _ => {}
    }
}

/// The names of the database's own tables, views, sequences, types and
/// functions (outside Postgres's own schemas): what a statement reading the
/// catalogs never writes into its text.
pub fn own_names(db: &SharedDatabase) -> Vec<String> {
    db.superuser()
        .batch(
            "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
              WHERE n.nspname NOT LIKE 'pg\\_%' AND n.nspname <> 'information_schema'
             UNION SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
              WHERE n.nspname NOT LIKE 'pg\\_%' AND n.nspname <> 'information_schema'
             UNION SELECT nspname FROM pg_namespace
              WHERE nspname NOT LIKE 'pg\\_%' AND nspname NOT IN ('information_schema', 'public')",
        )
        .into_iter()
        .filter_map(|r| r.into_iter().next().flatten())
        .collect()
}

/// Fails unless the `no-grant` refusal `body` (`{ "error": ... }`) names
/// the Resource and its contact, and says whom to ask and not to build
/// against it.
pub fn assert_no_grant_error(body: &Value, resource: &str, context: &str) {
    let error = &body["error"];
    assert_eq!(
        error["reason"].as_str(),
        Some("no-grant"),
        "{context}: expected the reason `no-grant`, got {body}"
    );
    assert_eq!(
        error["resource"].as_str(),
        Some(resource),
        "{context}: expected `resource` {resource:?} beside the reason, got {body}"
    );
    assert_eq!(
        error["contact"].as_str(),
        Some(CONTACT),
        "{context}: expected `contact`, the Resource's contact, beside the reason, got {body}"
    );
    assert_no_grant_message(error["message"].as_str().unwrap_or_default(), context);
}

/// Fails unless a `no-grant` message names the contact as whom to ask and
/// says not to build against the Resource.
pub fn assert_no_grant_message(message: &str, context: &str) {
    assert!(
        message.contains(CONTACT),
        "{context}: expected the message to name whom to ask ({CONTACT:?}), got {message:?}"
    );
    let lower = message.to_lowercase();
    assert!(
        lower.contains("build") && (lower.contains("not") || lower.contains("n't")),
        "{context}: expected the message to say not to build against the Resource until then, got {message:?}"
    );
}

