//! What the tests of pulling a Resource's structure share (CONTRACT.md,
//! "Pulling a Resource's structure"; ticket "Pull a Resource's structure as
//! a typed Drizzle definition"):
//!
//! - [`STOCK`], a fixture shared database with the common shapes, built on
//!   top of [`crate::shared_database`]'s own tables by [`IN_ORDER`] or by
//!   the same statements in another order ([`IN_ANOTHER_ORDER`]), and a
//!   structure login that may do nothing but connect ([`Stock`]);
//! - [`PROBE`], a small schema of its own whose every kind of change the
//!   fingerprint tests make and then undo by building it again;
//! - [`HOSTILE`], names that try to break out of a TypeScript string;
//! - the generated link a pull writes ([`link`]), the fingerprint's form,
//!   and the parts of the definition a test looks for;
//! - [`catalog_reads`], which reads the server log of the shared database
//!   and says what the statements of one login read: each statement is
//!   explained by the harness's superuser (`EXPLAIN (VERBOSE, GENERIC_PLAN)`
//!   in the session's `search_path`), and every relation the plan scans
//!   must be in `pg_catalog`, none of the statistics, and every statement in
//!   a read-only transaction;
//! - `tsc` over a project ([`type_check`]) and a copy of a fixture project
//!   ([`copy_project`]).

