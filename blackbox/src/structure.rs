/// Names that try to break out of a TypeScript string, a template literal
/// or a comment: a quote, an apostrophe, a backtick, `${`, `*/`, a
/// backslash, a line end and `</script>`. Each is a table, a column and an
/// enum label.
pub const HOSTILE_NAMES: [&str; 11] = [
    "q\"uote",
    "it's",
    "back`tick",
    "${globalThis.leak}",
    "*/ end",
    "back\\slash",
    "line\nend",
    "</script>",
    "line\u{2028}separator",
    "paragraph\u{2029}separator",
    "over\u{202e}ride",
];

/// The characters that must never be raw in a definition: JavaScript's
/// line and paragraph separators, and the bidirectional override.
pub const NEVER_RAW: [char; 3] = ['\u{2028}', '\u{2029}', '\u{202e}'];

/// A default's expression: a string constant holding every hostile name.
pub fn hostile_default() -> String {
    HOSTILE_NAMES.join(" | ")
}

/// The enum whose labels are [`HOSTILE_NAMES`].
pub const HOSTILE_ENUM: &str = "odd \"mood\"";

/// Quotes a name as a Postgres identifier.
pub fn ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

/// Quotes a text as a Postgres string literal (`E'...'` when it holds a
/// line end or a backslash).
pub fn literal(text: &str) -> String {
    if text.contains('\n') || text.contains('\\') {
        format!(
            "E'{}'",
            text.replace('\\', "\\\\")
                .replace('\'', "\\'")
                .replace('\n', "\\n")
        )
    } else {
        format!("'{}'", text.replace('\'', "''"))
    }
}

/// The statements that make the hostile structure: the enum, and one table
/// per hostile name whose columns are every hostile name, then `mood` of
/// the enum's type, then `note` whose default is [`hostile_default`].
pub fn hostile_setup() -> String {
    let labels: Vec<String> = HOSTILE_NAMES.iter().map(|n| literal(n)).collect();
    let mut sql = format!(
        "CREATE TYPE {} AS ENUM ({});\n",
        ident(HOSTILE_ENUM),
        labels.join(", ")
    );
    for table in HOSTILE_NAMES {
        let mut columns: Vec<String> = HOSTILE_NAMES
            .iter()
            .map(|c| format!("{} text", ident(c)))
            .collect();
        columns.push(format!("\"mood\" {}", ident(HOSTILE_ENUM)));
        columns.push(format!("note text DEFAULT {}", literal(&hostile_default())));
        sql.push_str(&format!(
            "CREATE TABLE {} (id integer PRIMARY KEY, {});\n",
            ident(table),
            columns.join(", ")
        ));
    }
    sql
}

/// The fixture shared database with a structure login, on a program.
pub struct Stock {
    pub scenario: Scenario,
    /// A login that may connect and nothing else.
    pub structure: Login,
}

impl Stock {
    /// A program, and a shared database with [`IN_ORDER`], [`SEED`] and
    /// [`GRANTS`]; nothing registered.
    pub fn start() -> Self {
        Self::start_ordered(&IN_ORDER)
    }

    /// As [`Stock::start`], built by these statements.
    pub fn start_ordered(statements: &[&str]) -> Self {
        let scenario = Scenario::start();
        let structure = build_stock(&scenario.db, statements);
        Self {
            scenario,
            structure,
        }
    }

    /// As [`Stock::start`], with [`STOCK`] registered with the read, write
    /// and structure logins, and [`READERS`] granted `read` on it.
    pub fn ready() -> Self {
        let stock = Self::start();
        stock.register(STOCK);
        stock.scenario.grant(STOCK, READERS, "read");
        stock
    }

    pub fn db(&self) -> &SharedDatabase {
        &self.scenario.db
    }

    /// Registers `name` with the read, write and structure logins.
    pub fn register(&self, name: &str) -> Value {
        self.scenario
            .register_body(name, &body_with_structure(name, self.db(), &self.structure))
    }

    /// Registers `name` with the read and write logins and no structure
    /// login.
    pub fn register_without_structure(&self, name: &str) -> Value {
        self.scenario.register_writable(name)
    }

    /// `GET /v1/resources/<name>/structure` as this User.
    pub fn pull(&self, user: &User, name: &str) -> Response {
        pull(&self.scenario.vm.api_as(user), name)
    }

    /// As [`Stock::pull`], which must be `200`; the answer's body.
    pub fn pull_ok(&self, user: &User, name: &str) -> Value {
        let answer = self.pull(user, name);
        if answer.status != 200 {
            self.scenario.vm.fail(&format!(
                "expected `200` pulling the structure of {name:?} as {:?}, got\n{}",
                user.id,
                answer.describe()
            ));
        }
        answer.json()
    }

    /// Everything that must never appear in anything the program says: the
    /// shared database's markers and the structure login's.
    pub fn markers(&self) -> Vec<(&'static str, String)> {
        let mut markers = self.db().credential_markers();
        markers.push(("the structure login's role", self.structure.role.clone()));
        markers.push((
            "the structure login's password",
            self.structure.password().to_owned(),
        ));
        markers
    }
}

/// Builds the fixture on `db` with these statements, then [`SEED`] and
/// [`GRANTS`], and makes a structure login that may connect to it and do
/// nothing else.
pub fn build_stock(db: &SharedDatabase, statements: &[&str]) -> Login {
    let superuser = db.superuser();
    for statement in statements {
        superuser.batch(statement);
    }
    superuser.batch(SEED);
    superuser.batch(
        &GRANTS
            .replace("%READER%", &db.reader.role)
            .replace("%WRITER%", &db.writer.role),
    );
    structure_login(db)
}

/// A new login that may connect to `db` and do nothing else there.
pub fn structure_login(db: &SharedDatabase) -> Login {
    let t = token();
    let login = Login::new(
        &format!("structure_role_{t}"),
        &format!("pw-structure-{t}{}", token()),
    );
    db.superuser().batch(&format!(
        "CREATE ROLE {} LOGIN PASSWORD '{}'; GRANT CONNECT ON DATABASE {} TO {};",
        login.role,
        login.password(),
        db.name(),
        login.role
    ));
    login
}

/// The body that registers `name` over `db` with its read and write logins
/// and this structure login.
pub fn body_with_structure(name: &str, db: &SharedDatabase, structure: &Login) -> Value {
    let mut body = resource_body(name, db, &db.reader);
    body["connection"]["write"] =
        json!({ "role": db.writer.role, "password": db.writer.password() });
    body["connection"]["structure"] =
        json!({ "role": structure.role, "password": structure.password() });
    body
}

/// `GET /v1/resources/<name>/structure`.
pub fn pull(api: &Api<'_>, name: &str) -> Response {
    api.request(&format!("/v1/resources/{name}/structure"))
        .timeout(PULL_TIMEOUT)
        .send()
}

/// Fails unless `fingerprint` is `sha256:` and 64 lower-case hex digits.
pub fn assert_fingerprint(fingerprint: &Value, context: &str) {
    let text = fingerprint.as_str().unwrap_or_default();
    let hex = text.strip_prefix("sha256:").unwrap_or_default();
    assert!(
        hex.len() == 64
            && hex
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
        "{context}: expected a fingerprint `sha256:` and 64 hex digits, got {fingerprint}"
    );
}

/// The second line a definition begins with.
pub fn second_line(resource: &str, fingerprint: &str) -> String {
    format!("// Resource: {resource}  Fingerprint: {fingerprint}")
}

/// The definition with its second line (which names the Resource) left
/// out: what must be the same, byte for byte, for the same structure
/// pulled under another name.
pub fn without_second_line(schema_ts: &str) -> String {
    let mut lines = schema_ts.split_inclusive('\n');
    let first = lines.next().unwrap_or_default();
    let _second = lines.next();
    let rest: String = lines.collect();
    format!("{first}{rest}")
}

/// The generated link of CONTRACT.md's "A project", with this name, with or
/// without the `relations` lines.
pub fn link(name: &str, relations: bool) -> String {
    if relations {
        format!(
            "// Generated. Do not edit.\nimport type * as schema from \"./schema.ts\";\nimport type * as relations from \"./relations.ts\";\n\ndeclare module \"@vm/sdk\" {{\n  interface SharedStructures {{\n    \"{name}\": typeof schema & typeof relations;\n  }}\n}}\n"
        )
    } else {
        format!(
            "// Generated. Do not edit.\nimport type * as schema from \"./schema.ts\";\n\ndeclare module \"@vm/sdk\" {{\n  interface SharedStructures {{\n    \"{name}\": typeof schema;\n  }}\n}}\n"
        )
    }
}

/// Whether `name` is a TypeScript identifier that is no reserved word.
pub fn is_identifier(name: &str) -> bool {
    const RESERVED: [&str; 46] = [
        "break",
        "case",
        "catch",
        "class",
        "const",
        "continue",
        "debugger",
        "default",
        "delete",
        "do",
        "else",
        "enum",
        "export",
        "extends",
        "false",
        "finally",
        "for",
        "function",
        "if",
        "import",
        "in",
        "instanceof",
        "new",
        "null",
        "return",
        "super",
        "switch",
        "this",
        "throw",
        "true",
        "try",
        "typeof",
        "var",
        "void",
        "while",
        "with",
        "implements",
        "interface",
        "let",
        "package",
        "private",
        "protected",
        "public",
        "static",
        "yield",
        "await",
    ];
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
        && !RESERVED.contains(&name)
}

/// The name exported for the table, view or enum whose definition line
/// holds `call` (`pgTable("sites"`, say): the `X` of the line's `export
/// const X =`.
pub fn export_of(schema_ts: &str, call: &str) -> Option<String> {
    schema_ts
        .lines()
        .find(|l| l.contains(call) && l.trim_start().starts_with("export const "))
        .and_then(|l| {
            let rest = l.trim_start().strip_prefix("export const ")?;
            let name = rest.split([' ', '=', ':']).next()?;
            Some(name.to_owned())
        })
}

/// The key of the column whose real name is `column`, in the block of the
/// table exported as `export`: the text before `:` on the first line of
/// that block that holds `("<column>"`.
pub fn key_of(schema_ts: &str, export: &str, column: &str) -> Option<String> {
    let start = schema_ts.find(&format!("export const {export} "))?;
    let block = schema_ts.get(start..)?;
    let end = block
        .get(1..)
        .and_then(|b| b.find("\nexport const "))
        .map_or(block.len(), |e| e + 1);
    let block = block.get(..end)?;
    let needle = format!("(\"{column}\"");
    block
        .lines()
        .find(|l| l.contains(&needle))
        .and_then(|l| l.split(':').next())
        .map(|k| k.trim().trim_matches('"').to_owned())
}

/// Copies the fixture project `fixtures/sdk/<name>` into a new
/// [`TempProject`] (under the repository's `target/`, so that `@vm/sdk` and
/// `drizzle-orm` resolve from the root's `node_modules`).
pub fn copy_project(name: &str) -> TempProject {
    let project = TempProject::new(name);
    copy_dir(&crate::sdk::fixture_project(name), &project.dir);
    project
}

fn copy_dir(from: &Path, to: &Path) {
    fs::create_dir_all(to).unwrap_or_else(|e| panic!("cannot make {}: {e}", to.display()));
    for entry in
        fs::read_dir(from).unwrap_or_else(|e| panic!("cannot read {}: {e}", from.display()))
    {
        let entry = entry.unwrap_or_else(|e| panic!("cannot read {}: {e}", from.display()));
        let path = entry.path();
        let target = to.join(entry.file_name());
        if path.is_dir() {
            copy_dir(&path, &target);
        } else {
            fs::copy(&path, &target).unwrap_or_else(|e| {
                panic!(
                    "cannot copy {} to {}: {e}",
                    path.display(),
                    target.display()
                )
            });
        }
    }
}

