/// The version of the SDK in the repository (`sdk/package.json`): the one
/// the program carries.
pub fn sdk_version() -> String {
    let text = fs::read_to_string(repository_root().join("sdk/package.json"))
        .unwrap_or_else(|e| panic!("cannot read sdk/package.json: {e}"));
    let package: Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("sdk/package.json is not JSON: {e}"));
    package["version"]
        .as_str()
        .unwrap_or_else(|| panic!("sdk/package.json has no version"))
        .to_owned()
}

/// The path of the SDK's tarball in a project, relative to it.
pub fn tarball_path(version: &str) -> String {
    format!("{PACKAGES}/vm-sdk-{version}.tgz")
}

/// Every file a new project holds, by path relative to it, sorted.
pub fn template_files() -> Vec<String> {
    let mut files: Vec<String> = TEMPLATE_FILES.iter().map(|f| (*f).to_owned()).collect();
    files.push(tarball_path(&sdk_version()));
    files.sort();
    files
}

/// `vm new <name> [--directory <dir>] --json`.
pub fn new_args<'a>(name: &'a str, directory: Option<&'a str>) -> Vec<&'a str> {
    let mut args = vec!["new", name];
    if let Some(dir) = directory {
        args.push("--directory");
        args.push(dir);
    }
    args.push("--json");
    args
}

/// `vm new <name> --directory <dir> --json` on this machine, which must end
/// with `0`; returns what it printed.
pub fn new_project(machine: &Machine, name: &str, dir: &Path) -> Value {
    let dir = dir.to_str().unwrap_or_else(|| panic!("not UTF-8: {dir:?}"));
    machine.run(&new_args(name, Some(dir))).ok_json()
}

/// A new project made by `vm new <name>` in a directory under the
/// repository's `target/` (so that its packages resolve from the root's
/// `node_modules`, as if installed). Fails the test unless `vm new` ends
/// with `0`.
pub fn new_project_in_repository(machine: &Machine, name: &str) -> TempProject {
    let project = TempProject::new(&format!("new-{name}"));
    new_project(machine, name, &project.dir);
    project
}

