/// A `src/db/schema.ts` with no table that, when it is run (as
/// `drizzle-kit` runs a schema to read it), appends its process id to
/// `pids`, starts a child of its own (`sleep 1000`, its output nowhere)
/// and appends that one's id too, and then, when `hang` is true, never
/// finishes (it waits on itself, using no CPU). Without `hang` it lets the
/// child run on and finishes. It type-checks: it names Node's own modules
/// only through `globalThis`.
pub fn schema_starting_a_child(pids: &Path, hang: bool) -> String {
    let file = serde_json::to_string(&pids.to_string_lossy())
        .unwrap_or_else(|e| panic!("cannot quote {}: {e}", pids.display()));
    let end = if hang {
        "// Never finishes.\nAtomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0);\n"
    } else {
        "child.unref();\n"
    };
    format!(
        "// The own database: no table. Run, it starts a process of its own.\nconst host = (globalThis as any).process;\nconst fs = host.getBuiltinModule(\"node:fs\");\nconst cp = host.getBuiltinModule(\"node:child_process\");\nfs.appendFileSync({file}, `${{host.pid}}\\n`);\nconst child = cp.spawn(\"sleep\", [\"1000\"], {{ stdio: \"ignore\" }});\nfs.appendFileSync({file}, `${{child.pid}}\\n`);\n{end}export {{}};\n"
    )
}

/// A module with `n` type errors, one a line: `export const n<i>: number =
/// "<i>";`, each at column 14.
pub fn type_errors(n: usize) -> String {
    (1..=n)
        .map(|i| format!("export const n{i}: number = \"{i}\";\n"))
        .collect()
}

/// The name of [`checked_project`]'s Application.
pub const CHECKED: &str = "checked";

/// A project as a new one stands, written by the harness (not by `vm
/// new`): `manifest.ts` (name [`CHECKED`], no Resource), `src/index.ts`,
/// `src/db/schema.ts` with no table, `migrations/.gitkeep` and
/// `tsconfig.json`, under the repository's `target/`.
pub fn checked_project(label: &str) -> TempProject {
    let project = TempProject::new(label);
    write_checked(&project.dir);
    project
}

/// Writes the files of [`checked_project`] into `dir`, wherever it is.
pub fn write_checked(dir: &Path) {
    for (relative, text) in [
        ("manifest.ts", manifest_ts(CHECKED, "{}")),
        ("src/index.ts", INDEX_TS.to_owned()),
        ("src/db/schema.ts", EMPTY_SCHEMA_TS.to_owned()),
        ("migrations/.gitkeep", String::new()),
        ("tsconfig.json", TSCONFIG.to_owned()),
    ] {
        let path = dir.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .unwrap_or_else(|e| panic!("cannot make {}: {e}", parent.display()));
        }
        fs::write(&path, text).unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
    }
}

/// Writes `resources/<name>/schema.ts` and `index.ts` as `vm pull` would
/// (each beginning with its generated first line), with one table
/// `things`, by hand: for a Resource the Builder cannot pull.
pub fn pulled_by_hand(project: &TempProject, name: &str) {
    project
        .write(
            &format!("resources/{name}/schema.ts"),
            &format!(
                "{SCHEMA_FIRST_LINE}\n// Resource: {name}  Fingerprint: sha256:{}\nimport {{ integer, pgTable }} from \"drizzle-orm/pg-core\";\n\nexport const things = pgTable(\"things\", {{\n  id: integer(\"id\").primaryKey(),\n}});\n",
                "0".repeat(64)
            ),
        )
        .write(
            &format!("resources/{name}/index.ts"),
            &crate::structure::link(name, false),
        );
}

/// `drizzle-kit generate --dialect postgresql --schema src/db/schema.ts
/// --out migrations`, run in `dir` with the root's `drizzle-kit` (by the
/// `bin` of its `package.json`) and no terminal.
pub fn generate_migrations(dir: &Path) -> Tooled {
    let bin = repository_root().join("node_modules/drizzle-kit/bin.cjs");
    let args = [
        "generate",
        "--dialect",
        "postgresql",
        "--schema",
        "src/db/schema.ts",
        "--out",
        "migrations",
    ];
    let mut command = Command::new("node");
    command.current_dir(dir).arg(&bin).args(args);
    let text = format!(
        "(in {}) node {} {}",
        dir.display(),
        bin.display(),
        args.join(" ")
    );
    let finished = run_to_exit(command, crate::sdk::TOOLING_TIMEOUT)
        .unwrap_or_else(|problem| panic!("cannot run {text}: {problem}"));
    Tooled {
        code: finished.status.and_then(|s| s.code()),
        stdout: finished.stdout,
        stderr: finished.stderr,
        command: text,
    }
}

/// The `*.sql` files in `dir/migrations`, by name.
pub fn sql_files(dir: &Path) -> Vec<String> {
    let mut found: Vec<String> = fs::read_dir(dir.join("migrations"))
        .map(|entries| {
            entries
                .flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.ends_with(".sql"))
                .collect()
        })
        .unwrap_or_default();
    found.sort();
    found
}

/// `vm check --project <dir> --json`, and these arguments after.
