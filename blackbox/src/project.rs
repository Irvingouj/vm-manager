/// What `vm check --json` printed, its shape checked.
#[derive(Clone, Debug)]
pub struct Report {
    pub run: Run,
    pub body: Value,
}

impl Report {
    /// Fails unless the check passed: exit code `0`, `ok` true, no problem;
    /// warnings and notes may be there.
    pub fn passed(run: &Run) -> Self {
        let body = run.ok_json();
        let report = Self {
            run: run.clone(),
            body,
        };
        report.assert_shape();
        assert_eq!(
            report.body["ok"],
            Value::Bool(true),
            "expected `ok` true\n{}",
            run.describe()
        );
        assert!(
            report.problems().is_empty(),
            "expected no problem\n{}",
            run.describe()
        );
        assert!(
            report.body.get("error").is_none(),
            "expected no `error` when the check passes\n{}",
            run.describe()
        );
        report
    }

    /// Fails unless the check passed with no problem, no warning and no
    /// note.
    pub fn clean(run: &Run) -> Self {
        let report = Self::passed(run);
        assert!(
            report.warnings().is_empty() && report.notes().is_empty(),
            "expected no warning and no note\n{}",
            run.describe()
        );
        report
    }

    /// Fails unless the check failed: exit code `1`, `ok` false, at least
    /// one problem, and `error` with reason `check-failed` and a message
    /// that says how many problems there are.
    pub fn failed(run: &Run) -> Self {
        let message = run.json_error(1, "check-failed");
        let body = run.json();
        let report = Self {
            run: run.clone(),
            body,
        };
        report.assert_shape();
        assert_eq!(
            report.body["ok"],
            Value::Bool(false),
            "expected `ok` false\n{}",
            run.describe()
        );
        let count = report.problems().len();
        assert!(count > 0, "expected a problem\n{}", run.describe());
        assert!(
            holds_number(&message, count),
            "expected the error's message to say how many problems there are ({count}), got {message:?}"
        );
        report
    }

    /// Fails unless the object has `ok`, `problems`, `warnings` and `notes`
    /// (and `error` only when `ok` is false), each problem a `check`, a
    /// `reason` and a `message`, each warning and note a `reason` and a
    /// `message`.
    pub fn assert_shape(&self) {
        let describe = || self.run.describe();
        let object = self
            .body
            .as_object()
            .unwrap_or_else(|| panic!("expected an object\n{}", describe()));
        let mut keys: Vec<&str> = object.keys().map(String::as_str).collect();
        keys.sort_unstable();
        let ok = self.body["ok"]
            .as_bool()
            .unwrap_or_else(|| panic!("expected `ok` as a boolean\n{}", describe()));
        let want: &[&str] = if ok {
            &["notes", "ok", "problems", "warnings"]
        } else {
            &["error", "notes", "ok", "problems", "warnings"]
        };
        assert_eq!(keys, want, "the report's keys\n{}", describe());
        for list in ["problems", "warnings", "notes"] {
            let items = self.body[list]
                .as_array()
                .unwrap_or_else(|| panic!("expected `{list}` as an array\n{}", describe()));
            for item in items {
                for field in ["reason", "message"] {
                    assert!(
                        item[field].as_str().is_some_and(|s| !s.trim().is_empty()),
                        "expected each of `{list}` to have a `{field}`, got {item}\n{}",
                        describe()
                    );
                }
                if list == "problems" {
                    let check = item["check"].as_str().unwrap_or_default();
                    assert!(
                        CHECKS.contains(&check),
                        "expected each problem's `check` to be one of {CHECKS:?}, got {item}"
                    );
                }
            }
        }
    }

    fn list(&self, name: &str) -> Vec<Value> {
        self.body[name].as_array().cloned().unwrap_or_default()
    }

    pub fn problems(&self) -> Vec<Value> {
        self.list("problems")
    }

    pub fn warnings(&self) -> Vec<Value> {
        self.list("warnings")
    }

    pub fn notes(&self) -> Vec<Value> {
        self.list("notes")
    }

    /// The problems with this reason.
    pub fn problems_for(&self, reason: &str) -> Vec<Value> {
        self.problems()
            .into_iter()
            .filter(|p| p["reason"] == reason)
            .collect()
    }

    /// The one problem with this reason; fails unless there is exactly one,
    /// and unless its `check` is `check`.
    pub fn problem(&self, check: &str, reason: &str) -> Value {
        let found = self.problems_for(reason);
        assert!(
            found.len() == 1,
            "expected exactly one problem `{reason}`, got {}\n{}",
            found.len(),
            self.run.describe()
        );
        let problem = found.into_iter().next().unwrap_or_default();
        assert_eq!(
            problem["check"],
            Value::from(check),
            "expected the problem `{reason}` to be of the check `{check}`"
        );
        problem
    }

    /// The problems of this check.
    pub fn of_check(&self, check: &str) -> Vec<Value> {
        self.problems()
            .into_iter()
            .filter(|p| p["check"] == check)
            .collect()
    }

    /// The warnings with this reason.
    pub fn warnings_for(&self, reason: &str) -> Vec<Value> {
        self.warnings()
            .into_iter()
            .filter(|p| p["reason"] == reason)
            .collect()
    }

    /// The notes with this reason.
    pub fn notes_for(&self, reason: &str) -> Vec<Value> {
        self.notes()
            .into_iter()
            .filter(|p| p["reason"] == reason)
            .collect()
    }

    /// The `check-failed` error's message.
    pub fn error_message(&self) -> String {
        self.body["error"]["message"]
            .as_str()
            .unwrap_or_default()
            .to_owned()
    }
}

/// Whether `text` holds `n` as a number standing alone.
pub fn holds_number(text: &str, n: usize) -> bool {
    text.split(|c: char| !c.is_ascii_digit())
        .any(|word| word == n.to_string())
}

/// One entry of a [`Tree`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Entry {
    Folder {
        modified: SystemTime,
    },
    File {
        bytes: Vec<u8>,
        modified: SystemTime,
    },
    Link {
        target: PathBuf,
    },
}

/// Every file, folder and link under a directory, by path relative to it,
/// with every file's bytes and every file's and folder's modification time.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Tree(pub BTreeMap<String, Entry>);

impl Tree {
    pub fn of(dir: &Path) -> Self {
        Self::of_skipping(dir, &[])
    }

    /// As [`Tree::of`], without what is inside these folders of `dir`
    /// (`node_modules`, say): each is there with its modification time
    /// only.
    pub fn of_skipping(dir: &Path, skip: &[&str]) -> Self {
        let mut entries = BTreeMap::new();
        walk(dir, dir, skip, &mut entries);
        Self(entries)
    }

    /// The paths, folders with a `/` after.
    pub fn paths(&self) -> Vec<String> {
        self.0
            .iter()
            .map(|(path, entry)| match entry {
                Entry::Folder { .. } => format!("{path}/"),
                _ => path.clone(),
            })
            .collect()
    }

    /// The files' paths (not folders, not links).
    pub fn files(&self) -> Vec<String> {
        self.0
            .iter()
            .filter(|(_, e)| matches!(e, Entry::File { .. }))
            .map(|(p, _)| p.clone())
            .collect()
    }

    /// What differs from `other`, one line each.
    pub fn differences(&self, other: &Self) -> Vec<String> {
        let mut found = Vec::new();
        for (path, entry) in &self.0 {
            match other.0.get(path) {
                None => found.push(format!("{path}: gone")),
                Some(theirs) if theirs != entry => found.push(format!(
                    "{path}: {} became {}",
                    describe_entry(entry),
                    describe_entry(theirs)
                )),
                Some(_) => {}
            }
        }
        for path in other.0.keys() {
            if !self.0.contains_key(path) {
                found.push(format!("{path}: new"));
            }
        }
        found
    }
}

fn describe_entry(entry: &Entry) -> String {
    match entry {
        Entry::Folder { modified } => format!("a folder modified at {modified:?}"),
        Entry::File { bytes, modified } => {
            format!("a file of {} bytes modified at {modified:?}", bytes.len())
        }
        Entry::Link { target } => format!("a link to {}", target.display()),
    }
}

fn walk(root: &Path, dir: &Path, skip: &[&str], entries: &mut BTreeMap<String, Entry>) {
    let Ok(listing) = fs::read_dir(dir) else {
        return;
    };
    for item in listing.flatten() {
        let path = item.path();
        let relative = path
            .strip_prefix(root)
            .map(|p| p.to_string_lossy().into_owned())
            .unwrap_or_default();
        let Ok(meta) = fs::symlink_metadata(&path) else {
            continue;
        };
        let modified = meta.modified().unwrap_or(SystemTime::UNIX_EPOCH);
        if meta.file_type().is_symlink() {
            let target = fs::read_link(&path).unwrap_or_default();
            entries.insert(relative, Entry::Link { target });
        } else if meta.is_dir() {
            let skipped = skip.contains(&relative.as_str());
            entries.insert(relative, Entry::Folder { modified });
            if !skipped {
                walk(root, &path, skip, entries);
            }
        } else {
            let bytes = fs::read(&path).unwrap_or_default();
            entries.insert(relative, Entry::File { bytes, modified });
        }
    }
}

/// Whether the process `pid` is running: `/proc/<pid>` is there and the
/// process is not a zombie (one that has ended and not yet been reaped).
pub fn is_running(pid: u32) -> bool {
    let Ok(stat) = fs::read_to_string(format!("/proc/{pid}/stat")) else {
        return false;
    };
    // `pid (comm) state ...`: the state follows the last `)`.
    let state = stat
        .rsplit_once(')')
        .and_then(|(_, rest)| rest.split_whitespace().next())
        .unwrap_or("X");
    !matches!(state, "Z" | "X" | "x")
}

/// Those of `pids` still running after waiting up to `grace` for them to
/// end.
pub fn still_running_after(pids: &[u32], grace: Duration) -> Vec<u32> {
    let deadline = Instant::now() + grace;
    loop {
        let running: Vec<u32> = pids.iter().copied().filter(|p| is_running(*p)).collect();
        if running.is_empty() || Instant::now() >= deadline {
            return running;
        }
        std::thread::sleep(Duration::from_millis(20));
    }
}

/// The process ids written one a line in `file`; none when it is not there.
pub fn pids_in(file: &Path) -> Vec<u32> {
    fs::read_to_string(file)
        .unwrap_or_default()
        .lines()
        .filter_map(|l| l.trim().parse().ok())
        .collect()
}

/// Kills these processes (`kill -KILL`, by id), for a test's own clean-up
/// of what the program should have stopped.
pub fn kill_all(pids: &[u32]) {
    for pid in pids {
        if is_running(*pid) {
            let mut command = Command::new("kill");
            command.arg("-KILL").arg(pid.to_string());
            drop(run_to_exit(command, Duration::from_secs(5)));
        }
    }
}

/// Kills, when dropped, every process whose id is written in `file`.
pub struct KillOnDrop(pub PathBuf);

impl Drop for KillOnDrop {
    fn drop(&mut self) {
        kill_all(&pids_in(&self.0));
    }
}

/// The members of the gzip'd tar `file`, as `tar -tzf` lists them, or the
/// error `tar` gave.
pub fn tar_list(file: &Path) -> Result<Vec<String>, String> {
    let mut command = Command::new("tar");
    command.arg("-tzf").arg(file);
    let finished = run_to_exit(command, Duration::from_secs(30))?;
    if finished.status.is_some_and(|s| s.success()) {
        Ok(finished.stdout.lines().map(str::to_owned).collect())
    } else {
        Err(format!(
            "tar -tzf {} ended {}: {}",
            file.display(),
            finished.status_text(),
            finished.stderr
        ))
    }
}

/// One member of the gzip'd tar `file`, as text (`tar -xzOf`).
pub fn tar_member(file: &Path, member: &str) -> Result<String, String> {
    let mut command = Command::new("tar");
    command.arg("-xzOf").arg(file).arg(member);
    let finished = run_to_exit(command, Duration::from_secs(30))?;
    if finished.status.is_some_and(|s| s.success()) {
        Ok(finished.stdout)
    } else {
        Err(format!(
            "tar -xzOf {} {member} ended {}: {}",
            file.display(),
            finished.status_text(),
            finished.stderr
        ))
    }
}

/// A folder `dir` holding these programs, each a `/bin/sh` script with this
/// body, executable: to be the whole of a `PATH`.
pub fn stand_ins(dir: &Path, programs: &[(&str, &str)]) -> PathBuf {
    fs::create_dir_all(dir).unwrap_or_else(|e| panic!("cannot make {}: {e}", dir.display()));
    for (name, body) in programs {
        let path = dir.join(name);
        fs::write(&path, format!("#!/bin/sh\n{body}\n"))
            .unwrap_or_else(|e| panic!("cannot write {}: {e}", path.display()));
        fs::set_permissions(&path, fs::Permissions::from_mode(0o755))
            .unwrap_or_else(|e| panic!("cannot make {} executable: {e}", path.display()));
    }
    dir.to_path_buf()
}

