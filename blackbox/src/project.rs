//! What the tests of "The project template, and creating and checking a
//! project" share (CONTRACT.md, "A project: the template, creating one and
//! checking one"):
//!
//! - `vm new` run on a [`Machine`] ([`new_args`], [`new_project`]) and the
//!   files a new project holds ([`template_files`]);
//! - a small project written by the harness itself ([`checked_project`]),
//!   under the repository's `target/` so that `@vm/sdk`, `typescript`,
//!   `drizzle-orm` and `drizzle-kit` resolve from the root `node_modules`
//!   as Node resolves them: the tests of `vm check` stand on it rather than
//!   on `vm new`, so that each says something of the check alone;
//! - files that look pulled ([`pulled_by_hand`]), migrations generated with
//!   the root's `drizzle-kit` exactly as the contract's command line says
//!   ([`generate_migrations`]);
//! - `vm check` run and its report read ([`check_args`], [`Report`]);
//! - a whole tree with every file's bytes and modification time and every
//!   folder's ([`Tree`]), to say that nothing was written;
//! - whether a process is running ([`is_running`]), from `/proc`;
//! - a gzip'd tar listed and read by the system's `tar` ([`tar_list`],
//!   [`tar_member`]);
//! - a folder of stand-in programs to put on a `PATH` ([`stand_ins`]);
//! - the versions the root lock file holds ([`lock_version`]), the commands
//!   `vm --help` lists ([`help_commands`]), the `vm <command>`s a Markdown
//!   text names in code ([`vm_commands_in`]), and HTML text decoded
//!   ([`html_text`]).

