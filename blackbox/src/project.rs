/// The version of `node_modules/<package>` in the root's
/// `package-lock.json`.
pub fn lock_version(package: &str) -> String {
    let text = fs::read_to_string(repository_root().join("package-lock.json"))
        .unwrap_or_else(|e| panic!("cannot read package-lock.json: {e}"));
    let lock: Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("package-lock.json: {e}"));
    lock["packages"][format!("node_modules/{package}")]["version"]
        .as_str()
        .unwrap_or_else(|| panic!("no node_modules/{package} in the root's package-lock.json"))
        .to_owned()
}

/// The commands `vm --help` lists: the first word of each line of its
/// `Commands:` section.
pub fn help_commands(help: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut inside = false;
    for line in help.lines() {
        if line.trim_end() == "Commands:" {
            inside = true;
            continue;
        }
        if inside {
            if line.trim().is_empty() || !line.starts_with(' ') {
                break;
            }
            if let Some(word) = line.split_whitespace().next() {
                found.push(word.to_owned());
            }
        }
    }
    found
}

/// The texts in code of a Markdown text: each inline code span and each
/// fenced block.
pub fn code_in(markdown: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut fenced: Option<String> = None;
    for line in markdown.lines() {
        if line.trim_start().starts_with("```") {
            match fenced.take() {
                Some(block) => found.push(block),
                None => fenced = Some(String::new()),
            }
            continue;
        }
        if let Some(block) = fenced.as_mut() {
            block.push_str(line);
            block.push('\n');
            continue;
        }
        // Inside a span are the pieces at odd places; a last one after an
        // unclosed backtick is not code.
        let pieces: Vec<&str> = line.split('`').collect();
        let closed = if pieces.len().is_multiple_of(2) {
            pieces.len().saturating_sub(1)
        } else {
            pieces.len()
        };
        for (place, code) in pieces.iter().enumerate().take(closed) {
            if place % 2 == 1 {
                found.push((*code).to_owned());
            }
        }
    }
    found
}

/// The `<command>` of each `vm <command>` in code in a Markdown text.
pub fn vm_commands_in(markdown: &str) -> Vec<String> {
    let mut found = Vec::new();
    for code in code_in(markdown) {
        let words: Vec<&str> = code.split_whitespace().collect();
        for pair in words.windows(2) {
            if let [first, second] = pair
                && *first == "vm"
            {
                let command: String = second
                    .chars()
                    .take_while(|c| c.is_ascii_lowercase() || *c == '-')
                    .collect();
                if !command.is_empty() {
                    found.push(command);
                }
            }
        }
    }
    found
}

/// The text's paragraphs: runs of lines between blank lines.
pub fn paragraphs(text: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut current = String::new();
    for line in text.lines() {
        if line.trim().is_empty() {
            if !current.is_empty() {
                found.push(std::mem::take(&mut current));
            }
        } else {
            current.push_str(line);
            current.push('\n');
        }
    }
    if !current.is_empty() {
        found.push(current);
    }
    found
}

/// The text with every run of white space (line ends included) made one
/// space: words wrapped across lines read as written.
pub fn squashed(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// HTML text decoded: `&lt;`, `&gt;`, `&amp;`, `&quot;`, `&apos;` and
/// numeric references made the characters they stand for.
pub fn html_text(html: &str) -> String {
    let mut out = String::new();
    let mut rest = html;
    while let Some(at) = rest.find('&') {
        out.push_str(rest.get(..at).unwrap_or_default());
        let after = rest.get(at..).unwrap_or_default();
        let Some(end) = after.find(';').filter(|e| *e <= 10) else {
            out.push('&');
            rest = after.get(1..).unwrap_or_default();
            continue;
        };
        let name = after.get(1..end).unwrap_or_default();
        let decoded = match name {
            "lt" => Some('<'),
            "gt" => Some('>'),
            "amp" => Some('&'),
            "quot" => Some('"'),
            "apos" => Some('\''),
            _ => name
                .strip_prefix("#x")
                .or_else(|| name.strip_prefix("#X"))
                .and_then(|hex| u32::from_str_radix(hex, 16).ok())
                .or_else(|| name.strip_prefix('#').and_then(|d| d.parse().ok()))
                .and_then(char::from_u32),
        };
        match decoded {
            Some(c) => {
                out.push(c);
                rest = after.get(end + 1..).unwrap_or_default();
            }
            None => {
                out.push('&');
                rest = after.get(1..).unwrap_or_default();
            }
        }
    }
    out.push_str(rest);
    out
}

/// The code points written `\u{<hex>}` in a text.
pub fn escapes_in(text: &str) -> Vec<u32> {
    text.split("\\u{")
        .skip(1)
        .filter_map(|rest| {
            let hex: String = rest.chars().take_while(char::is_ascii_hexdigit).collect();
            u32::from_str_radix(&hex, 16).ok()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn html_text_is_decoded() {
        assert_eq!(html_text("&lt;b&gt;a&amp;b&lt;/b&gt;"), "<b>a&b</b>");
        assert_eq!(html_text("&#60;&#x3c;&#X3C;&quot;&#39;"), "<<<\"'");
        assert_eq!(html_text("a & b; c"), "a & b; c");
        assert_eq!(html_text("&unknown;"), "&unknown;");
    }

    #[test]
    fn commands_in_code_are_found_and_prose_is_not() {
        let text = "Run `vm check` first.\n\nThe vm program, and `vm pull <name>`.\n\n```\nvm resources --json\nnpm install\n```\nSee vm.dev.json and `vm.dev.json`.\n";
        assert_eq!(vm_commands_in(text), ["check", "pull", "resources"]);
    }

    #[test]
    fn the_commands_of_the_help_are_read() {
        let help = "Usage: vm [COMMAND]\n\nCommands:\n  serve   Serve\n  sign-in  Sign in\n  help  Print\n\nOptions:\n  -h\n";
        assert_eq!(help_commands(help), ["serve", "sign-in", "help"]);
    }

    #[test]
    fn paragraphs_and_squashing() {
        let text = "one\ntwo\n\n\nthree\n";
        assert_eq!(paragraphs(text), ["one\ntwo\n", "three\n"]);
        assert_eq!(squashed("a\n  b\tc"), "a b c");
        assert!(holds_number("3 problems", 3));
        assert!(!holds_number("13 problems", 3));
    }
}
