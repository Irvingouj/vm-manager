//! A sealed value belongs to its row (CONTRACT.md, "Resources and Grants in
//! full: What is sealed, and under which key"): copied to another Resource's
//! row, or left in a row whose name or id is not the one it was sealed for, it
//! does not open; an own database's passwords copied to another Application's
//! row do not open there. Someone with write access to the platform database
//! cannot make one Resource reach another's database by moving what is
//! stored.
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    reason = "test code: a failed expectation is a failing test"
)]

use std::time::Duration;

use blackbox::VmOptions;
use blackbox::own_database::{first_tables, own_query};
use blackbox::scenario::{assert_error_kind, op, resource_body, sql_on};
use blackbox::sealed::{DEVOPS, SHOP, Sealed, Stored, rita};
use blackbox::shared_database::SharedDatabase;
use serde_json::{Value, json};

const LEDGER: &str = "ledger";
const LEDGER_BOARD: &str = "ledgerboard";

fn records(s: &Sealed, event: &str, field: &str, name: &str) -> Vec<Value> {
    s.logged(event)
        .into_iter()
        .filter(|r| r[field] == name)
        .collect()
}

/// DEVOPS over the program's shared database and LEDGER over another, each
/// read through its own Application.
fn two_resources() -> (Sealed, SharedDatabase) {
    let s = Sealed::start(&VmOptions::new());
    s.with_board();
    let other = SharedDatabase::create();
    s.register_body(LEDGER, &resource_body(LEDGER, &other, &other.reader));
    s.grant_read(LEDGER);
    s.install(LEDGER_BOARD, &[(LEDGER, "read")], &[]);
    (s, other)
}

fn read_ledger(s: &Sealed) -> Value {
    s.call(
        &rita(),
        LEDGER_BOARD,
        &op("query", &sql_on(LEDGER, "SELECT 1 AS one")),
    )
    .1
}

#[test]
fn a_value_copied_to_another_resource_s_row_does_not_open_there_and_reaches_no_database() {
    let (s, other) = two_resources();
    assert_eq!(
        read_ledger(&s)["ok"]["rows"],
        json!([[1]]),
        "the harness's own check: the second Resource is served before the copy"
    );
    Stored::of(s.platform()).copy_connection(DEVOPS, LEDGER);
    let s = s.restarted();
    let said = records(&s, "resource-unusable", "resource", LEDGER);
    assert_eq!(
        said.len(),
        1,
        "expected {LEDGER:?} not to open, got {said:?}"
    );
    assert_eq!(said[0]["problem"], "does-not-open", "{}", said[0]);
    assert_eq!(
        records(&s, "resource-unusable", "resource", DEVOPS),
        Vec::<Value>::new(),
        "expected {DEVOPS:?} to be served"
    );
    assert_eq!(s.read_devops().1["ok"]["rows"], json!([[1]]));
    std::thread::sleep(Duration::from_millis(500));
    let (first, second) = (s.db.server_log().len(), other.server_log().len());
    assert_error_kind(&read_ledger(&s), "unavailable", "a copied value");
    std::thread::sleep(Duration::from_millis(500));
    assert_eq!(
        s.db.server_log().len(),
        first,
        "expected the copied value not to reach the other Resource's database"
    );
    assert_eq!(
        other.server_log().len(),
        second,
        "expected nothing to reach the database the row names either"
    );
}

#[test]
fn a_value_left_in_a_row_whose_name_was_changed_does_not_open() {
    let s = Sealed::start(&VmOptions::new());
    s.with_board();
    let stored = Stored::of(s.platform());
    stored
        .admin()
        .batch("UPDATE resources SET name = 'moved' WHERE name = 'devops' RETURNING id");
    let s = s.restarted();
    let said = records(&s, "resource-unusable", "resource", "moved");
    assert_eq!(
        said.len(),
        1,
        "expected a Resource whose name is not the one its value was sealed for not to open, got {said:?}"
    );
    assert_eq!(said[0]["problem"], "does-not-open", "{}", said[0]);
}

#[test]
fn a_value_left_in_a_row_whose_id_was_changed_does_not_open() {
    let s = Sealed::start(&VmOptions::new());
    s.with_board();
    let stored = Stored::of(s.platform());
    stored.admin().batch(
        "ALTER TABLE resources ALTER COLUMN id SET GENERATED BY DEFAULT;
         SET session_replication_role = replica;
         UPDATE resources SET id = id + 1000 WHERE name = 'devops' RETURNING id",
    );
    let s = s.restarted();
    let said = records(&s, "resource-unusable", "resource", DEVOPS);
    assert_eq!(
        said.len(),
        1,
        "expected a Resource whose id is not the one its value was sealed for not to open, got {said:?}"
    );
    assert_eq!(said[0]["problem"], "does-not-open", "{}", said[0]);
}

#[test]
fn an_own_database_s_passwords_copied_to_another_application_s_row_do_not_open_there() {
    let s = Sealed::start(&VmOptions::new());
    s.with_shop(&[first_tables()]);
    s.install("shop2", &[], &[first_tables()]);
    assert_eq!(
        s.read_own("shop2").1["ok"]["rows"],
        json!([["seeded by 0000"]]),
        "the harness's own check: the second own database is served before the copy"
    );
    Stored::of(s.platform()).copy_own_passwords(SHOP, "shop2");
    let s = s.restarted();
    let said = records(&s, "own-database-unusable", "application", "shop2");
    assert_eq!(said.len(), 1, "expected shop2 not to open, got {said:?}");
    assert_eq!(said[0]["problem"], "does-not-open", "{}", said[0]);
    assert_eq!(
        records(&s, "own-database-unusable", "application", SHOP),
        Vec::<Value>::new(),
        "expected {SHOP:?} to be served"
    );
    assert_eq!(s.read_shop().1["ok"]["rows"], json!([["seeded by 0000"]]));
    // At its next use shop2 gets new passwords and keeps its data.
    let answer = s
        .call(
            &rita(),
            "shop2",
            &own_query("user", "SELECT label FROM seeded"),
        )
        .1;
    assert_eq!(
        answer["ok"]["rows"],
        json!([["seeded by 0000"]]),
        "{answer}"
    );
    let replaced = s.logged("own-database-passwords-replaced");
    assert_eq!(replaced.len(), 1, "{replaced:?}");
    assert_eq!(replaced[0]["application"], "shop2", "{}", replaced[0]);
    assert_eq!(replaced[0]["reason"], "does-not-open", "{}", replaced[0]);
}
