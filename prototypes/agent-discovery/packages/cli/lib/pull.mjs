// Pulling a shared database's structure as a read-only Drizzle definition.
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { PGlite } from "@electric-sql/pglite";
import { VmError, ownRequire, readJson } from "./util.mjs";
import { rank } from "./installation.mjs";

function drizzleKitBin() {
  return join(dirname(ownRequire.resolve("drizzle-kit/api")), "bin.cjs");
}

export function runDrizzleKit(args, { cwd, timeout = 60000 } = {}) {
  return spawnSync(process.execPath, [drizzleKitBin(), ...args], {
    cwd,
    encoding: "utf8",
    timeout,
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, FORCE_COLOR: "0", NO_COLOR: "1" },
  });
}

function clean(source, header) {
  let s = source
    .split("\n")
    .filter((l) => !/^\s*\/\/ (You can use \{ mode|TODO: failed to parse)/.test(l))
    .join("\n");
  const body = s.replace(/^import .*\n/gm, "");
  if (!/\bsql`/.test(body)) s = s.replace(/^import \{ sql \} from "drizzle-orm"\n/m, "");
  s = s.replace(/\n{3,}/g, "\n\n");
  return header + s.trimEnd() + "\n";
}

/** Asks the installation for a Resource's current structure. */
export async function fetchStructure(inst, name, cwd) {
  const r = inst.data.resources[name];
  const tmp = mkdtempSync(join(tmpdir(), "vm-pull-"));
  try {
    const pg = new PGlite(join(tmp, "db"));
    await pg.exec(inst.file(r.structure));
    await pg.close();
    const config = join(tmp, "pull.config.mjs");
    writeFileSync(
      config,
      `export default ${JSON.stringify({ dialect: "postgresql", driver: "pglite", out: join(tmp, "out"), dbCredentials: { url: join(tmp, "db") } })};\n`,
    );
    const res = runDrizzleKit(["pull", "--config", config], { cwd });
    if (res.status !== 0 || !existsSync(join(tmp, "out", "schema.ts"))) {
      throw new VmError(`The structure of '${name}' could not be pulled. Try again; if it keeps failing, tell the Platform administrators.\n${res.stderr || res.stdout}`);
    }
    const header = `// Structure of the shared database '${name}', pulled from ${inst.url}.\n// Generated by \`vm resources pull ${name}\`. Read-only: do not edit; pull again to update.\n\n`;
    const schema = clean(readFileSync(join(tmp, "out", "schema.ts"), "utf8"), header);
    const relations = clean(readFileSync(join(tmp, "out", "relations.ts"), "utf8"), header);
    const tables = [...schema.matchAll(/export const (\w+) = pgTable\("([^"]+)"/g)].map((m) => m[2]);
    const fingerprint = createHash("sha256").update(schema).update(relations).digest("hex").slice(0, 16);
    return { schema, relations, tables, fingerprint };
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

export function checkCanPull(inst, name) {
  const r = inst.resource(name);
  if (!r) {
    throw new VmError(`There is no Resource named '${name}'. Run \`npx vm resources list\` to see every registered Resource.`, {
      code: "not-registered",
    });
  }
  if (rank(r.access) < rank("structure")) {
    const me = inst.me();
    throw new VmError(
      [
        `Refused: you (${me.id}) hold no Grant on '${name}', so its structure cannot be pulled.`,
        `Access is given by adding you to a Group that holds a Grant on '${name}'. Only a person can arrange that; it cannot be worked around from code.`,
        `Ask: ${r.ask}`,
        `Tell the Builder this, and do not build against '${name}' until the pull succeeds.`,
      ].join("\n"),
      { code: "no-grant", exit: 2, details: { resource: name, held: null, ask: r.ask } },
    );
  }
  return r;
}

export function writePulled(root, inst, name, pulled) {
  const dir = join(root, "resources", name);
  mkdirSync(dir, { recursive: true });
  const before = existsSync(join(dir, "schema.ts")) ? readFileSync(join(dir, "schema.ts"), "utf8") + readFileSync(join(dir, "relations.ts"), "utf8") : null;
  writeFileSync(join(dir, "schema.ts"), pulled.schema);
  writeFileSync(join(dir, "relations.ts"), pulled.relations);
  writeFileSync(
    join(dir, "index.ts"),
    `// Generated by \`vm resources pull ${name}\`. Do not edit.
// Registers the structure of '${name}' with the SDK, so that ctx.user().db("${name}") is typed with it.
// fingerprint: ${pulled.fingerprint}
import type * as schema from "./schema.ts";
import type * as relations from "./relations.ts";

declare module "@vm/sdk" {
  interface SharedStructures {
    ${JSON.stringify(name)}: typeof schema & typeof relations;
  }
}
`,
  );
  return { changed: before !== null && before !== pulled.schema + pulled.relations, created: before === null };
}

/** Local stand-in files: sample rows and the local Grants for the Builder's own Groups. */
export function prepareLocal(root, inst, name) {
  const notes = [];
  const r = inst.data.resources[name];
  mkdirSync(join(root, "seed"), { recursive: true });
  const seed = join(root, "seed", `${name}.sql`);
  if (!existsSync(seed)) {
    const head = `-- Test rows for the local stand-in of '${name}', loaded by \`vm dev\`. Not real data: edit freely.\n`;
    const sample = r.sample ? inst.file(r.sample) : null;
    writeFileSync(seed, sample ? head + `-- Starting rows provided by the Resource owner (${r.owner}).\n\n` + sample : head + "-- Add INSERT statements here.\n");
    notes.push(`Wrote seed/${name}.sql (${sample ? "sample rows from the Resource owner" : "empty"}) for the local stand-in.`);
  }
  const devFile = join(root, "vm.dev.json");
  if (existsSync(devFile)) {
    const dev = readJson(devFile);
    dev.grants ??= [];
    const me = inst.me();
    for (const g of inst.data.grants) {
      if (g.resource !== name || !me.groups.includes(g.group)) continue;
      if (dev.grants.some((x) => x.group === g.group && x.resource === name)) continue;
      dev.grants.push({ group: g.group, resource: name, access: g.access });
      notes.push(`Added to vm.dev.json: Group ${g.group} holds ${g.access} on the local '${name}', as it does in the company.`);
    }
    writeFileSync(devFile, JSON.stringify(dev, null, 2) + "\n");
  }
  return notes;
}
