-- The platform's schema `vm` in an Application's own database
-- (blackbox/CONTRACT.md, "Identity and Change history in the own
-- database", and "The platform's part of an own database is out of a
-- migration's reach"; ADR 0017). Run by the platform's own role for the
-- database (`<p>_app_<n>_platform`), which owns the schema and everything
-- in it, in a transaction, whenever the own database is made or brought to
-- the present form (crate::own_db): every statement is idempotent, so an
-- own database made before any of this gets it whole, and one that has it
-- is left as it is. The grants to the runtime role and to the migration
-- role follow it (crate::own_db), since they name the roles.
--
-- Every function pins its search path to the catalog (then nothing: no
-- role of the Application can make a temporary object), and names the
-- platform's own objects with `vm.`, so that no name a migration or
-- Application SQL could make is found first. No function here reads a
-- table of the Application's, and none calls a function of the
-- Application's: the capture reads only its transition tables and the
-- catalog, and refuses to convert rows while a user-made cast to json
-- exists (Postgres would call it inside `to_jsonb`).
--
-- What the migration role may call is called by the host on the migration
-- role's own session, inside the migrations' transaction (only that
-- session sees its uncommitted catalog). A migration may call them as
-- well; it gains nothing by it: they report on the catalog, put the
-- platform's own capture on its tables, or read the names of migrations
-- already recorded, and recording one needs an identity only the host can
-- attach.

CREATE SCHEMA IF NOT EXISTS vm;
REVOKE ALL ON SCHEMA vm FROM PUBLIC;

-- Which migrations have been applied (ticket "An Application's own
-- database"). Written only by vm.record_migration().
CREATE TABLE IF NOT EXISTS vm.migrations (
    position integer PRIMARY KEY,
    name text NOT NULL UNIQUE,
    sha256 text NOT NULL,
    sql text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
);

-- The platform's secret: two keys of 32 bytes, made here from the
-- server's strong random source (four version 4 UUIDs, 488 random bits,
-- through sha256), so that neither ever travels in a statement. One row,
-- made once. Only the platform's role reads it: the host, once per own
-- database and program run (a result, which Postgres does not log), and
-- the functions below.
CREATE TABLE IF NOT EXISTS vm.keys (
    one boolean PRIMARY KEY DEFAULT true CHECK (one),
    k1 bytea NOT NULL CHECK (length(k1) = 32),
    k2 bytea NOT NULL CHECK (length(k2) = 32)
);
INSERT INTO vm.keys (k1, k2)
SELECT pg_catalog.sha256(pg_catalog.convert_to(
           pg_catalog.gen_random_uuid()::text || pg_catalog.gen_random_uuid()::text
           || pg_catalog.gen_random_uuid()::text || pg_catalog.gen_random_uuid()::text, 'UTF8')),
       pg_catalog.sha256(pg_catalog.convert_to(
           pg_catalog.gen_random_uuid()::text || pg_catalog.gen_random_uuid()::text
           || pg_catalog.gen_random_uuid()::text || pg_catalog.gen_random_uuid()::text, 'UTF8'))
ON CONFLICT (one) DO NOTHING;

-- The outbox (ADR 0017, second slice; blackbox/CONTRACT.md, "The Change
-- history in the platform database"): every change the capture records, in
-- the transaction of the change, until the host has shipped it to the
-- platform database's `change_history` and deleted it here. Only the
-- platform's role reads or writes it. `id` is the change's id in
-- `change_history`. `json_nulls`: the `json` and `jsonb` columns of `old`
-- and `new` whose value was JSON `null`, not SQL null (`to_jsonb` of a row
-- writes both as `null`), as `{"old": [...], "new": [...]}`; null when
-- none. `structure`: what a change of structure changed (kind
-- `structure`, `vm.record_structure`).
--
-- An own database of the earlier form had the history itself here, as
-- `vm.history`: that table becomes the outbox, its rows and its identity
-- (so later ids are greater) kept, and is shipped like any outbox.
DO $do$
BEGIN
    IF pg_catalog.to_regclass('vm.history') IS NOT NULL
       AND pg_catalog.to_regclass('vm.outbox') IS NULL THEN
        ALTER TABLE vm.history RENAME TO outbox;
    END IF;
END
$do$;
CREATE TABLE IF NOT EXISTS vm.outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at timestamptz NOT NULL,
    schema_name text NOT NULL,
    table_name text NOT NULL,
    kind text NOT NULL,
    key jsonb,
    old jsonb,
    new jsonb,
    changed jsonb,
    user_id text NOT NULL,
    application text NOT NULL,
    actor text NOT NULL,
    request text,
    migration text,
    structure jsonb,
    json_nulls jsonb
);
-- `BY DEFAULT`, not `ALWAYS`: with `ALWAYS`, Postgres refuses an `INSERT`
-- that names `id` (`428C9`) before it asks whether the role may insert at
-- all, and the roles of the Application are to be refused for want of the
-- right (`42501`), whatever they send. Only the platform's role, which
-- names no `id`, writes here.
ALTER TABLE vm.outbox ALTER COLUMN id SET GENERATED BY DEFAULT,
                      ADD COLUMN IF NOT EXISTS structure jsonb,
                      ADD COLUMN IF NOT EXISTS json_nulls jsonb;
-- The earlier form's index for reading a row's history here: nothing
-- reads the outbox by key.
DROP INDEX IF EXISTS vm.history_row;

-- What makes the transaction it is called in different from every other:
-- the backend, the virtual transaction id (unique in the backend's slot
-- until the server restarts) and the transaction's start, in
-- microseconds since the epoch (so not printed by the session's time
-- zone). An attached identity is signed over it; the host also asks it
-- after every statement of a migration, so that a transaction ended and
-- begun again behind its back is seen.
CREATE OR REPLACE FUNCTION vm.transaction_key() RETURNS text
LANGUAGE sql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT pg_catalog.pg_backend_pid()::text
    || '/' || coalesce((SELECT l.virtualtransaction FROM pg_catalog.pg_locks l
                         WHERE l.locktype = 'virtualxid'
                           AND l.pid = pg_catalog.pg_backend_pid()
                           AND l.virtualxid = l.virtualtransaction
                         LIMIT 1), '-')
    || '/' || ((EXTRACT(epoch FROM pg_catalog.transaction_timestamp()) * 1000000)::bigint)::text
$f$;

-- The identity attached to this transaction, as the host wrote it: the
-- setting `vm.ctx` is 64 hex digits of a tag, then the identity as JSON;
-- the tag is sha256(k2 || sha256(k1 || 'vm.ctx v1' \n transaction key \n
-- identity)). Raises VM001 unless the tag is the one the keys give for
-- this transaction: nothing set, anything made up, anything set in
-- another transaction.
CREATE OR REPLACE FUNCTION vm.attached() RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_ctx text := pg_catalog.current_setting('vm.ctx', true);
    v_k1 bytea;
    v_k2 bytea;
    v_identity text;
BEGIN
    IF v_ctx IS NULL OR pg_catalog.length(v_ctx) <= 64 THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'no verifiable identity is attached to this transaction';
    END IF;
    SELECT k.k1, k.k2 INTO v_k1, v_k2 FROM vm.keys k;
    IF v_k1 IS NULL OR v_k2 IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'no verifiable identity is attached to this transaction';
    END IF;
    v_identity := pg_catalog.substr(v_ctx, 65);
    IF pg_catalog.encode(pg_catalog.sha256(v_k2 || pg_catalog.sha256(v_k1 || pg_catalog.convert_to(
           'vm.ctx v1' || pg_catalog.chr(10) || vm.transaction_key() || pg_catalog.chr(10) || v_identity,
           'UTF8'))), 'hex')
       IS DISTINCT FROM pg_catalog.substr(v_ctx, 1, 64) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'no verifiable identity is attached to this transaction';
    END IF;
    RETURN v_identity::jsonb;
END
$f$;

-- Who the transaction is for (blackbox/CONTRACT.md, "Identity").
CREATE OR REPLACE FUNCTION vm.identity()
RETURNS TABLE (user_id text, application text, actor text, request text)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_who jsonb := vm.attached();
BEGIN
    user_id := v_who ->> 'user_id';
    application := v_who ->> 'application';
    actor := v_who ->> 'actor';
    request := v_who ->> 'request';
    RETURN NEXT;
END
$f$;

-- Refuses (VM003) while a cast from a type of the Application's to json
-- or jsonb exists whose function is not written in C or internal (only a
-- superuser, or a trusted extension's script, makes those): `to_jsonb`
-- would call it inside the capture, with the platform's rights.
CREATE OR REPLACE FUNCTION vm.capture_guard() RETURNS void
LANGUAGE plpgsql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    IF EXISTS (SELECT FROM pg_catalog.pg_cast c
                 JOIN pg_catalog.pg_proc p ON p.oid = c.castfunc
                 JOIN pg_catalog.pg_language l ON l.oid = p.prolang
                WHERE c.casttarget IN ('pg_catalog.json'::pg_catalog.regtype,
                                       'pg_catalog.jsonb'::pg_catalog.regtype)
                  AND c.castsource >= 16384
                  AND l.lanname NOT IN ('c', 'internal')) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM003',
            MESSAGE = 'a cast to json or jsonb from a type of the Application''s exists: the Change history capture refuses to run it, so no captured table can be changed until the cast is dropped';
    END IF;
END
$f$;

-- The capture: an AFTER ... FOR EACH STATEMENT trigger for each of
-- insert, update and delete, with the statement's rows as transition
-- tables (`vm_new`, `vm_old`). The identity is verified once per
-- statement that changed rows; then one row per changed row is written to
-- the outbox, in the order the rows were changed. A statement that changed
-- no row records nothing and needs no identity. An update's old and new
-- rows are paired in the order Postgres put them into its two transition
-- tables, which is the order it updated them in, one old and one new each.
--
-- A row is turned into JSON whole, as `to_jsonb(vm_row.*)`: a column
-- named like the alias (`t`, `vm_row`, `vm_new`, `vm_old`) cannot stand
-- for it. The settings that change how values print are pinned, so what
-- is recorded does not depend on the writer's session.
--
-- `to_jsonb` writes a `json` or `jsonb` column holding JSON `null` as it
-- writes SQL null. For a table with such columns, which of them hold JSON
-- `null` in each row is found by a second scan of the same transition
-- table (in the same order: Postgres reads it as it was written), with
-- Postgres's own `json_typeof`/`jsonb_typeof`, and kept in `json_nulls`.
CREATE OR REPLACE FUNCTION vm.capture() RETURNS trigger
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
SET TimeZone = 'UTC'
SET extra_float_digits = 1
SET IntervalStyle = 'postgres'
SET DateStyle = 'ISO, YMD'
SET bytea_output = 'hex'
AS $f$
DECLARE
    v_who jsonb;
    v_at timestamptz;
    v_key text[];
    v_columns text[];
    v_tests text;
    v_old_nulls jsonb;
    v_new_nulls jsonb;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NOT EXISTS (SELECT FROM vm_new) THEN
            RETURN NULL;
        END IF;
    ELSIF NOT EXISTS (SELECT FROM vm_old) THEN
        RETURN NULL;
    END IF;
    v_who := vm.attached();
    PERFORM vm.capture_guard();
    v_at := pg_catalog.clock_timestamp();
    SELECT pg_catalog.array_agg(a.attname::text ORDER BY pg_catalog.array_position(i.indkey::int2[], a.attnum))
      INTO v_key
      FROM pg_catalog.pg_index i
      JOIN pg_catalog.pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY (i.indkey)
     WHERE i.indrelid = TG_RELID AND i.indisprimary;
    -- One test per json or jsonb column: (its name, whether it is JSON null).
    SELECT pg_catalog.string_agg(
               pg_catalog.format('(%L, pg_catalog.%s(vm_row.%I) OPERATOR(pg_catalog.=) %L)',
                                 a.attname,
                                 CASE WHEN a.atttypid = 'pg_catalog.json'::pg_catalog.regtype
                                      THEN 'json_typeof' ELSE 'jsonb_typeof' END,
                                 a.attname, 'null'),
               ', ' ORDER BY a.attnum)
      INTO v_tests
      FROM pg_catalog.pg_attribute a
     WHERE a.attrelid = TG_RELID AND a.attnum > 0 AND NOT a.attisdropped
       AND a.atttypid IN ('pg_catalog.json'::pg_catalog.regtype, 'pg_catalog.jsonb'::pg_catalog.regtype);
    IF v_tests IS NOT NULL THEN
        IF TG_OP IN ('INSERT', 'UPDATE') THEN
            EXECUTE 'SELECT pg_catalog.jsonb_agg(x.z ORDER BY x.i) FROM (SELECT pg_catalog.row_number() OVER () AS i, '
                    || 'ARRAY(SELECT v.c FROM (VALUES ' || v_tests || ') AS v(c, n) WHERE v.n) AS z '
                    || 'FROM vm_new vm_row) x'
               INTO v_new_nulls;
        END IF;
        IF TG_OP IN ('DELETE', 'UPDATE') THEN
            EXECUTE 'SELECT pg_catalog.jsonb_agg(x.z ORDER BY x.i) FROM (SELECT pg_catalog.row_number() OVER () AS i, '
                    || 'ARRAY(SELECT v.c FROM (VALUES ' || v_tests || ') AS v(c, n) WHERE v.n) AS z '
                    || 'FROM vm_old vm_row) x'
               INTO v_old_nulls;
        END IF;
    END IF;
    IF TG_OP = 'INSERT' THEN
        INSERT INTO vm.outbox (at, schema_name, table_name, kind, key, old, new, changed,
                               user_id, application, actor, request, migration, json_nulls)
        SELECT v_at, TG_TABLE_SCHEMA::text, TG_TABLE_NAME::text, 'insert',
               CASE WHEN v_key IS NULL THEN NULL
                    ELSE (SELECT pg_catalog.jsonb_object_agg(c, r.j -> c) FROM pg_catalog.unnest(v_key) c) END,
               NULL, r.j, NULL,
               v_who ->> 'user_id', v_who ->> 'application', v_who ->> 'actor',
               v_who ->> 'request', v_who ->> 'migration',
               vm.json_nulls(NULL, v_new_nulls -> (r.i - 1)::integer)
          FROM (SELECT pg_catalog.to_jsonb(vm_row.*) AS j, pg_catalog.row_number() OVER () AS i
                  FROM vm_new vm_row) r
         ORDER BY r.i;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO vm.outbox (at, schema_name, table_name, kind, key, old, new, changed,
                               user_id, application, actor, request, migration, json_nulls)
        SELECT v_at, TG_TABLE_SCHEMA::text, TG_TABLE_NAME::text, 'delete',
               CASE WHEN v_key IS NULL THEN NULL
                    ELSE (SELECT pg_catalog.jsonb_object_agg(c, r.j -> c) FROM pg_catalog.unnest(v_key) c) END,
               r.j, NULL, NULL,
               v_who ->> 'user_id', v_who ->> 'application', v_who ->> 'actor',
               v_who ->> 'request', v_who ->> 'migration',
               vm.json_nulls(v_old_nulls -> (r.i - 1)::integer, NULL)
          FROM (SELECT pg_catalog.to_jsonb(vm_row.*) AS j, pg_catalog.row_number() OVER () AS i
                  FROM vm_old vm_row) r
         ORDER BY r.i;
    ELSE
        SELECT pg_catalog.array_agg(a.attname::text ORDER BY a.attnum)
          INTO v_columns
          FROM pg_catalog.pg_attribute a
         WHERE a.attrelid = TG_RELID AND a.attnum > 0 AND NOT a.attisdropped;
        INSERT INTO vm.outbox (at, schema_name, table_name, kind, key, old, new, changed,
                               user_id, application, actor, request, migration, json_nulls)
        SELECT v_at, TG_TABLE_SCHEMA::text, TG_TABLE_NAME::text, 'update',
               CASE WHEN v_key IS NULL THEN NULL
                    ELSE (SELECT pg_catalog.jsonb_object_agg(c, o.j -> c) FROM pg_catalog.unnest(v_key) c) END,
               o.j, n.j,
               (SELECT coalesce(pg_catalog.jsonb_agg(u.c ORDER BY u.p), '[]'::jsonb)
                  FROM pg_catalog.unnest(v_columns) WITH ORDINALITY u(c, p)
                 WHERE (o.j -> u.c) IS DISTINCT FROM (n.j -> u.c)
                    OR (v_old_nulls -> (o.i - 1)::integer ? u.c)
                       IS DISTINCT FROM (v_new_nulls -> (o.i - 1)::integer ? u.c)),
               v_who ->> 'user_id', v_who ->> 'application', v_who ->> 'actor',
               v_who ->> 'request', v_who ->> 'migration',
               vm.json_nulls(v_old_nulls -> (o.i - 1)::integer, v_new_nulls -> (o.i - 1)::integer)
          FROM (SELECT pg_catalog.to_jsonb(vm_row.*) AS j, pg_catalog.row_number() OVER () AS i
                  FROM vm_old vm_row) o
          JOIN (SELECT pg_catalog.to_jsonb(vm_row.*) AS j, pg_catalog.row_number() OVER () AS i
                  FROM vm_new vm_row) n
            ON n.i = o.i
         ORDER BY o.i;
    END IF;
    RETURN NULL;
END
$f$;

-- `json_nulls` of one row of the outbox: from the names of the `json` and
-- `jsonb` columns holding JSON `null` in its old row and in its new row
-- (each a jsonb array, or null), `{"old": [...], "new": [...]}` with the
-- empty ones left out; null when both are.
CREATE OR REPLACE FUNCTION vm.json_nulls(p_old jsonb, p_new jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE PARALLEL SAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT NULLIF(
           pg_catalog.jsonb_strip_nulls(pg_catalog.jsonb_build_object(
               'old', NULLIF(p_old, '[]'::jsonb),
               'new', NULLIF(p_new, '[]'::jsonb))),
           '{}'::jsonb)
$f$;

-- The fourth capture trigger's function: TRUNCATE of a table with history
-- is refused, whoever runs it, also through CASCADE and through a
-- partition (each truncated table fires its own).
CREATE OR REPLACE FUNCTION vm.capture_truncate() RETURNS trigger
LANGUAGE plpgsql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    RAISE EXCEPTION USING ERRCODE = 'VM002',
        MESSAGE = pg_catalog.format(
            'TRUNCATE of %I.%I is refused: the rows it removes would leave no Change history. Use DELETE FROM %I.%I instead, which is recorded',
            TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_TABLE_SCHEMA, TG_TABLE_NAME);
END
$f$;

-- Puts the four capture triggers on every table, in any schema but the
-- platform's and the catalog's, that does not have them yet: partitioned
-- tables and partitions both, since a statement fires the statement
-- triggers of the table it names only. Runs with the platform's role's
-- rights, which may make triggers on the migration role's tables through
-- its inheriting membership; a table of another role's (a superuser made
-- it there) is left as it is, and `vm.capture_problems()` names it.
-- Called by the host after each migration, inside the migrations'
-- transaction, and when the capture is put back; answers how many
-- triggers it made.
CREATE OR REPLACE FUNCTION vm.capture_new_tables() RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_table record;
    v_made integer := 0;
BEGIN
    FOR v_table IN
        SELECT c.oid::pg_catalog.regclass AS relation, e.event, e.timing, e.referencing, e.fn
          FROM pg_catalog.pg_class c
          JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
         CROSS JOIN (VALUES ('insert', 'AFTER', 'REFERENCING NEW TABLE AS vm_new', 'vm.capture()'),
                            ('update', 'AFTER', 'REFERENCING OLD TABLE AS vm_old NEW TABLE AS vm_new', 'vm.capture()'),
                            ('delete', 'AFTER', 'REFERENCING OLD TABLE AS vm_old', 'vm.capture()'),
                            ('truncate', 'BEFORE', '', 'vm.capture_truncate()'))
               AS e(event, timing, referencing, fn)
         WHERE c.relkind IN ('r', 'p')
           AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
           AND pg_catalog.left(n.nspname, 3) <> 'pg_'
           AND pg_catalog.pg_has_role(c.relowner, 'USAGE')
           AND NOT EXISTS (SELECT FROM pg_catalog.pg_trigger t
                            WHERE t.tgrelid = c.oid AND t.tgname = 'vm_capture_' || e.event)
         ORDER BY c.oid, e.event
    LOOP
        EXECUTE pg_catalog.format(
            'CREATE TRIGGER %I %s %s ON %s %s FOR EACH STATEMENT EXECUTE FUNCTION %s',
            'vm_capture_' || v_table.event, v_table.timing, pg_catalog.upper(v_table.event),
            v_table.relation, v_table.referencing, v_table.fn);
        v_made := v_made + 1;
    END LOOP;
    RETURN v_made;
END
$f$;

-- Whether the table `p_table` has its whole capture: the four triggers as
-- `vm.capture_new_tables()` makes them, enabled, and no other trigger
-- calling a function of `vm`.
CREATE OR REPLACE FUNCTION vm.capture_whole(p_table oid) RETURNS boolean
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT NOT EXISTS (
    SELECT FROM (VALUES
        ('vm_capture_insert', 4, 'vm.capture()'::pg_catalog.regprocedure, NULL, 'vm_new'),
        ('vm_capture_update', 16, 'vm.capture()'::pg_catalog.regprocedure, 'vm_old', 'vm_new'),
        ('vm_capture_delete', 8, 'vm.capture()'::pg_catalog.regprocedure, 'vm_old', NULL),
        ('vm_capture_truncate', 34, 'vm.capture_truncate()'::pg_catalog.regprocedure, NULL, NULL))
        AS w(name, tgtype, fn, oldt, newt)
     WHERE NOT EXISTS (
        SELECT FROM pg_catalog.pg_trigger g
         WHERE g.tgrelid = p_table AND g.tgname = w.name
           AND g.tgtype = w.tgtype AND g.tgfoid = w.fn
           AND g.tgenabled IN ('O', 'A') AND g.tgqual IS NULL
           AND g.tgnargs = 0 AND coalesce(pg_catalog.array_length(g.tgattr::int2[], 1), 0) = 0
           AND NOT g.tgdeferrable AND g.tgconstraint = 0
           AND g.tgoldtable IS NOT DISTINCT FROM w.oldt
           AND g.tgnewtable IS NOT DISTINCT FROM w.newt))
   AND NOT EXISTS (
    SELECT FROM pg_catalog.pg_trigger g
      JOIN pg_catalog.pg_proc p ON p.oid = g.tgfoid
     WHERE g.tgrelid = p_table AND p.pronamespace = 'vm'::pg_catalog.regnamespace
       AND g.tgname NOT LIKE 'vm\_capture\_%')
$f$;

-- Puts the capture back whole (blackbox/CONTRACT.md, "What something else
-- changed"): on every table of the migration role's without its whole
-- capture, every trigger calling a function of `vm` is dropped and the
-- four are made again (so one found disabled, missing, renamed or
-- replaced is as the platform makes it). Answers the tables the platform
-- may not put the capture on (another role's) that are without it.
-- Called by the host as the platform's role, outside any migration.
CREATE OR REPLACE FUNCTION vm.restore_capture() RETURNS TABLE (uncaptured text)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_trigger record;
BEGIN
    FOR v_trigger IN
        SELECT g.tgname, g.tgrelid::pg_catalog.regclass AS relation
          FROM pg_catalog.pg_trigger g
          JOIN pg_catalog.pg_proc p ON p.oid = g.tgfoid
          JOIN pg_catalog.pg_class c ON c.oid = g.tgrelid
          JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
         WHERE p.pronamespace = 'vm'::pg_catalog.regnamespace AND NOT g.tgisinternal
           AND c.relkind IN ('r', 'p')
           AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
           AND pg_catalog.left(n.nspname, 3) <> 'pg_'
           AND pg_catalog.pg_has_role(c.relowner, 'USAGE')
           AND NOT vm.capture_whole(c.oid)
         ORDER BY g.tgrelid, g.tgname
    LOOP
        EXECUTE pg_catalog.format('DROP TRIGGER %I ON %s', v_trigger.tgname, v_trigger.relation);
    END LOOP;
    PERFORM vm.capture_new_tables();
    RETURN QUERY
        SELECT n.nspname::text || '.' || c.relname::text
          FROM pg_catalog.pg_class c
          JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
         WHERE c.relkind IN ('r', 'p')
           AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
           AND pg_catalog.left(n.nspname, 3) <> 'pg_'
           AND NOT vm.capture_whole(c.oid)
         ORDER BY 1;
END
$f$;

-- What the structure and the capture of every table outside `vm` are, as
-- a digest per table (blackbox/CONTRACT.md, "What something else
-- changed"; research part F): the values of its `pg_class` row that make
-- it what it is (object id, name, schema, owner, kind, persistence,
-- partition), the object id and `xmin` of each of its `pg_attribute` and
-- `pg_trigger` rows, and its `pg_inherits` rows. Ordinary maintenance
-- (`VACUUM`, `VACUUM FULL`, `CLUSTER`, `REINDEX`, `ANALYZE`) changes none of
-- these; disabling, enabling, dropping, renaming or making a trigger, and
-- adding, dropping or retyping a column, change one. Neither `ctid` nor
-- `pg_class`'s `xmin` is used: maintenance moves them. The host keeps the
-- answer in the platform database and compares.
CREATE OR REPLACE FUNCTION vm.structure_state() RETURNS TABLE (table_name text, digest text)
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT n.nspname::text || '.' || c.relname::text,
       pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(pg_catalog.concat_ws('|',
           c.oid::text, c.relname::text, n.nspname::text, c.relowner::text, c.relkind::text,
           c.relpersistence::text, c.relispartition::text,
           (SELECT pg_catalog.string_agg(a.attnum::text || ':' || a.xmin::text, ',' ORDER BY a.attnum)
              FROM pg_catalog.pg_attribute a WHERE a.attrelid = c.oid),
           (SELECT pg_catalog.string_agg(g.oid::text || ':' || g.xmin::text, ',' ORDER BY g.oid)
              FROM pg_catalog.pg_trigger g WHERE g.tgrelid = c.oid),
           (SELECT pg_catalog.string_agg(i.inhparent::text || ':' || i.inhseqno::text, ',' ORDER BY i.inhseqno)
              FROM pg_catalog.pg_inherits i WHERE i.inhrelid = c.oid)), 'UTF8')), 'hex')
  FROM pg_catalog.pg_class c
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
 WHERE c.relkind IN ('r', 'p')
   AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
   AND pg_catalog.left(n.nspname, 3) <> 'pg_'
 ORDER BY 1
$f$;

-- The check before the commit of every read-write transaction the host
-- runs on the own database (blackbox/CONTRACT.md, "Checked before every
-- commit that could carry a change"; ADR 0017; research part F): raises
-- VM004 while this session holds a lock on a relation of a mode that
-- reading and writing rows never takes (`SHARE UPDATE EXCLUSIVE` or
-- stronger). Every change of a table's structure or of the capture takes
-- one and keeps it until the transaction ends; one made in a
-- subtransaction that was rolled back was let go with it, and so was what
-- it changed. The host sends it in the same simple query as the `COMMIT`,
-- after `SET CONSTRAINTS ALL IMMEDIATE` and `CLOSE ALL`, so a raised error
-- turns the commit into a rollback and nothing runs in between. The
-- runtime role may call it itself, to no end: it reads the lock manager's
-- own view of this session, and it cannot be replaced (the platform's
-- role owns it and `vm`).
CREATE OR REPLACE FUNCTION vm.before_commit() RETURNS void
LANGUAGE plpgsql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    IF EXISTS (SELECT FROM pg_catalog.pg_locks l
                WHERE l.locktype = 'relation'
                  AND l.pid = pg_catalog.pg_backend_pid()
                  AND l.mode IN ('ShareUpdateExclusiveLock', 'ShareLock', 'ShareRowExclusiveLock',
                                 'ExclusiveLock', 'AccessExclusiveLock')) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM004',
            MESSAGE = 'the transaction changed the structure of a table or the Change history capture, or locked, analyzed or refreshed a table, which only a migration may: an Application''s structure changes in migrations only. Everything the transaction did was rolled back';
    END IF;
END
$f$;

-- Which catalog rows the capture triggers of every table are: one row per
-- table outside `vm`, with its capture triggers (those named like the
-- platform's; another trigger calling a function of `vm` is
-- `capture-missing`, below) as their names and the
-- identity of their `pg_trigger` tuples (object id, `xmin`, `ctid`).
-- Disabling, enabling, renaming, replacing or dropping one gives another
-- tuple, also when it is put back, so the host compares what this answers
-- before and after each migration (kept in the host's memory, not here).
CREATE OR REPLACE FUNCTION vm.capture_state()
RETURNS TABLE (table_oid oid, table_name text, triggers text)
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT c.oid, c.oid::pg_catalog.regclass::text,
       coalesce((SELECT pg_catalog.string_agg(
                            pg_catalog.format('%s|%s|%s|%s|%s', g.tgname, g.oid, g.xmin, g.ctid, g.tgenabled),
                            ';' ORDER BY g.oid)
                   FROM pg_catalog.pg_trigger g
                  WHERE g.tgrelid = c.oid
                    AND g.tgname LIKE 'vm\_capture\_%'), '')
  FROM pg_catalog.pg_class c
  JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
 WHERE c.relkind IN ('r', 'p')
   AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
   AND pg_catalog.left(n.nspname, 3) <> 'pg_'
$f$;

-- Whether what the role `p_owner` owns is code of the Application's for
-- `index-code`: owned by any role but a superuser and the platform's role
-- of the database (which owns `vm`). Postgres's own functions, and a
-- trusted extension's, belong to the bootstrap superuser; nothing of the
-- platform's can be changed by a role of the Application's. Membership of
-- an extension says nothing: the migration role owns a trusted extension
-- it installs and may add its own code to it (`ALTER EXTENSION ... ADD`),
-- still owning that code (research part F, "An extension's membership is
-- not a mark of trust"). So every other owner is a role of the
-- Application's: the migration role, or the runtime role where a migration
-- let it create.
CREATE OR REPLACE FUNCTION vm.application_owned(p_owner oid) RETURNS boolean
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT NOT EXISTS (SELECT FROM pg_catalog.pg_roles r WHERE r.oid = p_owner AND r.rolsuper)
   AND p_owner <> (SELECT n.nspowner FROM pg_catalog.pg_namespace n WHERE n.nspname = 'vm')
$f$;

-- Earlier forms had `vm.application_code(oid, oid)`, by extension
-- membership; it is gone.
DROP FUNCTION IF EXISTS vm.application_code(oid, oid);

-- What the platform refuses at the end of a migration, one row per
-- finding: the rule (as the answer names it) and what was found, where,
-- and what to do instead. No row: nothing to refuse. Called on the
-- migration role's own session. `security-definer`: "the migrations'" is
-- "the session's user owns" (`SESSION_USER`, which no statement of a
-- non-superuser changes), a function a migration added to an extension
-- among them. `index-code`: code a role of the Application's owns
-- (`vm.application_owned`), whatever extension it was added to.
-- `type-code`: a range type, whoever owns it, whose `subtype_diff` (which
-- ANALYZE calls for a column of the range or its multirange, as the
-- table's owner) is such code.
CREATE OR REPLACE FUNCTION vm.capture_problems()
RETURNS TABLE (rule text, message text)
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
WITH tabs AS (
    SELECT c.oid FROM pg_catalog.pg_class c
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE c.relkind IN ('r', 'p')
       AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
       AND pg_catalog.left(n.nspname, 3) <> 'pg_'),
want(name, tgtype, fn, oldt, newt) AS (VALUES
    ('vm_capture_insert', 4, 'vm.capture()'::pg_catalog.regprocedure, NULL, 'vm_new'),
    ('vm_capture_update', 16, 'vm.capture()'::pg_catalog.regprocedure, 'vm_old', 'vm_new'),
    ('vm_capture_delete', 8, 'vm.capture()'::pg_catalog.regprocedure, 'vm_old', NULL),
    ('vm_capture_truncate', 34, 'vm.capture_truncate()'::pg_catalog.regprocedure, NULL, NULL)),
vm_functions AS (
    SELECT p.oid FROM pg_catalog.pg_proc p WHERE p.pronamespace = 'vm'::pg_catalog.regnamespace)
SELECT 'capture-missing',
       pg_catalog.format('the table %s is without its whole Change history capture: its trigger %s is missing, disabled or altered. The platform puts its capture triggers (named vm_capture_...) on every table; leave them as they are: do not drop, disable, rename or replace them', t.oid::pg_catalog.regclass, w.name)
  FROM tabs t CROSS JOIN want w
 WHERE NOT EXISTS (
    SELECT FROM pg_catalog.pg_trigger g
     WHERE g.tgrelid = t.oid AND g.tgname = w.name
       AND g.tgtype = w.tgtype AND g.tgfoid = w.fn
       AND g.tgenabled IN ('O', 'A') AND g.tgqual IS NULL
       AND g.tgnargs = 0 AND coalesce(pg_catalog.array_length(g.tgattr::int2[], 1), 0) = 0
       AND NOT g.tgdeferrable AND g.tgconstraint = 0
       AND g.tgoldtable IS NOT DISTINCT FROM w.oldt
       AND g.tgnewtable IS NOT DISTINCT FROM w.newt)
UNION ALL
SELECT 'capture-missing',
       pg_catalog.format('the trigger %s on %s calls the platform''s function %s and is not one of its capture triggers: drop it; a trigger of the Application''s calls a function of the Application''s',
                         g.tgname, g.tgrelid::pg_catalog.regclass, g.tgfoid::pg_catalog.regprocedure)
  FROM pg_catalog.pg_trigger g
 WHERE g.tgfoid IN (SELECT oid FROM vm_functions)
   AND (g.tgname NOT LIKE 'vm\_capture\_%' OR g.tgrelid NOT IN (SELECT oid FROM tabs))
UNION ALL
SELECT 'deferrable',
       pg_catalog.format('the constraint %s on %s is DEFERRABLE: its work would run at the commit, after the platform''s checks. Declare it NOT DEFERRABLE (the default)',
                         co.conname, co.conrelid::pg_catalog.regclass)
  FROM pg_catalog.pg_constraint co
  JOIN pg_catalog.pg_namespace n ON n.oid = co.connamespace
 WHERE co.condeferrable AND co.conrelid <> 0
   AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
   AND pg_catalog.left(n.nspname, 3) <> 'pg_'
UNION ALL
SELECT 'deferrable',
       pg_catalog.format('the trigger %s on %s is DEFERRABLE: its work would run at the commit, after the platform''s checks. Make it an ordinary trigger, or a constraint trigger NOT DEFERRABLE',
                         g.tgname, g.tgrelid::pg_catalog.regclass)
  FROM pg_catalog.pg_trigger g
 WHERE g.tgdeferrable AND NOT g.tgisinternal AND g.tgconstraint = 0
UNION ALL
SELECT 'json-cast',
       pg_catalog.format('the cast from %s to %s runs the function %s, which Postgres would call inside the Change history capture with the platform''s rights: drop the cast (DROP CAST (%s AS %s)) and call the function where the conversion is wanted',
                         c.castsource::pg_catalog.regtype, c.casttarget::pg_catalog.regtype,
                         c.castfunc::pg_catalog.regprocedure,
                         c.castsource::pg_catalog.regtype, c.casttarget::pg_catalog.regtype)
  FROM pg_catalog.pg_cast c
  JOIN pg_catalog.pg_proc p ON p.oid = c.castfunc
  JOIN pg_catalog.pg_language l ON l.oid = p.prolang
 WHERE c.casttarget IN ('pg_catalog.json'::pg_catalog.regtype, 'pg_catalog.jsonb'::pg_catalog.regtype)
   AND c.castsource >= 16384 AND l.lanname NOT IN ('c', 'internal')
UNION ALL
SELECT 'in-vm',
       pg_catalog.format('the extension %s is in the platform''s schema vm, which holds only the platform''s: create it in a schema of the Application''s (CREATE EXTENSION %s SCHEMA public)',
                         e.extname, e.extname)
  FROM pg_catalog.pg_extension e
 WHERE e.extnamespace = 'vm'::pg_catalog.regnamespace
UNION ALL
SELECT 'in-vm',
       pg_catalog.format('the %s %s in the platform''s schema vm is not the platform''s: the schema vm holds only the platform''s; make it in a schema of the Application''s', o.kind, o.name)
  FROM (SELECT 'function' AS kind, p.oid::pg_catalog.regprocedure::text AS name, p.proowner AS owner
          FROM pg_catalog.pg_proc p WHERE p.pronamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'relation', c.oid::pg_catalog.regclass::text, c.relowner
          FROM pg_catalog.pg_class c WHERE c.relnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'type', t.oid::pg_catalog.regtype::text, t.typowner
          FROM pg_catalog.pg_type t WHERE t.typnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'operator', o.oid::pg_catalog.regoperator::text, o.oprowner
          FROM pg_catalog.pg_operator o WHERE o.oprnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'operator class', oc.opcname::text, oc.opcowner
          FROM pg_catalog.pg_opclass oc WHERE oc.opcnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'operator family', of.opfname::text, of.opfowner
          FROM pg_catalog.pg_opfamily of WHERE of.opfnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'collation', co.collname::text, co.collowner
          FROM pg_catalog.pg_collation co WHERE co.collnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'conversion', cv.conname::text, cv.conowner
          FROM pg_catalog.pg_conversion cv WHERE cv.connamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'text search configuration', ts.cfgname::text, ts.cfgowner
          FROM pg_catalog.pg_ts_config ts WHERE ts.cfgnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'text search dictionary', td.dictname::text, td.dictowner
          FROM pg_catalog.pg_ts_dict td WHERE td.dictnamespace = 'vm'::pg_catalog.regnamespace
        UNION ALL
        SELECT 'statistics object', se.stxname::text, se.stxowner
          FROM pg_catalog.pg_statistic_ext se WHERE se.stxnamespace = 'vm'::pg_catalog.regnamespace) o
 WHERE o.owner <> (SELECT n.nspowner FROM pg_catalog.pg_namespace n WHERE n.nspname = 'vm')
UNION ALL
SELECT 'security-definer',
       pg_catalog.format('the %s %s is SECURITY DEFINER: Postgres would run it with the rights of the role that owns the Application''s tables, which can switch the Change history capture off, whoever calls it. The runtime role may already read and write every table the migrations make: declare it SECURITY INVOKER (the default)',
                         CASE p.prokind WHEN 'p' THEN 'procedure' ELSE 'function' END,
                         p.oid::pg_catalog.regprocedure)
  FROM pg_catalog.pg_proc p
 WHERE p.prosecdef AND pg_catalog.pg_get_userbyid(p.proowner) = SESSION_USER
UNION ALL
SELECT 'index-code',
       pg_catalog.format('the %s %s calls %s, which a role of the Application''s owns: Postgres''s autovacuum would run it with the rights of the role that owns the Application''s tables, outside any transaction of the platform''s. Index or analyze Postgres''s own functions and operators only (or an extension''s), or keep the computed value in a column of its own',
                         x.what, x.name, x.called)
  FROM (SELECT DISTINCT
               CASE d.classid WHEN 'pg_catalog.pg_class'::pg_catalog.regclass THEN 'index'
                              WHEN 'pg_catalog.pg_constraint'::pg_catalog.regclass THEN 'exclusion constraint'
                              ELSE 'extended statistic' END AS what,
               CASE d.classid WHEN 'pg_catalog.pg_class'::pg_catalog.regclass
                                   THEN d.objid::pg_catalog.regclass::text
                              WHEN 'pg_catalog.pg_constraint'::pg_catalog.regclass
                                   THEN (SELECT co.conname::text FROM pg_catalog.pg_constraint co WHERE co.oid = d.objid)
                              ELSE (SELECT se.stxname::text FROM pg_catalog.pg_statistic_ext se WHERE se.oid = d.objid) END AS name,
               CASE d.refclassid WHEN 'pg_catalog.pg_proc'::pg_catalog.regclass
                                      THEN 'the function ' || d.refobjid::pg_catalog.regprocedure::text
                                 WHEN 'pg_catalog.pg_operator'::pg_catalog.regclass
                                      THEN (SELECT 'the operator ' || o.oid::pg_catalog.regoperator::text
                                                   || ' (its function ' || o.oprcode::pg_catalog.regprocedure::text || ')'
                                              FROM pg_catalog.pg_operator o WHERE o.oid = d.refobjid)
                                 WHEN 'pg_catalog.pg_cast'::pg_catalog.regclass
                                      THEN 'the cast ' || (SELECT ca.castsource::pg_catalog.regtype::text || ' AS ' || ca.casttarget::pg_catalog.regtype::text
                                                                  || ' (its function ' || ca.castfunc::pg_catalog.regprocedure::text || ')'
                                                             FROM pg_catalog.pg_cast ca WHERE ca.oid = d.refobjid)
                                 ELSE 'the domain ' || d.refobjid::pg_catalog.regtype::text END AS called
          FROM pg_catalog.pg_depend d
         WHERE (d.classid = 'pg_catalog.pg_statistic_ext'::pg_catalog.regclass
                OR (d.classid = 'pg_catalog.pg_class'::pg_catalog.regclass
                    AND EXISTS (SELECT FROM pg_catalog.pg_class i
                                 WHERE i.oid = d.objid AND i.relkind IN ('i', 'I')))
                OR (d.classid = 'pg_catalog.pg_constraint'::pg_catalog.regclass
                    AND EXISTS (SELECT FROM pg_catalog.pg_constraint co
                                 WHERE co.oid = d.objid AND co.contype = 'x')))
           AND ((d.refclassid = 'pg_catalog.pg_proc'::pg_catalog.regclass
                 AND EXISTS (SELECT FROM pg_catalog.pg_proc p
                              WHERE p.oid = d.refobjid AND vm.application_owned(p.proowner)))
             OR (d.refclassid = 'pg_catalog.pg_operator'::pg_catalog.regclass
                 AND EXISTS (SELECT FROM pg_catalog.pg_operator o
                              WHERE o.oid = d.refobjid
                                AND EXISTS (SELECT FROM pg_catalog.pg_proc p
                                             WHERE p.oid = o.oprcode AND vm.application_owned(p.proowner))))
             OR (d.refclassid = 'pg_catalog.pg_cast'::pg_catalog.regclass
                 AND EXISTS (SELECT FROM pg_catalog.pg_cast ca
                              WHERE ca.oid = d.refobjid AND ca.castfunc <> 0
                                AND EXISTS (SELECT FROM pg_catalog.pg_proc p
                                             WHERE p.oid = ca.castfunc AND vm.application_owned(p.proowner))))
             OR (d.refclassid = 'pg_catalog.pg_type'::pg_catalog.regclass
                 AND EXISTS (SELECT FROM pg_catalog.pg_type t
                              WHERE t.oid = d.refobjid AND t.typtype = 'd'
                                AND vm.application_owned(t.typowner))))) x
UNION ALL
SELECT 'type-code',
       pg_catalog.format('the range type %s has the subtype_diff %s, which a role of the Application''s owns: Postgres''s autovacuum would run it with the rights of the role that owns the Application''s tables, on any table with a column of the type, outside any transaction of the platform''s. Leave subtype_diff out, or make it one of Postgres''s own (float8mi, int4range_subdiff)',
                         r.rngtypid::pg_catalog.regtype, r.rngsubdiff::pg_catalog.regprocedure)
  FROM pg_catalog.pg_range r
  JOIN pg_catalog.pg_proc p ON p.oid = r.rngsubdiff
 WHERE vm.application_owned(p.proowner)
$f$;

-- The migrations recorded, in order: what the host compares a Version's
-- list with, and reads back after recording. `sql_sha256` is computed
-- from the text kept, not taken from the record.
CREATE OR REPLACE FUNCTION vm.applied_migrations()
RETURNS TABLE (place integer, name text, sha256 text, sql_sha256 text)
LANGUAGE sql STABLE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT m.position, m.name, m.sha256,
       pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(m.sql, 'UTF8')), 'hex')
  FROM vm.migrations m
 ORDER BY m.position
$f$;

-- Records one migration as applied. Only with the identity the host
-- attaches for this, after the Version's last migration and its checks
-- (`actor` `platform`), which a migration cannot make: it does not have
-- the keys.
CREATE OR REPLACE FUNCTION vm.record_migration(p_position integer, p_name text, p_sql text)
RETURNS void
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    IF (vm.attached() ->> 'actor') IS DISTINCT FROM 'platform' THEN
        RAISE EXCEPTION USING ERRCODE = '42501',
            MESSAGE = 'only the platform records a migration';
    END IF;
    INSERT INTO vm.migrations (position, name, sha256, sql)
    VALUES (p_position, p_name,
            pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(p_sql, 'UTF8')), 'hex'),
            p_sql);
END
$f$;

-- What the tables outside `vm` and the enum types are, for the changes of
-- structure that change data (blackbox/CONTRACT.md, "Changes of structure
-- that change data"): `tables`, by object id, each with its schema `s`,
-- name `n`, file node `f` (a new one when Postgres writes the rows anew;
-- 0 for a partitioned table), columns `c` (number, name, type as
-- `format_type` prints it under this function's search path, which names
-- every type that is not Postgres's own with its schema, type's object id;
-- dropped ones left out) and partitions `p` (object ids); and `enums`, each
-- value by its object id, which renaming it keeps: [type, label]. Called
-- by the host on the migration role's session at the start of each
-- migration, kept in the host's memory, and given back to
-- `vm.record_structure` at its end. Reads only the catalog.
CREATE OR REPLACE FUNCTION vm.structure_snapshot() RETURNS jsonb
LANGUAGE sql STABLE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT pg_catalog.jsonb_build_object(
    'tables', coalesce((
        SELECT pg_catalog.jsonb_object_agg(c.oid::text, pg_catalog.jsonb_build_object(
                   's', n.nspname::text,
                   'n', c.relname::text,
                   'f', c.relfilenode::text,
                   'c', coalesce((
                        SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_array(
                                   a.attnum, a.attname::text,
                                   pg_catalog.format_type(a.atttypid, a.atttypmod),
                                   a.atttypid::text) ORDER BY a.attnum)
                          FROM pg_catalog.pg_attribute a
                         WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped), '[]'::jsonb),
                   'p', coalesce((
                        SELECT pg_catalog.jsonb_agg(i.inhrelid::text ORDER BY i.inhrelid)
                          FROM pg_catalog.pg_inherits i
                          JOIN pg_catalog.pg_class k ON k.oid = i.inhrelid
                         WHERE i.inhparent = c.oid AND k.relispartition AND k.relkind IN ('r', 'p')), '[]'::jsonb)))
          FROM pg_catalog.pg_class c
          JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
         WHERE c.relkind IN ('r', 'p')
           AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
           AND pg_catalog.left(n.nspname, 3) <> 'pg_'), '{}'::jsonb),
    'enums', coalesce((
        SELECT pg_catalog.jsonb_object_agg(e.oid::text,
                   pg_catalog.jsonb_build_array(e.enumtypid::text, e.enumlabel::text))
          FROM pg_catalog.pg_enum e), '{}'::jsonb))
$f$;

-- Records, as entries of the outbox of kind `structure`, what the
-- migration that just ended changed of the structure of the tables there
-- were when it began (`p_before`, `vm.structure_snapshot()` then), against
-- what the catalog says now (blackbox/CONTRACT.md, "Changes of structure
-- that change data"); answers how many. Only with the identity the host
-- attaches for this at the end of each migration (`actor` `platform`,
-- with the Contributor and the migration's name), which a migration
-- cannot make: it does not have the keys. The entries have `actor`
-- `migration`, that Contributor and that migration. On a table there is
-- still: `column-dropped`, `column-type`, `table-rewritten` (a new file
-- node and no `column-type` entry; on a partitioned table, when a table
-- under it was), `enum-value-renamed` (one per value renamed, on every
-- such table with a column of a type that holds it: a domain over it, an
-- array, a range or multirange over it, a composite type or row type with
-- an attribute of it, at any depth), `partition-attached` (a table that
-- was there, attached) and `partition-detached` (detached or dropped),
-- under the table's name now. On a table that is gone, or whose name
-- another table has now, and that was not a partition: `table-dropped` or
-- `table-replaced`, under the name it had.
CREATE OR REPLACE FUNCTION vm.record_structure(p_before jsonb) RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_who jsonb := vm.attached();
    v_now jsonb;
    v_at timestamptz := pg_catalog.clock_timestamp();
    v_made integer;
    v_enums oid[] := '{}';
    v_types oid[] := '{}';
BEGIN
    IF (v_who ->> 'actor') IS DISTINCT FROM 'platform' OR (v_who ->> 'migration') IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = '42501',
            MESSAGE = 'only the platform records a change of structure';
    END IF;
    v_now := vm.structure_snapshot();
    -- The types whose values hold a renamed enum's: the enum, and every
    -- domain over one of these, array of one, range over one and its
    -- multirange, and composite type with an attribute of one (a table's
    -- row type among them), to any depth; as pairs (enum, type). Looked
    -- for only when a label changed: the statement that would look costs
    -- its plan's start (a hash table for the recursion) even when it finds
    -- nothing, about 5 ms (research section 13).
    IF EXISTS (SELECT FROM pg_catalog.jsonb_each(p_before -> 'enums') o
                 JOIN pg_catalog.jsonb_each(v_now -> 'enums') w ON w.key = o.key
                WHERE (w.value ->> 1) IS DISTINCT FROM (o.value ->> 1)) THEN
        WITH RECURSIVE renamed AS (
            SELECT DISTINCT (o.value ->> 0)::oid AS typid
              FROM pg_catalog.jsonb_each(p_before -> 'enums') o
              JOIN pg_catalog.jsonb_each(v_now -> 'enums') w ON w.key = o.key
             WHERE (w.value ->> 1) IS DISTINCT FROM (o.value ->> 1)),
        holding (enum, typid) AS (
            SELECT r.typid, r.typid FROM renamed r
            UNION
            SELECT h.enum, x.typid
              FROM holding h
              CROSS JOIN LATERAL (
                  SELECT t.oid FROM pg_catalog.pg_type t
                   WHERE t.typtype = 'd' AND t.typbasetype = h.typid
                  UNION ALL
                  SELECT u.typarray FROM pg_catalog.pg_type u
                   WHERE u.oid = h.typid AND u.typarray <> 0
                  UNION ALL
                  SELECT g.rngtypid FROM pg_catalog.pg_range g WHERE g.rngsubtype = h.typid
                  UNION ALL
                  SELECT g.rngmultitypid FROM pg_catalog.pg_range g WHERE g.rngsubtype = h.typid
                  UNION ALL
                  SELECT c.oid FROM pg_catalog.pg_attribute a
                    JOIN pg_catalog.pg_type c ON c.typrelid = a.attrelid
                   WHERE a.atttypid = h.typid AND a.attnum > 0 AND NOT a.attisdropped) x(typid))
        SELECT coalesce(pg_catalog.array_agg(h.enum ORDER BY h.enum, h.typid), '{}'),
               coalesce(pg_catalog.array_agg(h.typid ORDER BY h.enum, h.typid), '{}')
          INTO v_enums, v_types
          FROM holding h;
    END IF;
    WITH b AS (
        SELECT t.key AS id, t.value ->> 's' AS s, t.value ->> 'n' AS n, t.value AS v
          FROM pg_catalog.jsonb_each(p_before -> 'tables') t),
    a AS (
        SELECT t.key AS id, t.value ->> 's' AS s, t.value ->> 'n' AS n, t.value AS v
          FROM pg_catalog.jsonb_each(v_now -> 'tables') t),
    kept AS (
        SELECT b.id, a.s, a.n, b.v AS bv, a.v AS av FROM b JOIN a ON a.id = b.id),
    bcols AS (
        SELECT k.id, (c.value ->> 0)::integer AS attnum, c.value ->> 1 AS name, c.value ->> 2 AS type
          FROM kept k CROSS JOIN LATERAL pg_catalog.jsonb_array_elements(k.bv -> 'c') c),
    acols AS (
        SELECT k.id, (c.value ->> 0)::integer AS attnum, c.value ->> 1 AS name, c.value ->> 2 AS type,
               (c.value ->> 3)::oid AS typid
          FROM kept k CROSS JOIN LATERAL pg_catalog.jsonb_array_elements(k.av -> 'c') c),
    retyped AS (
        SELECT x.id, y.attnum, y.name, x.type AS from_type, y.type AS to_type
          FROM bcols x JOIN acols y ON y.id = x.id AND y.attnum = x.attnum
         WHERE y.type IS DISTINCT FROM x.type),
    renamed AS (
        SELECT (o.value ->> 0)::oid AS typid, o.value ->> 1 AS from_label, w.value ->> 1 AS to_label
          FROM pg_catalog.jsonb_each(p_before -> 'enums') o
          JOIN pg_catalog.jsonb_each(v_now -> 'enums') w ON w.key = o.key
         WHERE (w.value ->> 1) IS DISTINCT FROM (o.value ->> 1)),
    -- The types whose values hold a renamed enum's (v_enums, v_types).
    holding (enum, typid) AS (
        SELECT u.enum, u.typid
          FROM ROWS FROM (pg_catalog.unnest(v_enums), pg_catalog.unnest(v_types)) u(enum, typid)),
    -- Written anew, and no type change says why.
    rewritten AS (
        SELECT k.id FROM kept k
         WHERE (k.bv ->> 'f') <> '0' AND (k.av ->> 'f') IS DISTINCT FROM (k.bv ->> 'f')
           AND NOT EXISTS (SELECT FROM retyped r WHERE r.id = k.id)),
    -- What was a partition when the migration began: its own history has
    -- no entry of a change of structure; its parent's has.
    was_partition AS (
        SELECT ch.id FROM b CROSS JOIN LATERAL pg_catalog.jsonb_array_elements_text(b.v -> 'p') ch(id)),
    entries (s, n, place, structure) AS (
        SELECT b.s, b.n, 1,
               pg_catalog.jsonb_build_object('change',
                   CASE WHEN EXISTS (SELECT FROM a WHERE a.s = b.s AND a.n = b.n)
                        THEN 'table-replaced' ELSE 'table-dropped' END)
          FROM b
         WHERE (NOT EXISTS (SELECT FROM a WHERE a.id = b.id)
                OR EXISTS (SELECT FROM a WHERE a.s = b.s AND a.n = b.n AND a.id <> b.id))
           AND NOT EXISTS (SELECT FROM was_partition w WHERE w.id = b.id)
        UNION ALL
        SELECT k.s, k.n, 2, pg_catalog.jsonb_build_object('change', 'column-dropped', 'column', x.name)
          FROM bcols x JOIN kept k ON k.id = x.id
         WHERE NOT EXISTS (SELECT FROM acols y WHERE y.id = x.id AND y.attnum = x.attnum)
        UNION ALL
        SELECT k.s, k.n, 3, pg_catalog.jsonb_build_object('change', 'column-type', 'column', r.name,
                                                          'from', r.from_type, 'to', r.to_type)
          FROM retyped r JOIN kept k ON k.id = r.id
        UNION ALL
        SELECT k.s, k.n, 4, pg_catalog.jsonb_build_object('change', 'table-rewritten')
          FROM kept k
         WHERE EXISTS (SELECT FROM rewritten w WHERE w.id = k.id)
            OR ((k.av ->> 'f') = '0'
                AND NOT EXISTS (SELECT FROM retyped r WHERE r.id = k.id)
                AND EXISTS (SELECT FROM pg_catalog.pg_partition_tree(k.id::oid) u
                            JOIN rewritten w ON w.id = u.relid::oid::text
                           WHERE u.relid::oid OPERATOR(pg_catalog.<>) k.id::oid))
        UNION ALL
        SELECT k.s, k.n, 5, pg_catalog.jsonb_build_object('change', 'enum-value-renamed',
                   'type', pg_catalog.format_type(e.typid, NULL),
                   'from', e.from_label, 'to', e.to_label,
                   'columns', (SELECT pg_catalog.jsonb_agg(y.name ORDER BY y.attnum)
                                 FROM acols y
                                WHERE y.id = k.id
                                  AND y.typid IN (SELECT h.typid FROM holding h WHERE h.enum = e.typid)))
          FROM renamed e
          CROSS JOIN kept k
         WHERE EXISTS (SELECT FROM acols y
                        WHERE y.id = k.id
                          AND y.typid IN (SELECT h.typid FROM holding h WHERE h.enum = e.typid))
        UNION ALL
        SELECT k.s, k.n, 6, pg_catalog.jsonb_build_object('change', 'partition-attached',
                                                          'partition', p.s || '.' || p.n)
          FROM kept k
          CROSS JOIN LATERAL pg_catalog.jsonb_array_elements_text(k.av -> 'p') ch(id)
          JOIN a p ON p.id = ch.id
         WHERE NOT (k.bv -> 'p') @> pg_catalog.to_jsonb(ch.id)
           AND EXISTS (SELECT FROM b WHERE b.id = ch.id)
        UNION ALL
        SELECT k.s, k.n, 7, pg_catalog.jsonb_build_object('change', 'partition-detached',
                   'partition', coalesce((SELECT p.s || '.' || p.n FROM a p WHERE p.id = ch.id),
                                         (SELECT p.s || '.' || p.n FROM b p WHERE p.id = ch.id)))
          FROM kept k
          CROSS JOIN LATERAL pg_catalog.jsonb_array_elements_text(k.bv -> 'p') ch(id)
         WHERE NOT (k.av -> 'p') @> pg_catalog.to_jsonb(ch.id))
    INSERT INTO vm.outbox (at, schema_name, table_name, kind, key, old, new, changed,
                           user_id, application, actor, request, migration, structure)
    SELECT v_at, e.s, e.n, 'structure', NULL, NULL, NULL, NULL,
           v_who ->> 'user_id', v_who ->> 'application', 'migration', NULL,
           v_who ->> 'migration', e.structure
      FROM entries e
     ORDER BY e.s, e.n, e.place, e.structure::text;
    GET DIAGNOSTICS v_made = ROW_COUNT;
    RETURN v_made;
END
$f$;

-- A rewrite records each row it changed (blackbox/CONTRACT.md, "A rewrite
-- records each row it changed"; ADR 0017, third slice).
--
-- The host, on the migration role's own session and in the migration's
-- transaction:
--
-- - at the start of each migration, `vm.rewrite_begin` notes every table
--   there is (the tables with history when the migration began) and its
--   file node;
-- - before a statement it knows rewrites (seen so in an earlier run, or
--   foreseen from its text), `vm.rewrite_before` reads the rows of those
--   tables into `vm.rewrite_rows`;
-- - after every statement, `vm.rewrites_seen()` says whether a noted table
--   has a new file node; if one has, `vm.rewrite_after` says which (by the
--   table at the top of its partitions, and its name when the migration
--   began), and `vm.rewrite_record_after` reads their rows again and
--   records each row that differs (`vm.rewrite_record`).
--
-- The reading is done as the migration role, never with the platform's
-- rights: `vm.rewrite_before`, `vm.rewrite_read` and
-- `vm.rewrite_record_after` are SECURITY INVOKER, so whatever reading the
-- table runs (a policy, a cast) runs with the migration role's rights
-- only. No identity of the platform's is attached meanwhile: the
-- migration's own is, as for its statements.
--
-- What lets the reading put rows where the migration cannot is a token:
-- the host's tag over the transaction's key and the migration's identity,
-- made with the own database's keys (`vm.keys`, which the migration role
-- cannot read), passed as a parameter of the host's statements and from
-- there as an argument, never in a statement's text (which
-- `current_query()` would show to code running in it). Every function
-- that writes in `vm` checks it (`vm.rewrite_who`), and checks that the
-- statement running is one of the host's, by its exact text: code of the
-- migration's runs inside its own statements, whose text is the
-- migration's. The tables are the platform's role's alone; the functions
-- that write them are SECURITY DEFINER and touch nothing outside `vm` and
-- the catalog.
CREATE UNLOGGED TABLE IF NOT EXISTS vm.rewrite_nodes (
    relid oid PRIMARY KEY,
    node oid NOT NULL,
    s text NOT NULL,
    n text NOT NULL
);
CREATE UNLOGGED TABLE IF NOT EXISTS vm.rewrite_columns (
    relid oid NOT NULL,
    phase smallint NOT NULL,
    attnum smallint NOT NULL,
    name text NOT NULL,
    virtual boolean NOT NULL,
    key smallint,
    PRIMARY KEY (relid, phase, attnum)
);
CREATE UNLOGGED TABLE IF NOT EXISTS vm.rewrite_rows (
    id bigint GENERATED ALWAYS AS IDENTITY,
    relid oid NOT NULL,
    phase smallint NOT NULL,
    j jsonb NOT NULL,
    n jsonb
);

-- The identity a token of the host's carries, once its tag is checked
-- against the keys and this transaction, and the statement running is one
-- of the host's own; raises VM001 otherwise.
CREATE OR REPLACE FUNCTION vm.rewrite_who(p_token text) RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_k1 bytea;
    v_k2 bytea;
    v_who text;
BEGIN
    IF p_token IS NULL OR pg_catalog.length(p_token) <= 64
       OR pg_catalog.current_query() IS NULL
       OR pg_catalog.current_query() NOT IN (
           'SELECT vm.rewrite_begin($1)',
           'SELECT vm.rewrite_before($1, $2::pg_catalog.text[], ARRAY(SELECT pg_catalog.to_regclass(x)::pg_catalog.oid FROM pg_catalog.unnest($3::pg_catalog.text[]) x))',
           'SELECT r.relid, r.s, r.n, r.read FROM vm.rewrite_after($1) r',
           'SELECT vm.rewrite_record_after($1, $2::pg_catalog.oid[])',
           'SELECT vm.rewrite_done($1, false)',
           'SELECT vm.rewrite_done($1, true)') THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'only the platform reads and records a rewrite';
    END IF;
    SELECT k.k1, k.k2 INTO v_k1, v_k2 FROM vm.keys k;
    v_who := pg_catalog.substr(p_token, 65);
    IF v_k1 IS NULL OR v_k2 IS NULL
       OR pg_catalog.encode(pg_catalog.sha256(v_k2 || pg_catalog.sha256(v_k1 || pg_catalog.convert_to(
              'vm.rewrite v1' || pg_catalog.chr(10) || vm.transaction_key() || pg_catalog.chr(10) || v_who,
              'UTF8'))), 'hex')
          IS DISTINCT FROM pg_catalog.substr(p_token, 1, 64) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'only the platform reads and records a rewrite';
    END IF;
    RETURN v_who::jsonb;
END
$f$;

-- At the start of a migration: every table there is now, with its file
-- node and its name (a partitioned table's node is 0, its partitions'
-- move). What was left of an earlier migration's is gone.
CREATE OR REPLACE FUNCTION vm.rewrite_begin(p_token text) RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_made integer;
BEGIN
    PERFORM vm.rewrite_who(p_token);
    DELETE FROM vm.rewrite_rows;
    DELETE FROM vm.rewrite_columns;
    DELETE FROM vm.rewrite_nodes;
    INSERT INTO vm.rewrite_nodes (relid, node, s, n)
    SELECT c.oid, c.relfilenode, n.nspname::text, c.relname::text
      FROM pg_catalog.pg_class c
      JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE c.relkind IN ('r', 'p')
       AND n.nspname <> 'vm' AND n.nspname <> 'information_schema'
       AND pg_catalog.left(n.nspname, 3) <> 'pg_';
    GET DIAGNOSTICS v_made = ROW_COUNT;
    RETURN v_made;
END
$f$;

-- Whether a table noted at the start of the migration has a new file
-- node: asked after every statement. Reads only `vm` and the catalog,
-- writes nothing.
CREATE OR REPLACE FUNCTION vm.rewrites_seen() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
SELECT EXISTS (SELECT FROM vm.rewrite_nodes r
                 JOIN pg_catalog.pg_class c ON c.oid OPERATOR(pg_catalog.=) r.relid
                WHERE c.relfilenode OPERATOR(pg_catalog.<>) r.node)
$f$;

-- The tables with history the statement just run rewrote, each as the
-- table at the top of its partitions (itself, when it is none), with its
-- name when the migration began, and whether its rows were read before
-- the statement; their new file nodes noted.
CREATE OR REPLACE FUNCTION vm.rewrite_after(p_token text)
RETURNS TABLE (relid oid, s text, n text, read boolean)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    PERFORM vm.rewrite_who(p_token);
    RETURN QUERY
    WITH moved AS (
        UPDATE vm.rewrite_nodes r SET node = c.relfilenode
          FROM pg_catalog.pg_class c
         WHERE c.oid = r.relid AND c.relfilenode <> r.node
        RETURNING r.relid),
    roots AS (
        SELECT DISTINCT coalesce(pg_catalog.pg_partition_root(m.relid), m.relid) AS root FROM moved m)
    SELECT t.relid, t.s, t.n,
           EXISTS (SELECT FROM vm.rewrite_columns k WHERE k.relid = t.relid AND k.phase = 0)
      FROM roots x
      JOIN vm.rewrite_nodes t ON t.relid = x.root
      JOIN pg_catalog.pg_class c ON c.oid = t.relid
     ORDER BY t.s, t.n;
END
$f$;

-- The tables whose rows are to be read before a statement: those noted
-- under the names `p_names` (schema and name by turns, as when the
-- migration began) and, for each table of `p_relids` and every table
-- under it, the table at the top of its partitions; only tables noted at
-- the start of the migration. What an earlier statement left is gone.
CREATE OR REPLACE FUNCTION vm.rewrite_roots(p_token text, p_names text[], p_relids oid[])
RETURNS oid[]
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_roots oid[];
BEGIN
    PERFORM vm.rewrite_who(p_token);
    DELETE FROM vm.rewrite_rows;
    DELETE FROM vm.rewrite_columns;
    WITH RECURSIVE named AS (
        SELECT t.relid
          FROM pg_catalog.generate_subscripts(p_names, 1) i
          JOIN vm.rewrite_nodes t
            ON t.s = p_names[i] AND t.n = p_names[i + 1]
         WHERE i % 2 = 1),
    under (relid) AS (
        SELECT x FROM pg_catalog.unnest(p_relids) x WHERE x IS NOT NULL
        UNION
        SELECT h.inhrelid FROM pg_catalog.pg_inherits h JOIN under u ON h.inhparent = u.relid),
    roots AS (
        SELECT relid FROM named
        UNION
        SELECT coalesce(pg_catalog.pg_partition_root(u.relid), u.relid) FROM under u)
    SELECT coalesce(pg_catalog.array_agg(r.relid ORDER BY r.relid), '{}')
      INTO v_roots
      FROM roots r
     WHERE EXISTS (SELECT FROM vm.rewrite_nodes t WHERE t.relid = r.relid);
    RETURN v_roots;
END
$f$;

-- Keeps what a reading `p_phase` (0 before the statement, 1 after) of
-- the table `p_relid` read. Without rows, it begins: the table's columns
-- as the reading sees them (number, name, whether virtual, place in the
-- primary key), what an earlier reading of the same phase kept gone.
-- With rows, each as the capture records it (`p_rows`) with the names of
-- its `json` and `jsonb` columns holding JSON null (`p_nulls`).
CREATE OR REPLACE FUNCTION vm.rewrite_keep(p_token text, p_relid oid, p_phase smallint,
                                           p_rows jsonb[], p_nulls jsonb[])
RETURNS integer
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_made integer;
BEGIN
    PERFORM vm.rewrite_who(p_token);
    IF p_rows IS NULL THEN
        IF NOT EXISTS (SELECT FROM vm.rewrite_nodes t WHERE t.relid = p_relid) THEN
            RAISE EXCEPTION USING ERRCODE = 'VM001',
                MESSAGE = 'only a table noted at the start of the migration is read';
        END IF;
        DELETE FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = p_phase;
        DELETE FROM vm.rewrite_rows r WHERE r.relid = p_relid AND r.phase = p_phase;
        INSERT INTO vm.rewrite_columns (relid, phase, attnum, name, virtual, key)
        SELECT p_relid, p_phase, a.attnum, a.attname::text, a.attgenerated = 'v',
               (SELECT pg_catalog.array_position(i.indkey::int2[], a.attnum)::smallint
                  FROM pg_catalog.pg_index i
                 WHERE i.indrelid = p_relid AND i.indisprimary)
          FROM pg_catalog.pg_attribute a
         WHERE a.attrelid = p_relid AND a.attnum > 0 AND NOT a.attisdropped;
        GET DIAGNOSTICS v_made = ROW_COUNT;
        RETURN v_made;
    END IF;
    IF NOT EXISTS (SELECT FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = p_phase) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'rows are kept only for a reading begun';
    END IF;
    INSERT INTO vm.rewrite_rows (relid, phase, j, n)
    SELECT p_relid, p_phase, x.j, x.n
      FROM ROWS FROM (pg_catalog.unnest(p_rows), pg_catalog.unnest(p_nulls)) x(j, n);
    GET DIAGNOSTICS v_made = ROW_COUNT;
    RETURN v_made;
END
$f$;

-- One reading of the table `p_relid`'s own rows (`ONLY`; a partitioned
-- table's are its partitions', in its form), as the migration role
-- (SECURITY INVOKER), the settings that change how values print pinned as
-- in the capture, row security off. Refused when row security would apply
-- to the reading (VM004), or a cast to json or jsonb of the Application's
-- exists (VM003: `to_jsonb` would call it). Each row is the object of its
-- columns as `to_jsonb` makes it, a virtual generated column null (as in
-- the capture, and never computed). The rows go to `vm.rewrite_keep` in
-- chunks of 5,000, so that no more than a chunk is held here at once.
-- Answers how many rows.
CREATE OR REPLACE FUNCTION vm.rewrite_read(p_token text, p_relid oid, p_phase smallint)
RETURNS bigint
LANGUAGE plpgsql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
SET TimeZone = 'UTC'
SET extra_float_digits = 1
SET IntervalStyle = 'postgres'
SET DateStyle = 'ISO, YMD'
SET bytea_output = 'hex'
SET row_security = off
AS $f$
DECLARE
    v_kind "char";
    v_pairs text[];
    v_row text;
    v_tests text;
    v_nulls text;
    v_js jsonb[] := '{}';
    v_ns jsonb[] := '{}';
    v_held integer := 0;
    v_read bigint := 0;
    v_r record;
BEGIN
    PERFORM vm.capture_guard();
    SELECT c.relkind INTO v_kind FROM pg_catalog.pg_class c WHERE c.oid = p_relid;
    IF v_kind IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'the table to read is not there';
    END IF;
    IF pg_catalog.row_security_active(p_relid) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM004',
            MESSAGE = pg_catalog.format(
                'row security applies to the table %s as its owner reads it (FORCE ROW LEVEL SECURITY), so the platform cannot read all its rows before and after a statement that writes them anew, to record each row it changed: take FORCE ROW LEVEL SECURITY off before the statement and put it back after it',
                p_relid::pg_catalog.regclass);
    END IF;
    PERFORM vm.rewrite_keep(p_token, p_relid, p_phase, NULL, NULL);
    -- `jsonb_build_object` takes at most 50 pairs: one per 50 columns.
    SELECT pg_catalog.array_agg(x.o ORDER BY x.g)
      INTO v_pairs
      FROM (SELECT (a.i - 1) / 50 AS g,
                   'pg_catalog.jsonb_build_object(' || pg_catalog.string_agg(
                       CASE WHEN a.attgenerated = 'v'
                            THEN pg_catalog.format('%L, NULL::pg_catalog.jsonb', a.attname)
                            ELSE pg_catalog.format('%L, vm_row.%I', a.attname, a.attname) END,
                       ', ' ORDER BY a.attnum) || ')' AS o
              FROM (SELECT t.attname, t.attnum, t.attgenerated,
                           pg_catalog.row_number() OVER (ORDER BY t.attnum) AS i
                      FROM pg_catalog.pg_attribute t
                     WHERE t.attrelid = p_relid AND t.attnum > 0 AND NOT t.attisdropped) a
             GROUP BY 1) x;
    v_row := coalesce(pg_catalog.array_to_string(v_pairs, ' OPERATOR(pg_catalog.||) '),
                      '''{}''::pg_catalog.jsonb');
    SELECT pg_catalog.string_agg(
               pg_catalog.format('(%L, pg_catalog.%s(vm_row.%I) OPERATOR(pg_catalog.=) %L)',
                                 a.attname,
                                 CASE WHEN a.atttypid = 'pg_catalog.json'::pg_catalog.regtype
                                      THEN 'json_typeof' ELSE 'jsonb_typeof' END,
                                 a.attname, 'null'),
               ', ' ORDER BY a.attnum)
      INTO v_tests
      FROM pg_catalog.pg_attribute a
     WHERE a.attrelid = p_relid AND a.attnum > 0 AND NOT a.attisdropped AND a.attgenerated <> 'v'
       AND a.atttypid IN ('pg_catalog.json'::pg_catalog.regtype, 'pg_catalog.jsonb'::pg_catalog.regtype);
    IF v_tests IS NULL THEN
        v_nulls := 'NULL::pg_catalog.jsonb';
    ELSE
        v_nulls := 'pg_catalog.to_jsonb(ARRAY(SELECT v.c FROM (VALUES ' || v_tests || ') AS v(c, n) WHERE v.n))';
    END IF;
    FOR v_r IN EXECUTE pg_catalog.format('SELECT %s AS j, %s AS n FROM %s %s vm_row',
                                         v_row, v_nulls,
                                         CASE WHEN v_kind = 'p' THEN '' ELSE 'ONLY' END,
                                         p_relid::pg_catalog.regclass) LOOP
        v_js := pg_catalog.array_append(v_js, v_r.j);
        v_ns := pg_catalog.array_append(v_ns, v_r.n);
        v_held := v_held + 1;
        IF v_held >= 5000 THEN
            v_read := v_read + vm.rewrite_keep(p_token, p_relid, p_phase, v_js, v_ns);
            v_js := '{}';
            v_ns := '{}';
            v_held := 0;
        END IF;
    END LOOP;
    IF v_held > 0 THEN
        v_read := v_read + vm.rewrite_keep(p_token, p_relid, p_phase, v_js, v_ns);
    END IF;
    RETURN v_read;
END
$f$;

-- Before a statement: the rows of the tables `vm.rewrite_roots` names,
-- read as the migration role. Answers how many rows.
CREATE OR REPLACE FUNCTION vm.rewrite_before(p_token text, p_names text[], p_relids oid[])
RETURNS bigint
LANGUAGE plpgsql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_root oid;
    v_read bigint := 0;
BEGIN
    FOREACH v_root IN ARRAY vm.rewrite_roots(p_token, p_names, p_relids) LOOP
        v_read := v_read + vm.rewrite_read(p_token, v_root, 0::smallint);
    END LOOP;
    RETURN v_read;
END
$f$;

-- After a statement that rewrote the tables `p_relids` (each read before
-- it): their rows read again, as the migration role, and recorded.
-- Answers how many entries.
CREATE OR REPLACE FUNCTION vm.rewrite_record_after(p_token text, p_relids oid[])
RETURNS bigint
LANGUAGE plpgsql VOLATILE PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_root oid;
    v_made bigint := 0;
BEGIN
    FOREACH v_root IN ARRAY p_relids LOOP
        PERFORM vm.rewrite_read(p_token, v_root, 1::smallint);
        v_made := v_made + vm.rewrite_record(p_token, v_root);
    END LOOP;
    RETURN v_made;
END
$f$;

-- Compares the rows of `p_relid` read before and after the statement and
-- records each that differs, under the identity the token carries, in
-- the outbox; then forgets them. Answers how many entries. Touches only
-- `vm` and the catalog: no value is cast to a type of the Application's,
-- nothing of the Application's runs. A table without a primary key that
-- is the same columns before and after is compared as a multiset of
-- rows, and refused (VM005) when they differ.
CREATE OR REPLACE FUNCTION vm.rewrite_record(p_token text, p_relid oid) RETURNS bigint
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
DECLARE
    v_who jsonb := vm.rewrite_who(p_token);
    v_at timestamptz := pg_catalog.clock_timestamp();
    v_schema text;
    v_table text;
    v_keyed boolean;
    v_made bigint;
BEGIN
    IF NOT EXISTS (SELECT FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = 0)
       OR NOT EXISTS (SELECT FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = 1) THEN
        RAISE EXCEPTION USING ERRCODE = 'VM001',
            MESSAGE = 'a rewrite is recorded only from its two readings';
    END IF;
    SELECT n.nspname::text, c.relname::text INTO v_schema, v_table
      FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE c.oid = p_relid;
    -- Paired by the key only when it is the same columns before and after.
    SELECT EXISTS (SELECT FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = 0 AND k.key IS NOT NULL)
       AND NOT EXISTS (
           SELECT FROM (SELECT k.attnum FROM vm.rewrite_columns k
                         WHERE k.relid = p_relid AND k.phase = 0 AND k.key IS NOT NULL) b
           FULL JOIN (SELECT k.attnum FROM vm.rewrite_columns k
                       WHERE k.relid = p_relid AND k.phase = 1 AND k.key IS NOT NULL) a
             ON a.attnum = b.attnum
          WHERE a.attnum IS NULL OR b.attnum IS NULL)
      INTO v_keyed;
    IF NOT v_keyed THEN
        IF EXISTS (
            WITH common AS (
                SELECT b.attnum, b.name AS bname, a.name AS aname
                  FROM vm.rewrite_columns b
                  JOIN vm.rewrite_columns a ON a.relid = b.relid AND a.attnum = b.attnum AND a.phase = 1
                 WHERE b.relid = p_relid AND b.phase = 0 AND NOT b.virtual AND NOT a.virtual),
            rows_before AS (
                SELECT (SELECT coalesce(pg_catalog.jsonb_object_agg(c.aname, r.j -> c.bname), '{}') FROM common c) AS v,
                       (SELECT coalesce(pg_catalog.jsonb_agg(c.aname ORDER BY c.attnum), '[]') FROM common c
                         WHERE coalesce(r.n ? c.bname, false)) AS z
                  FROM vm.rewrite_rows r WHERE r.relid = p_relid AND r.phase = 0),
            rows_after AS (
                SELECT (SELECT coalesce(pg_catalog.jsonb_object_agg(c.aname, r.j -> c.aname), '{}') FROM common c) AS v,
                       (SELECT coalesce(pg_catalog.jsonb_agg(c.aname ORDER BY c.attnum), '[]') FROM common c
                         WHERE coalesce(r.n ? c.aname, false)) AS z
                  FROM vm.rewrite_rows r WHERE r.relid = p_relid AND r.phase = 1),
            counted_before AS (SELECT x.v, x.z, pg_catalog.count(*) AS c FROM rows_before x GROUP BY x.v, x.z),
            counted_after AS (SELECT x.v, x.z, pg_catalog.count(*) AS c FROM rows_after x GROUP BY x.v, x.z)
            SELECT FROM counted_before b
              FULL JOIN counted_after a ON a.v = b.v AND a.z = b.z
             WHERE a.c IS DISTINCT FROM b.c) THEN
            RAISE EXCEPTION USING ERRCODE = 'VM005',
                MESSAGE = pg_catalog.format(
                    'the statement wrote the rows of the table %I.%I anew with other values, and the table has no primary key that is the same columns before and after the statement, so its rows cannot be paired to record each one that changed: give it a primary key in an earlier statement',
                    v_schema, v_table);
        END IF;
        DELETE FROM vm.rewrite_rows r WHERE r.relid = p_relid;
        DELETE FROM vm.rewrite_columns k WHERE k.relid = p_relid;
        RETURN 0;
    END IF;
    WITH cb AS (SELECT * FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = 0),
    ca AS (SELECT * FROM vm.rewrite_columns k WHERE k.relid = p_relid AND k.phase = 1),
    common AS (
        SELECT b.attnum, b.name AS bname, a.name AS aname
          FROM cb b JOIN ca a ON a.attnum = b.attnum
         WHERE NOT b.virtual AND NOT a.virtual),
    key_before AS (SELECT b.name, b.attnum FROM cb b WHERE b.key IS NOT NULL),
    key_after AS (SELECT a.name, a.attnum FROM ca a WHERE a.key IS NOT NULL),
    rb AS (
        SELECT r.id, r.j, r.n,
               (SELECT pg_catalog.jsonb_agg(r.j -> k.name ORDER BY k.attnum) FROM key_before k) AS k
          FROM vm.rewrite_rows r WHERE r.relid = p_relid AND r.phase = 0),
    ra AS (
        SELECT r.id, r.j, r.n,
               (SELECT pg_catalog.jsonb_agg(r.j -> k.name ORDER BY k.attnum) FROM key_after k) AS k
          FROM vm.rewrite_rows r WHERE r.relid = p_relid AND r.phase = 1),
    exact AS (SELECT b.id AS bid, a.id AS aid FROM rb b JOIN ra a ON a.k = b.k),
    -- The rows the exact pairing left: each key's values made text the
    -- way a number, a boolean and the string that reads the same agree
    -- (a number without trailing zeros, a boolean as `true`/`false`, a
    -- string that reads as a number as that number), for the loose
    -- pairing only.
    left_before AS (
        SELECT b.id, b.k,
               (SELECT pg_catalog.jsonb_agg(
                       CASE pg_catalog.jsonb_typeof(e.v)
                            WHEN 'number' THEN pg_catalog.to_jsonb(pg_catalog.trim_scale((e.v #>> '{}')::pg_catalog.numeric)::pg_catalog.text)
                            WHEN 'boolean' THEN pg_catalog.to_jsonb(e.v #>> '{}')
                            WHEN 'string' THEN
                                CASE WHEN pg_catalog.pg_input_is_valid(e.v #>> '{}', 'numeric')
                                     THEN pg_catalog.to_jsonb(pg_catalog.trim_scale((e.v #>> '{}')::pg_catalog.numeric)::pg_catalog.text)
                                     ELSE e.v END
                            ELSE e.v END
                       ORDER BY e.o)
                  FROM pg_catalog.jsonb_array_elements(b.k) WITH ORDINALITY e(v, o)) AS t
          FROM rb b
         WHERE NOT EXISTS (SELECT FROM exact e WHERE e.bid = b.id)),
    left_after AS (
        SELECT a.id, a.k,
               (SELECT pg_catalog.jsonb_agg(
                       CASE pg_catalog.jsonb_typeof(e.v)
                            WHEN 'number' THEN pg_catalog.to_jsonb(pg_catalog.trim_scale((e.v #>> '{}')::pg_catalog.numeric)::pg_catalog.text)
                            WHEN 'boolean' THEN pg_catalog.to_jsonb(e.v #>> '{}')
                            WHEN 'string' THEN
                                CASE WHEN pg_catalog.pg_input_is_valid(e.v #>> '{}', 'numeric')
                                     THEN pg_catalog.to_jsonb(pg_catalog.trim_scale((e.v #>> '{}')::pg_catalog.numeric)::pg_catalog.text)
                                     ELSE e.v END
                            ELSE e.v END
                       ORDER BY e.o)
                  FROM pg_catalog.jsonb_array_elements(a.k) WITH ORDINALITY e(v, o)) AS t
          FROM ra a
         WHERE NOT EXISTS (SELECT FROM exact e WHERE e.aid = a.id)),
    loose AS (
        SELECT b.id AS bid, a.id AS aid
          FROM (SELECT x.*, pg_catalog.count(*) OVER (PARTITION BY x.t) AS c FROM left_before x) b
          JOIN (SELECT x.*, pg_catalog.count(*) OVER (PARTITION BY x.t) AS c FROM left_after x) a
            ON a.t = b.t
         -- Paired when each is the only one so made on its side, and each
         -- key column is equal as JSON values or is a number or a boolean
         -- against a string.
         WHERE b.c = 1 AND a.c = 1
           AND pg_catalog.jsonb_array_length(b.k) = pg_catalog.jsonb_array_length(a.k)
           AND NOT EXISTS (
               SELECT FROM pg_catalog.jsonb_array_elements(b.k) WITH ORDINALITY x(v, o)
                 JOIN pg_catalog.jsonb_array_elements(a.k) WITH ORDINALITY y(v, o) ON y.o = x.o
                WHERE x.v <> y.v
                  AND NOT ((pg_catalog.jsonb_typeof(x.v) IN ('number', 'boolean') AND pg_catalog.jsonb_typeof(y.v) = 'string')
                           OR (pg_catalog.jsonb_typeof(y.v) IN ('number', 'boolean') AND pg_catalog.jsonb_typeof(x.v) = 'string')))),
    pairs AS (SELECT * FROM exact UNION ALL SELECT * FROM loose),
    entries AS (
        SELECT 'update' AS kind, a.j AS key_row, 1 AS side, b.j AS old, a.j AS new, b.n AS old_nulls, a.n AS new_nulls,
               (SELECT pg_catalog.jsonb_agg(c.aname ORDER BY c.attnum) FROM common c
                 WHERE (b.j -> c.bname) IS DISTINCT FROM (a.j -> c.aname)
                    OR coalesce(b.n ? c.bname, false) IS DISTINCT FROM coalesce(a.n ? c.aname, false)) AS changed
          FROM pairs p
          JOIN rb b ON b.id = p.bid
          JOIN ra a ON a.id = p.aid
        UNION ALL
        SELECT 'delete', b.j, 0, b.j, NULL, b.n, NULL, NULL
          FROM rb b WHERE NOT EXISTS (SELECT FROM pairs p WHERE p.bid = b.id)
        UNION ALL
        SELECT 'insert', a.j, 1, NULL, a.j, NULL, a.n, NULL
          FROM ra a WHERE NOT EXISTS (SELECT FROM pairs p WHERE p.aid = a.id))
    INSERT INTO vm.outbox (at, schema_name, table_name, kind, key, old, new, changed,
                           user_id, application, actor, request, migration, json_nulls)
    SELECT v_at, v_schema, v_table, e.kind,
           CASE WHEN e.side = 0
                THEN (SELECT pg_catalog.jsonb_object_agg(k.name, e.key_row -> k.name) FROM key_before k)
                ELSE (SELECT pg_catalog.jsonb_object_agg(k.name, e.key_row -> k.name) FROM key_after k) END,
           e.old, e.new, e.changed,
           v_who ->> 'user_id', v_who ->> 'application', v_who ->> 'actor', NULL, v_who ->> 'migration',
           vm.json_nulls(e.old_nulls, e.new_nulls)
      FROM entries e
     WHERE e.kind <> 'update' OR e.changed IS NOT NULL;
    GET DIAGNOSTICS v_made = ROW_COUNT;
    DELETE FROM vm.rewrite_rows r WHERE r.relid = p_relid;
    DELETE FROM vm.rewrite_columns k WHERE k.relid = p_relid;
    RETURN v_made;
END
$f$;
-- What is left of a statement's readings gone; with `p_end`, at the end
-- of a migration, the tables noted at its start too: nothing of the
-- rewrites is left in `vm`.
CREATE OR REPLACE FUNCTION vm.rewrite_done(p_token text, p_end boolean) RETURNS void
LANGUAGE plpgsql VOLATILE SECURITY DEFINER PARALLEL UNSAFE
SET search_path = pg_catalog, pg_temp
AS $f$
BEGIN
    PERFORM vm.rewrite_who(p_token);
    DELETE FROM vm.rewrite_rows;
    DELETE FROM vm.rewrite_columns;
    IF p_end THEN
        DELETE FROM vm.rewrite_nodes;
    END IF;
END
$f$;

