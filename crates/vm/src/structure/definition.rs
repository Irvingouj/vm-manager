//! The definition (blackbox/CONTRACT.md, "The definition"): one TypeScript
//! module for `drizzle-orm/pg-core`, the same bytes for the same structure.
//!
//! Its bindings of its own begin with `$` (`$pg`, the namespace of
//! `drizzle-orm/pg-core`; `$unsupported`; `$t`, a table's columns in its
//! extra config), which no name [`naming`] makes can, so no export
//! shadows them; and `sql`, the tag of `drizzle-orm`, which the contract's
//! form needs by that name, so `sql` is taken before any export is given.
//! Every other identifier is an export or a key [`naming`] made. Every name
//! and expression of the shared database's is written by
//! [`ts_text::literal`]. Nothing of the shared database's is written into a
//! comment.
//!
//! Written in this order: the two first lines, the imports, the custom
//! type of what cannot be expressed, the schemas other than `public`, the
//! enums, then the tables and views; each list by schema, then name.

use std::collections::BTreeMap;

use tokio::time::Instant;

/// Appends a formatted line to a `String`.
macro_rules! say {
    ($text:expr, $($arg:tt)*) => {{
        $text.push_str(&format!($($arg)*));
        $text.push('\n');
    }};
}

/// Appends formatted text to a `String`.
macro_rules! put {
    ($text:expr, $($arg:tt)*) => {
        $text.push_str(&format!($($arg)*))
    };
}

use super::naming::{Given, camel};
use super::ts_text::{Form, literal};
use super::{Failed, Generated, Identity, Kind, Relation, Scalar, Structure, Type, Unsupported};

/// The definition's first line.
pub const FIRST_LINE: &str = "// Generated by vm pull. Do not edit.";

/// Postgres's own types the definition expresses, by their OIDs (the same
/// on every server: they are fixed in Postgres's source).
pub(super) mod oid {
    pub const BOOL: u32 = 16;
    pub const INT8: u32 = 20;
    pub const INT2: u32 = 21;
    pub const INT4: u32 = 23;
    pub const TEXT: u32 = 25;
    pub const JSON: u32 = 114;
    pub const FLOAT4: u32 = 700;
    pub const FLOAT8: u32 = 701;
    pub const BPCHAR: u32 = 1042;
    pub const VARCHAR: u32 = 1043;
    pub const DATE: u32 = 1082;
    pub const TIME: u32 = 1083;
    pub const TIMESTAMP: u32 = 1114;
    pub const TIMESTAMPTZ: u32 = 1184;
    pub const INTERVAL: u32 = 1186;
    pub const TIMETZ: u32 = 1266;
    pub const NUMERIC: u32 = 1700;
    pub const UUID: u32 = 2950;
    pub const JSONB: u32 = 3802;
}

/// Writes the definition of `structure` under `resource`'s name, with its
/// `fingerprint`, and lists the columns it cannot express. Past `limit`
/// bytes it stops: too large; past `deadline`, looked at after each
/// relation, it stops too, so that it ends by itself even when nobody waits
/// for it any more.
pub(super) fn write(
    structure: &Structure,
    resource: &str,
    fingerprint: &str,
    limit: usize,
    deadline: Instant,
) -> Result<(String, Vec<Unsupported>), Failed> {
    let names = Names::of(structure);
    let mut unsupported = Vec::new();
    let mut body = String::new();
    let mut uses_sql = false;
    let mut uses_custom = false;

    for (schema, export) in &names.schemas {
        say!(
            body,
            "export const {export} = $pg.pgSchema({});",
            literal(schema, Form::String)
        );
    }
    if !names.schemas.is_empty() {
        body.push('\n');
    }
    let mut any_enum = false;
    for (index, e) in structure.enums.iter().enumerate() {
        let Some(export) = names.enums.get(&index) else {
            continue;
        };
        let labels: Vec<String> = e.labels.iter().map(|l| literal(l, Form::String)).collect();
        say!(
            body,
            "export const {export} = {}({}, [{}]);",
            owner(&names, &e.schema, "pgEnum", "enum"),
            literal(&e.name, Form::String),
            labels.join(", ")
        );
        any_enum = true;
    }
    if any_enum {
        body.push('\n');
    }
    for (index, relation) in structure.relations.iter().enumerate() {
        let Some(export) = names.relations.get(index) else {
            continue;
        };
        let written = relation_text(structure, &names, relation, export, &mut unsupported);
        uses_sql |= written.uses_sql;
        uses_custom |= written.uses_custom;
        body.push_str(&written.text);
        body.push('\n');
        if body.len() > limit {
            return Err(Failed::TooLarge);
        }
        if Instant::now() > deadline {
            return Err(Failed::Time);
        }
    }

    let mut text = String::with_capacity(body.len() + 512);
    say!(text, "{FIRST_LINE}");
    say!(text, "{}", super::second_line(resource, fingerprint));
    if uses_sql {
        text.push_str("import { sql } from \"drizzle-orm\";\n");
    }
    text.push_str("import * as $pg from \"drizzle-orm/pg-core\";\n\n");
    if uses_custom {
        text.push_str(
            "// A type the definition cannot express: its values are typed `unknown`.\n\
             const $unsupported = (name: string) => $pg.customType<{ data: unknown }>({ dataType: () => name });\n\n",
        );
    }
    text.push_str(&body);
    // One line end at the end, not two.
    if text.ends_with("\n\n") {
        text.pop();
    }
    if text.len() > limit {
        return Err(Failed::TooLarge);
    }
    Ok((text, unsupported))
}

/// Every name the definition gives.
struct Names {
    /// Each schema other than `public` that holds a listed relation or
    /// enum, and its export: by schema.
    schemas: BTreeMap<String, String>,
    /// Each relation's export, by its index in [`Structure::relations`].
    relations: Vec<String>,
    /// Each expressed enum's export, by its index in [`Structure::enums`].
    enums: BTreeMap<usize, String>,
    /// Each table's export, by (schema, name): what a foreign key refers to.
    tables: BTreeMap<(String, String), String>,
}

impl Names {
    /// The exports, given in the contract's order: the schemas first, then
    /// tables, views and enums together by schema then name.
    fn of(structure: &Structure) -> Self {
        let mut given = Given::new(&["sql"]);
        let mut schemas = BTreeMap::new();
        let expressed = |labels: &[String]| !labels.is_empty();
        let other_schemas = structure
            .relations
            .iter()
            .map(|r| &r.schema)
            .chain(
                structure
                    .enums
                    .iter()
                    .filter(|e| expressed(&e.labels))
                    .map(|e| &e.schema),
            )
            .filter(|schema| schema.as_str() != "public");
        for schema in other_schemas {
            if !schemas.contains_key(schema.as_str()) {
                schemas.insert(schema.clone(), String::new());
            }
        }
        for (schema, export) in &mut schemas {
            *export = given.give(camel(&[schema, "Schema"]));
        }
        // Tables, views and enums by (schema, name): a relation and an
        // enum never share both, as each relation has a type of its name.
        let mut objects: Vec<(&str, &str, Object)> = structure
            .relations
            .iter()
            .enumerate()
            .map(|(index, r)| (r.schema.as_str(), r.name.as_str(), Object::Relation(index)))
            .chain(
                structure
                    .enums
                    .iter()
                    .enumerate()
                    .filter(|(_, e)| expressed(&e.labels))
                    .map(|(index, e)| (e.schema.as_str(), e.name.as_str(), Object::Enum(index))),
            )
            .collect();
        objects.sort_by(|a, b| (a.0, a.1).cmp(&(b.0, b.1)));
        let mut relations = vec![String::new(); structure.relations.len()];
        let mut enums = BTreeMap::new();
        let mut tables = BTreeMap::new();
        for (schema, name, object) in objects {
            let wanted = if schema == "public" {
                camel(&[name])
            } else {
                camel(&[schema, name])
            };
            let export = given.give(wanted);
            match object {
                Object::Relation(index) => {
                    if let Some(relation) = structure.relations.get(index)
                        && relation.kind == Kind::Table
                    {
                        // A second copy of a short name, for foreign keys.
                        tables.insert((schema.to_owned(), name.to_owned()), export.clone());
                    }
                    if let Some(slot) = relations.get_mut(index) {
                        *slot = export;
                    }
                }
                Object::Enum(index) => {
                    enums.insert(index, export);
                }
            }
        }
        Self {
            schemas,
            relations,
            enums,
            tables,
        }
    }
}

#[derive(Clone, Copy)]
enum Object {
    Relation(usize),
    Enum(usize),
}

/// What makes an object of `schema`: `$pg.<public>` in `public`, else
/// `<schema export>.<other>`.
fn owner(names: &Names, schema: &str, public: &str, other: &str) -> String {
    match names.schemas.get(schema) {
        Some(export) if schema != "public" => format!("{export}.{other}"),
        _ => format!("$pg.{public}"),
    }
}

/// One relation's text.
struct Written {
    text: String,
    uses_sql: bool,
    uses_custom: bool,
}

fn relation_text(
    structure: &Structure,
    names: &Names,
    relation: &Relation,
    export: &str,
    unsupported: &mut Vec<Unsupported>,
) -> Written {
    let (public, other) = match relation.kind {
        Kind::Table => ("pgTable", "table"),
        Kind::View => ("pgView", "view"),
        Kind::MaterializedView => ("pgMaterializedView", "materializedView"),
    };
    let keys = keys_of(relation);
    let key_of = |column: &str| {
        relation
            .columns
            .iter()
            .position(|c| c.name == column)
            .and_then(|index| keys.get(index))
    };
    let single_key = relation
        .primary_key
        .as_ref()
        .and_then(|k| match k.columns.as_slice() {
            [only] => Some(only.as_str()),
            _ => None,
        });

    let mut written = Written {
        text: String::new(),
        uses_sql: false,
        uses_custom: false,
    };
    let text = &mut written.text;
    say!(
        text,
        "export const {export} = {}({}, {{",
        owner(names, &relation.schema, public, other),
        literal(&relation.name, Form::String)
    );
    for (column, key) in relation.columns.iter().zip(&keys) {
        let mut line = format!("  {key}: ");
        let serial = is_serial(&column.ty, column);
        match builder(names, &column.ty, serial) {
            Some((callee, options)) => {
                put!(
                    line,
                    "{callee}({}{options})",
                    literal(&column.name, Form::String)
                );
                if column.ty.array {
                    line.push_str(".array()");
                }
            }
            None => {
                written.uses_custom = true;
                put!(
                    line,
                    "$unsupported({})({})",
                    literal(&column.printed, Form::String),
                    literal(&column.name, Form::String)
                );
                unsupported.push(Unsupported {
                    schema: relation.schema.clone(),
                    table: relation.name.clone(),
                    column: column.name.clone(),
                    printed: column.printed.clone(),
                });
            }
        }
        let primary = single_key == Some(column.name.as_str());
        if primary {
            line.push_str(".primaryKey()");
        } else if column.not_null {
            line.push_str(".notNull()");
        }
        if let Some(expression) = &column.expression {
            if column.generated != Generated::None {
                written.uses_sql = true;
                put!(
                    line,
                    ".generatedAlwaysAs(sql`{}`)",
                    literal(expression, Form::Template)
                );
            } else if !serial {
                written.uses_sql = true;
                put!(
                    line,
                    ".default(sql`{}`)",
                    literal(expression, Form::Template)
                );
            }
        }
        match column.identity {
            Identity::None => {}
            Identity::Always => line.push_str(".generatedAlwaysAsIdentity()"),
            Identity::ByDefault => line.push_str(".generatedByDefaultAsIdentity()"),
        }
        line.push_str(",\n");
        text.push_str(&line);
    }

    let mut extra: Vec<String> = Vec::new();
    let columns_of = |columns: &[String]| -> Option<String> {
        let keys: Option<Vec<String>> = columns
            .iter()
            .map(|c| key_of(c).map(|k| format!("$t.{k}")))
            .collect();
        keys.map(|k| k.join(", "))
    };
    if let Some(key) = &relation.primary_key
        && key.columns.len() > 1
        && let Some(columns) = columns_of(&key.columns)
    {
        extra.push(format!(
            "$pg.primaryKey({{ name: {}, columns: [{columns}] }})",
            literal(&key.name, Form::String)
        ));
    }
    for unique in &relation.uniques {
        if let Some(columns) = columns_of(&unique.columns) {
            extra.push(format!(
                "$pg.unique({}).on({columns})",
                literal(&unique.name, Form::String)
            ));
        }
    }
    for foreign in &relation.foreign_keys {
        let Some(columns) = columns_of(&foreign.columns) else {
            continue;
        };
        let referred = if foreign.schema == relation.schema && foreign.table == relation.name {
            columns_of(&foreign.referred)
        } else {
            referred_columns(
                structure,
                names,
                &foreign.schema,
                &foreign.table,
                &foreign.referred,
            )
        };
        // A table that is not listed (a partition) cannot be referred to.
        let Some(referred) = referred else {
            continue;
        };
        extra.push(format!(
            "$pg.foreignKey({{ name: {}, columns: [{columns}], foreignColumns: [{referred}] }}).onDelete({}).onUpdate({})",
            literal(&foreign.name, Form::String),
            literal(foreign.on_delete.name(), Form::String),
            literal(foreign.on_update.name(), Form::String),
        ));
    }
    if relation.kind == Kind::Table && !extra.is_empty() {
        // The return type is written so that two tables whose foreign keys
        // refer to each other do not make each other's type circular.
        text.push_str("}, ($t): $pg.PgTableExtraConfigValue[] => [\n");
        for item in &extra {
            say!(text, "  {item},");
        }
        text.push_str("]);\n");
    } else if relation.kind == Kind::Table {
        text.push_str("});\n");
    } else {
        text.push_str("}).existing();\n");
    }
    written
}

/// `<export>.<key>, ...` of the columns `columns` of the table
/// `schema`.`table`, if it is listed and has them all.
fn referred_columns(
    structure: &Structure,
    names: &Names,
    schema: &str,
    table: &str,
    columns: &[String],
) -> Option<String> {
    let export = names.tables.get(&(schema.to_owned(), table.to_owned()))?;
    let relation = structure
        .relations
        .iter()
        .find(|r| r.schema == schema && r.name == table)?;
    // Its keys, as its own text gives them.
    let keys = keys_of(relation);
    let referred: Option<Vec<String>> = columns
        .iter()
        .map(|column| {
            let index = relation.columns.iter().position(|c| &c.name == column)?;
            keys.get(index).map(|key| format!("{export}.{key}"))
        })
        .collect();
    referred.map(|r| r.join(", "))
}

/// The key of each column of `relation`, in the order of its columns,
/// given in the order of the columns' names.
fn keys_of(relation: &Relation) -> Vec<String> {
    let mut by_name: Vec<(usize, &str)> = relation
        .columns
        .iter()
        .enumerate()
        .map(|(index, c)| (index, c.name.as_str()))
        .collect();
    by_name.sort_by(|a, b| a.1.cmp(b.1));
    let mut given = Given::new(&[]);
    let mut keys = vec![String::new(); relation.columns.len()];
    for (index, name) in by_name {
        if let Some(slot) = keys.get_mut(index) {
            *slot = given.give(camel(&[name]));
        }
    }
    keys
}

/// Whether the column is a `serial`, `smallserial` or `bigserial`: one of
/// Postgres's integers, no array, no identity, no generation, and a
/// default that takes the next value of a sequence.
pub(super) fn is_serial(ty: &Type, column: &super::Column) -> bool {
    let integer = matches!(ty.scalar, Scalar::Oid(oid::INT2 | oid::INT4 | oid::INT8));
    let next_value = column
        .expression
        .as_deref()
        .is_some_and(|e| e.starts_with("nextval('") && e.ends_with("'::regclass)"));
    integer
        && !ty.array
        && column.identity == Identity::None
        && column.generated == Generated::None
        && next_value
}

/// The column builder of `ty` and its options (`, { ... }`), or `None`
/// when the definition cannot express it.
fn builder(names: &Names, ty: &Type, serial: bool) -> Option<(String, String)> {
    let modifier = ty.modifier;
    let id = match ty.scalar {
        // An enum with no label has no export: it cannot be expressed.
        Scalar::Enum(index) => return Some((names.enums.get(&index)?.clone(), String::new())),
        Scalar::Oid(id) => id,
    };
    let plain = |callee: &str| Some((format!("$pg.{callee}"), String::new()));
    let with = |callee: &str, options: Vec<String>| {
        let options = if options.is_empty() {
            String::new()
        } else {
            format!(", {{ {} }}", options.join(", "))
        };
        Some((format!("$pg.{callee}"), options))
    };
    // A modifier of -1 is none.
    let precision = (modifier >= 0).then_some(modifier);
    match id {
        oid::INT2 if serial => plain("smallserial"),
        oid::INT4 if serial => plain("serial"),
        oid::INT8 if serial => with("bigserial", vec!["mode: \"number\"".into()]),
        oid::INT2 => plain("smallint"),
        oid::INT4 => plain("integer"),
        oid::INT8 => with("bigint", vec!["mode: \"number\"".into()]),
        oid::BOOL => plain("boolean"),
        oid::TEXT => plain("text"),
        oid::VARCHAR | oid::BPCHAR => {
            let callee = if id == oid::VARCHAR {
                "varchar"
            } else {
                "char"
            };
            let length = modifier.checked_sub(4).filter(|n| *n >= 0);
            with(
                callee,
                length.map(|n| format!("length: {n}")).into_iter().collect(),
            )
        }
        oid::NUMERIC => {
            let options = match modifier.checked_sub(4).filter(|n| *n >= 0) {
                Some(packed) => {
                    let digits = (packed >> 16) & 0xffff;
                    // Eleven bits, signed: Postgres 15 allows a scale below 0.
                    let raw = packed & 0x7ff;
                    let scale = if raw & 0x400 != 0 { raw - 0x800 } else { raw };
                    vec![format!("precision: {digits}"), format!("scale: {scale}")]
                }
                None => Vec::new(),
            };
            with("numeric", options)
        }
        oid::FLOAT4 => plain("real"),
        oid::FLOAT8 => plain("doublePrecision"),
        oid::DATE => with("date", vec!["mode: \"string\"".into()]),
        oid::TIME | oid::TIMETZ => {
            let mut options: Vec<String> = precision
                .map(|p| format!("precision: {p}"))
                .into_iter()
                .collect();
            if id == oid::TIMETZ {
                options.push("withTimezone: true".into());
            }
            with("time", options)
        }
        oid::TIMESTAMP | oid::TIMESTAMPTZ => {
            let mut options: Vec<String> = precision
                .map(|p| format!("precision: {p}"))
                .into_iter()
                .collect();
            if id == oid::TIMESTAMPTZ {
                options.push("withTimezone: true".into());
            }
            options.push("mode: \"string\"".into());
            with("timestamp", options)
        }
        oid::INTERVAL => with("interval", interval_options(modifier)),
        oid::UUID => plain("uuid"),
        oid::JSON => plain("json"),
        oid::JSONB => plain("jsonb"),
        _ => None,
    }
}

/// An interval's fields and precision, from its modifier (Postgres's
/// `INTERVAL_RANGE` and `INTERVAL_PRECISION`), as Drizzle names them.
fn interval_options(modifier: i32) -> Vec<String> {
    const MONTH: i32 = 1 << 1;
    const YEAR: i32 = 1 << 2;
    const DAY: i32 = 1 << 3;
    const HOUR: i32 = 1 << 10;
    const MINUTE: i32 = 1 << 11;
    const SECOND: i32 = 1 << 12;
    if modifier < 0 {
        return Vec::new();
    }
    let range = (modifier >> 16) & 0x7fff;
    let precision = modifier & 0xffff;
    let fields = match range {
        YEAR => Some("year"),
        MONTH => Some("month"),
        DAY => Some("day"),
        HOUR => Some("hour"),
        MINUTE => Some("minute"),
        SECOND => Some("second"),
        r if r == YEAR | MONTH => Some("year to month"),
        r if r == DAY | HOUR => Some("day to hour"),
        r if r == DAY | HOUR | MINUTE => Some("day to minute"),
        r if r == DAY | HOUR | MINUTE | SECOND => Some("day to second"),
        r if r == HOUR | MINUTE => Some("hour to minute"),
        r if r == HOUR | MINUTE | SECOND => Some("hour to second"),
        r if r == MINUTE | SECOND => Some("minute to second"),
        _ => None,
    };
    let mut options: Vec<String> = fields
        .map(|f| format!("fields: {}", literal(f, Form::String)))
        .into_iter()
        .collect();
    if precision != 0xffff {
        options.push(format!("precision: {precision}"));
    }
    options
}
