//! The stand-in's statements (blackbox/CONTRACT.md, "The local loop: What a
//! pull writes"): what makes an empty database of the same structure, one
//! statement a text, each ending with `;`, made from the [`Structure`] the
//! definition is made from, and the same text for the same structure.
//!
//! In order: each schema but `public` and each enum; each relation as an
//! ordinary table with its columns, identities, serials, generated columns,
//! primary key and unique constraints; each default; each foreign key
//! between listed tables. Every name is quoted, every label is a literal,
//! and a default's or a generation's expression is taken as the catalog
//! printed it (with nothing on the search path, so its names are
//! qualified). Nothing else of the database's is in it: no row, privilege,
//! owner, comment or connection.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use super::definition::{is_serial, oid};
use super::{Action, Generated, Identity, Relation, Scalar, Structure};

/// The first type OID Postgres gives to an object made in a database: below
/// it every type is Postgres's own, with the same OID on every server.
const FIRST_NORMAL_OID: u32 = 16384;

/// The longest name Postgres keeps, in bytes.
const NAME_BYTES: usize = 63;

/// The stand-in's statements of `structure`.
pub(super) fn statements(structure: &Structure) -> Vec<String> {
    let mut statements = Vec::new();
    let schemas: BTreeSet<&str> = structure
        .relations
        .iter()
        .map(|r| r.schema.as_str())
        .chain(structure.enums.iter().map(|e| e.schema.as_str()))
        .filter(|schema| *schema != "public")
        .collect();
    for schema in schemas {
        statements.push(format!("CREATE SCHEMA {};", ident(schema)));
    }
    for e in &structure.enums {
        let labels: Vec<String> = e.labels.iter().map(|l| literal(l)).collect();
        statements.push(format!(
            "CREATE TYPE {}.{} AS ENUM ({});",
            ident(&e.schema),
            ident(&e.name),
            labels.join(", ")
        ));
    }
    for relation in &structure.relations {
        statements.push(table(structure, relation));
    }
    for relation in &structure.relations {
        for column in &relation.columns {
            let Some(expression) = column.expression.as_deref() else {
                continue;
            };
            if column.generated != Generated::None || serial(relation, column).is_some() {
                continue;
            }
            statements.push(format!(
                "ALTER TABLE {}.{} ALTER COLUMN {} SET DEFAULT {expression};",
                ident(&relation.schema),
                ident(&relation.name),
                ident(&column.name)
            ));
        }
    }
    let listed: BTreeSet<(&str, &str)> = structure
        .relations
        .iter()
        .map(|r| (r.schema.as_str(), r.name.as_str()))
        .collect();
    for relation in &structure.relations {
        for key in &relation.foreign_keys {
            if !listed.contains(&(key.schema.as_str(), key.table.as_str())) {
                continue;
            }
            let mut statement = format!(
                "ALTER TABLE {}.{} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {}.{} ({})",
                ident(&relation.schema),
                ident(&relation.name),
                ident(&key.name),
                idents(&key.columns),
                ident(&key.schema),
                ident(&key.table),
                idents(&key.referred)
            );
            for (clause, action) in [("UPDATE", key.on_update), ("DELETE", key.on_delete)] {
                if let Some(words) = action_words(action) {
                    write!(statement, " ON {clause} {words}").ok();
                }
            }
            statement.push(';');
            statements.push(statement);
        }
    }
    statements
}

/// The `CREATE TABLE` of `relation`, whatever its kind.
fn table(structure: &Structure, relation: &Relation) -> String {
    let mut lines: Vec<String> = Vec::with_capacity(relation.columns.len().saturating_add(2));
    for column in &relation.columns {
        let mut line = format!("  {} ", ident(&column.name));
        match serial(relation, column) {
            Some(kind) => line.push_str(kind),
            None => line.push_str(&type_of(structure, column)),
        }
        if column.not_null {
            line.push_str(" NOT NULL");
        }
        match column.identity {
            Identity::None => {}
            Identity::Always => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
            Identity::ByDefault => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        }
        if let Some(expression) = column.expression.as_deref() {
            match column.generated {
                Generated::None => {}
                Generated::Stored => {
                    write!(line, " GENERATED ALWAYS AS ({expression}) STORED").ok();
                }
                Generated::Virtual => {
                    write!(line, " GENERATED ALWAYS AS ({expression}) VIRTUAL").ok();
                }
            }
        }
        lines.push(line);
    }
    if let Some(key) = &relation.primary_key {
        lines.push(format!(
            "  CONSTRAINT {} PRIMARY KEY ({})",
            ident(&key.name),
            idents(&key.columns)
        ));
    }
    for key in &relation.uniques {
        lines.push(format!(
            "  CONSTRAINT {} UNIQUE ({})",
            ident(&key.name),
            idents(&key.columns)
        ));
    }
    if lines.is_empty() {
        format!(
            "CREATE TABLE {}.{} ();",
            ident(&relation.schema),
            ident(&relation.name)
        )
    } else {
        format!(
            "CREATE TABLE {}.{} (\n{}\n);",
            ident(&relation.schema),
            ident(&relation.name),
            lines.join(",\n")
        )
    }
}

/// The serial kind of `column` when it is one as Postgres makes it: one of
/// Postgres's integers, not null, whose default takes the next value of the
/// sequence a `serial` of that table and column is given. A default on
/// another sequence is set as any default is.
fn serial(relation: &Relation, column: &super::Column) -> Option<&'static str> {
    if !column.not_null || !is_serial(&column.ty, column) {
        return None;
    }
    let sequence = format!("{}_{}_seq", relation.name, column.name);
    let expression = column.expression.as_deref()?;
    let plain = format!(".{sequence}'::regclass)");
    let quoted = format!(".\"{}\"'::regclass)", sequence.replace('"', "\"\""));
    let names_it = sequence.len() <= NAME_BYTES
        && (expression.ends_with(&plain) || expression.ends_with(&quoted));
    if !names_it {
        return None;
    }
    match column.ty.scalar {
        Scalar::Oid(oid::INT2) => Some("smallserial"),
        Scalar::Oid(oid::INT4) => Some("serial"),
        Scalar::Oid(oid::INT8) => Some("bigserial"),
        _ => None,
    }
}

/// The type of a column in the stand-in: Postgres's own as printed, an enum
/// listed by its name, anything else `text` (an array of it `text[]`).
fn type_of(structure: &Structure, column: &super::Column) -> String {
    let suffix = if column.ty.array { "[]" } else { "" };
    match column.ty.scalar {
        Scalar::Oid(id) if id != 0 && id < FIRST_NORMAL_OID => column.printed.clone(),
        Scalar::Enum(index) => match structure.enums.get(index) {
            Some(e) => format!("{}.{}{suffix}", ident(&e.schema), ident(&e.name)),
            None => format!("text{suffix}"),
        },
        Scalar::Oid(_) => format!("text{suffix}"),
    }
}

fn action_words(action: Action) -> Option<&'static str> {
    match action {
        Action::Nothing => None,
        Action::Restrict => Some("RESTRICT"),
        Action::Cascade => Some("CASCADE"),
        Action::SetNull => Some("SET NULL"),
        Action::SetDefault => Some("SET DEFAULT"),
    }
}

fn idents(names: &[String]) -> String {
    let quoted: Vec<String> = names.iter().map(|n| ident(n)).collect();
    quoted.join(", ")
}

/// `name` as a quoted identifier: in double quotes, a double quote doubled;
/// with a control character, in the Unicode escape form, so that no line
/// end of a name's reaches the text raw.
pub fn ident(name: &str) -> String {
    if !name.chars().any(char::is_control) {
        return format!("\"{}\"", name.replace('"', "\"\""));
    }
    let mut text = String::with_capacity(name.len().saturating_add(6));
    text.push_str("U&\"");
    for c in name.chars() {
        match c {
            '"' => text.push_str("\"\""),
            '\\' => text.push_str("\\\\"),
            c if c.is_control() => {
                write!(text, "\\{:04X}", u32::from(c)).ok();
            }
            c => text.push(c),
        }
    }
    text.push('"');
    text
}

/// `text` as a string literal: in single quotes, a single quote doubled;
/// with a backslash or a control character, in the escape form.
pub fn literal(text: &str) -> String {
    if !text.chars().any(|c| c.is_control() || c == '\\') {
        return format!("'{}'", text.replace('\'', "''"));
    }
    let mut out = String::with_capacity(text.len().saturating_add(4));
    out.push_str("E'");
    for c in text.chars() {
        match c {
            '\'' => out.push_str("''"),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => {
                write!(out, "\\u{:04X}", u32::from(c)).ok();
            }
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}
