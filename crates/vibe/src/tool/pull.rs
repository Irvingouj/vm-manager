//! `vibe pull <resource> [--project <directory>] [--json]` (blackbox/
//! CONTRACT.md, "Pulling a Resource's structure: The tool", and "Pulling a
//! Storage Resource, checking and deploying").
//!
//! The Resource's name is checked on the command line, before it is part
//! of a path. The project is checked first (its `manifest.ts`), then every
//! file a pull of either kind writes, and every path on the way to them
//! (each at its path written by the tool, and no link followed): a
//! hand-written `schema.ts`, `index.ts` or `storage.json`, or a link,
//! ends the pull before the platform is asked anything, whatever kind the
//! Resource turns out to be. Then the structure is asked for, which says
//! the kind, then the kind's files are checked once more just before
//! writing and written: each compared with what is there first, so that an
//! unchanged file is not touched (its bytes and modification time stay),
//! and otherwise written whole to a file of its own beside it, synced, and
//! renamed over it. Nothing is written when the pull is refused or fails,
//! nor over a file the tool did not write.
//!
//! A database's pull writes `schema.ts`, `index.ts` and `standin.sql`; a
//! Storage Resource's writes the one file `storage.json` (its `generated`
//! is the marker, and a file that does not hold it is `not-generated`
//! whatever its size).
//!
//! `vibe deploy` pulls each declared Resource again the same way
//! ([`Pull`]), its messages naming it.
//!
//! The definition is file content, not words: it is written as answered
//! (once its first line shows it is a definition). What is printed of the
//! installation's (the fingerprint, the Access level, the unsupported
//! columns) reaches words only through [`Theirs`].

use std::fs::{self, File};
use std::io::{self, ErrorKind, Read};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use super::credential_file::{Kept, Place};
use super::test_users::{self, TestUsersFile};
use super::theirs::Theirs;
use super::{
    Done, Ending, Output, file_problem as project_file, get_signed_in, project_of, read_kept,
    shaped, unexpected, write_whole,
};
use crate::resources::is_resource_name;
use crate::structure::{FIRST_LINE as SCHEMA_FIRST_LINE, is_fingerprint};

/// `vibe pull`.
#[derive(clap::Args)]
pub struct PullArgs {
    /// The Resource whose structure to pull.
    #[arg(value_parser = resource_name)]
    pub resource: String,
    /// The project to write into; without it, the current directory.
    #[arg(long)]
    pub project: Option<PathBuf>,
    #[command(flatten)]
    pub output: Output,
}

/// The first line of the generated link.
pub(super) const INDEX_FIRST_LINE: &str = "// Generated. Do not edit.";

/// The first line of the stand-in's statements.
pub(super) const STANDIN_FIRST_LINE: &str = "-- Generated by vibe pull. Do not edit.";

/// The `generated` member of `storage.json`: a Storage Resource's one
/// generated file holds it, and one without it was not written by the tool.
pub(super) const STORAGE_GENERATED: &str = "vibe pull. Do not edit.";

/// The largest generated file read to compare: above what a pull answers.
const MAX_FILE_BYTES: u64 = 16 * 1024 * 1024;

/// The largest `storage.json` that can be the tool's own: a file larger
/// than this is not one, whatever it begins with, for every command alike
/// (blackbox/CONTRACT.md, "Pulling a Storage Resource, checking and
/// deploying").
pub(super) const STORAGE_FILE_BYTES: u64 = 64 * 1024;

fn resource_name(text: &str) -> Result<String, String> {
    if is_resource_name(text) {
        Ok(text.to_owned())
    } else {
        Err("not a Resource's name: 1 to 63 lower-case letters, digits and underscores, starting with a letter".into())
    }
}

/// What `GET /v1/resources/<name>/structure` answers: a database's
/// structure, or a Storage Resource's name and kind alone.
#[derive(Deserialize)]
struct Answered {
    resource: String,
    kind: String,
    your_access: Theirs,
    /// Written on one line into the stand-in's file; never printed.
    contact: String,
    /// A database's; absent on a Storage Resource.
    #[serde(default)]
    fingerprint: Option<String>,
    /// A database's; never printed. Absent on a Storage Resource.
    #[serde(default)]
    schema_ts: Option<String>,
    #[serde(default)]
    unsupported: Vec<UnsupportedColumn>,
    /// A database's; never printed. Absent on a Storage Resource.
    #[serde(default)]
    standin_sql: Vec<String>,
    /// A database's: the relations not shown because no login of the
    /// Resource reaches them. Absent on a Storage Resource.
    #[serde(default)]
    hidden: Option<u64>,
}

#[derive(Deserialize, Serialize)]
struct UnsupportedColumn {
    schema: Theirs,
    table: Theirs,
    column: Theirs,
    #[serde(rename = "type")]
    printed: Theirs,
}

/// How a generated file shows that the tool wrote it.
enum Marker {
    /// It begins with this line (followed by a line end, or nothing).
    FirstLine(&'static str),
    /// It is a JSON object whose `generated` is this text.
    Generated(&'static str),
}

/// One generated file of the project.
struct Generated {
    /// Relative to the project, as printed.
    shown: String,
    path: PathBuf,
    marker: Marker,
}

/// A pull of one Resource into a project: every file either kind writes,
/// checked before the platform is asked ([`Pull::prepare`]), and the
/// kind's files written once the structure (and so the kind) is known
/// ([`Pull::fetch`]).
pub(super) struct Pull<'a> {
    project: &'a Path,
    name: &'a str,
    /// The command, as its messages name it: `vibe pull`, `vibe deploy`.
    command: &'a str,
    folder: PathBuf,
    /// A database's pull's three files.
    database: [Generated; 3],
    /// A Storage Resource's pull's one file.
    storage: Generated,
    /// What is done with `vibe.dev.json` ([`Kind`]).
    kind: Kind,
}

/// Which pull: `vibe pull`'s, or a deploy's.
pub(super) enum Kind {
    /// `vibe pull`: every file written when its content changed, and the
    /// Builder's own Grant copied into the test Users file, read before
    /// (`None` when it is not there).
    Pull(Option<TestUsersFile>),
    /// A deploy's: the stand-in written only with a changed definition,
    /// the test Users file never touched.
    Deploy,
}

/// What a pull did.
pub(super) struct Pulled {
    /// `Some` for a database, with its fingerprint; `None` for a Storage
    /// Resource, which has no structure.
    pub fingerprint: Option<String>,
    /// Whether the Resource is a Storage Resource (its words say so).
    pub storage: bool,
    /// A database's `hidden`: relations no login of the Resource reaches.
    hidden: Option<u64>,
    /// Whom to ask, as the Resource's answer names them.
    contact: Theirs,
    your_access: Theirs,
    unsupported: Vec<UnsupportedColumn>,
    /// Each file, by its path relative to the project, and whether it was
    /// written.
    pub files: Vec<(String, bool)>,
    /// `vibe pull`'s: what was done with the test Users file.
    test_users: Option<Value>,
}

impl<'a> Pull<'a> {
    /// The pull of `name` into `project`: every file a pull of either kind
    /// writes, checked before anything is asked of the platform (a
    /// hand-written one, or a link at any of them, ends the pull with its
    /// reason there), and what is done with the test Users file.
    pub(super) fn prepare(
        project: &'a Path,
        name: &'a str,
        command: &'a str,
        deploy: bool,
    ) -> Result<Self, Ending> {
        let folder = project.join("resources").join(name);
        let database = [
            Generated {
                shown: format!("resources/{name}/schema.ts"),
                path: folder.join("schema.ts"),
                marker: Marker::FirstLine(SCHEMA_FIRST_LINE),
            },
            Generated {
                shown: format!("resources/{name}/index.ts"),
                path: folder.join("index.ts"),
                marker: Marker::FirstLine(INDEX_FIRST_LINE),
            },
            Generated {
                shown: format!("resources/{name}/standin.sql"),
                path: folder.join("standin.sql"),
                marker: Marker::FirstLine(STANDIN_FIRST_LINE),
            },
        ];
        let storage = Generated {
            shown: format!("resources/{name}/storage.json"),
            path: folder.join("storage.json"),
            marker: Marker::Generated(STORAGE_GENERATED),
        };
        // Before the platform is asked anything (blackbox/CONTRACT.md,
        // "Pulling a Storage Resource, checking and deploying"): every file
        // either kind writes, whatever the Resource turns out to be, and
        // every path on the way to them. A pull that is refused for want of
        // a Grant, or made signed out, ends here first when the project has
        // something the pull may not write over.
        no_link(
            project,
            name,
            database.iter().chain(std::iter::once(&storage)),
            !deploy,
            command,
        )?;
        for file in database.iter().chain(std::iter::once(&storage)) {
            generated_or_none(file, command)?;
        }
        let kind = if deploy {
            Kind::Deploy
        } else {
            Kind::Pull(test_users::read(project, command)?)
        };
        Ok(Self {
            project,
            name,
            command,
            folder,
            database,
            storage,
            kind,
        })
    }

    /// Asks the installation for the structure and writes the files whose
    /// content changed. Nothing is written when the pull is refused or
    /// fails: the API's refusal is the ending, with its reason.
    pub(super) async fn fetch(self, kept: &Kept) -> Result<Pulled, Ending> {
        let answered: Answered = shaped(
            kept.at(),
            get_signed_in(kept, &format!("/v1/resources/{}/structure", self.name)).await?,
        )?;
        if answered.resource != self.name {
            return Err(unexpected(
                kept.at(),
                "its answer is not the structure of the Resource asked for",
            ));
        }
        match answered.kind.as_str() {
            "postgres" => self.fetch_database(answered, kept).await,
            "storage" => self.fetch_storage(answered, kept).await,
            _ => Err(unexpected(
                kept.at(),
                "its answer's kind is not one of postgres and storage",
            )),
        }
    }

    /// A database's pull: the definition, the link and the stand-in.
    async fn fetch_database(self, answered: Answered, kept: &Kept) -> Result<Pulled, Ending> {
        let Self {
            project,
            name,
            command,
            folder,
            database,
            kind,
            ..
        } = self;
        let Answered {
            your_access,
            contact,
            fingerprint,
            schema_ts,
            unsupported,
            standin_sql,
            hidden,
            ..
        } = answered;
        let (Some(fingerprint), Some(schema_ts)) = (fingerprint, schema_ts) else {
            return Err(unexpected(
                kept.at(),
                "its answer is not the structure of the Resource asked for",
            ));
        };
        let definition_shape = schema_ts
            .strip_prefix(SCHEMA_FIRST_LINE)
            .is_some_and(|rest| rest.starts_with('\n'));
        if !is_fingerprint(&fingerprint) || !definition_shape {
            return Err(unexpected(
                kept.at(),
                "its answer is not the structure of the Resource asked for",
            ));
        }

        let Some(access) = ["structure", "read", "write"]
            .into_iter()
            .find(|level| your_access.is(level))
        else {
            return Err(unexpected(
                kept.at(),
                "its answer's access is not one of structure, read and write",
            ));
        };
        let one_statement_each = standin_sql.iter().all(|s| s.ends_with(';'));
        if !one_statement_each {
            return Err(unexpected(
                kept.at(),
                "its answer's stand-in is not a list of statements",
            ));
        }
        let test_users = match kind {
            Kind::Pull(Some(file)) => Some(file),
            Kind::Pull(None) => Some(test_users::as_new()?),
            Kind::Deploy => None,
        };
        let made = test_users.is_some() && !project.join(test_users::FILE).exists();
        let relations = folder.join("relations.ts").exists();
        let link = link(name, relations);
        let standin = standin_file(name, &fingerprint, &contact, &standin_sql);
        let files = database;
        let contents = [schema_ts.as_bytes(), link.as_bytes(), standin.as_bytes()];
        // Checked just before writing: a file made meanwhile by someone
        // else is not overwritten either, nor a link made meanwhile written
        // through.
        no_link(project, name, files.iter(), test_users.is_some(), command)?;
        let mut present: Vec<Option<Vec<u8>>> = Vec::with_capacity(files.len());
        for file in &files {
            present.push(generated_or_none(file, command)?);
        }
        fs::create_dir_all(&folder).map_err(|error| {
            file_problem(
                &format!("the folder resources/{name}"),
                "cannot be made",
                &error,
                command,
            )
        })?;
        let mut written = Vec::with_capacity(files.len());
        let definition_changed = present
            .first()
            .is_some_and(|was| was.as_deref() != contents.first().copied());
        for (index, ((file, content), was)) in files.iter().zip(contents).zip(&present).enumerate()
        {
            let mut changed = was.as_deref() != Some(content);
            // A deploy writes the stand-in only with the definition: a
            // stand-in that is missing or behind while the structure is
            // the same is left to `vibe pull`.
            if test_users.is_none() && index == 2 && !definition_changed {
                changed = false;
            }
            if changed {
                write_whole(&file.path, content, "vibe-pull").map_err(|error| {
                    file_problem(&file.shown, "cannot be written", &error, command)
                })?;
            }
            written.push((file.shown.clone(), changed));
        }
        let test_users = wrote_test_users(project, name, access, test_users, made, command)?;
        Ok(Pulled {
            fingerprint: Some(fingerprint),
            storage: false,
            hidden: Some(hidden.unwrap_or(0)),
            contact: Theirs::from(contact.as_str()),
            your_access,
            unsupported,
            files: written,
            test_users,
        })
    }

    /// A Storage Resource's pull: the one file `storage.json`.
    async fn fetch_storage(self, answered: Answered, kept: &Kept) -> Result<Pulled, Ending> {
        let Self {
            project,
            name,
            command,
            folder,
            storage,
            kind,
            ..
        } = self;
        let Answered {
            your_access,
            contact,
            fingerprint,
            schema_ts,
            unsupported,
            standin_sql,
            ..
        } = answered;
        // Its answer holds nothing of a database's.
        if fingerprint.is_some()
            || schema_ts.is_some()
            || !standin_sql.is_empty()
            || !unsupported.is_empty()
        {
            return Err(unexpected(
                kept.at(),
                "its answer is not the structure of the Resource asked for",
            ));
        }
        let Some(access) = ["read", "write"]
            .into_iter()
            .find(|level| your_access.is(level))
        else {
            return Err(unexpected(
                kept.at(),
                "its answer's access is not one of read and write",
            ));
        };
        let test_users = match kind {
            Kind::Pull(Some(file)) => Some(file),
            Kind::Pull(None) => Some(test_users::as_new()?),
            Kind::Deploy => None,
        };
        let made = test_users.is_some() && !project.join(test_users::FILE).exists();
        let file = storage;
        let content = storage_file(name, &contact);
        // Checked just before writing: a file made meanwhile by someone
        // else is not overwritten either, nor a link made meanwhile written
        // through.
        no_link(
            project,
            name,
            std::iter::once(&file),
            test_users.is_some(),
            command,
        )?;
        let was = generated_or_none(&file, command)?;
        fs::create_dir_all(&folder).map_err(|error| {
            file_problem(
                &format!("the folder resources/{name}"),
                "cannot be made",
                &error,
                command,
            )
        })?;
        let changed = was.as_deref() != Some(content.as_bytes());
        if changed {
            write_whole(&file.path, content.as_bytes(), "vibe-pull")
                .map_err(|error| file_problem(&file.shown, "cannot be written", &error, command))?;
        }
        let test_users = wrote_test_users(project, name, access, test_users, made, command)?;
        Ok(Pulled {
            fingerprint: None,
            storage: true,
            hidden: None,
            contact: Theirs::from(contact.as_str()),
            your_access,
            unsupported: Vec::new(),
            files: vec![(file.shown, changed)],
            test_users,
        })
    }
}

/// Copies the Builder's own Grant into `vibe.dev.json`, if this pull writes
/// it, and answers what was done with the file (`None` for a deploy's
/// pull, which never touches it).
fn wrote_test_users(
    project: &Path,
    name: &str,
    access: &'static str,
    test_users: Option<TestUsersFile>,
    made: bool,
    command: &str,
) -> Result<Option<Value>, Ending> {
    let mut test_users = match test_users {
        Some(file) => file,
        None => return Ok(None),
    };
    let changed = test_users.copy_grant(name, access) || made;
    if changed {
        let text = test_users.text().map_err(|_| {
            Ending::new(
                1,
                "tool-failed",
                format!("{} cannot be made", test_users::FILE),
            )
        })?;
        write_whole(&project.join(test_users::FILE), &text, "vibe-pull").map_err(|error| {
            file_problem(test_users::FILE, "cannot be written", &error, command)
        })?;
    }
    Ok(Some(json!({
        "file": test_users::FILE,
        "changed": changed,
        "grant": { "group": test_users::BUILDER, "resource": name, "access": access },
    })))
}

pub(super) async fn pull(args: &PullArgs) -> Result<Done, Ending> {
    let project = project_of(args.project.as_deref(), "vibe pull")?;
    let name = &args.resource;
    let pull = Pull::prepare(&project, name, "vibe pull", false)?;
    let place = Place::from_environment().map_err(Ending::credential_file)?;
    let kept = read_kept(&place)?;
    let pulled = pull.fetch(&kept).await?;

    // In words: a database's pull says its structure and its fingerprint; a
    // Storage Resource's says the Resource and its kind, and has no
    // fingerprint to give (blackbox/CONTRACT.md, "Pulling a Storage
    // Resource, checking and deploying").
    let mut text = if pulled.storage {
        format!(
            "Pulled {name} (storage; your access: {}).\n",
            pulled.your_access
        )
    } else {
        let fingerprint = pulled.fingerprint.as_deref().unwrap_or("null");
        format!(
            "Pulled the structure of {name} (your access: {}; fingerprint {fingerprint}).\n",
            pulled.your_access,
        )
    };
    for (shown, flag) in &pulled.files {
        let what = if *flag { "written" } else { "unchanged" };
        text.push_str(&format!("  {shown}: {what}\n"));
    }
    if let Some(hidden) = pulled.hidden
        && hidden > 0
    {
        text.push_str(&format!(
            "{hidden} relations are not shown because none of the Resource's logins can reach them; code written against one of them will not type-check. To have one shown, ask the Builder to ask the Resource's contact ({}) whether the Resource's logins should be given a privilege on it.\n",
            pulled.contact
        ));
    }
    if !pulled.unsupported.is_empty() {
        text.push_str("Columns of a type the definition cannot express, typed unknown:\n");
    }
    for u in &pulled.unsupported {
        text.push_str(&format!(
            "  {}.{}, column {}: {} is typed unknown\n",
            u.schema, u.table, u.column, u.printed
        ));
    }
    let listed: Vec<_> = pulled
        .files
        .iter()
        .map(|(shown, flag)| json!({ "path": shown, "changed": flag }))
        .collect();
    let mut json = json!({
        "resource": name,
        "fingerprint": pulled.fingerprint,
        "your_access": pulled.your_access,
        "files": listed,
        "unsupported": pulled.unsupported,
        "test_users": pulled.test_users,
    });
    if let Some(hidden) = pulled.hidden
        && let Some(object) = json.as_object_mut()
    {
        object.insert("hidden".into(), json!(hidden));
    }
    Ok(Done { json, text })
}

/// The generated link of `name` (blackbox/CONTRACT.md, "A project"), with
/// the `relations` lines when `relations`.
fn link(name: &str, relations: bool) -> String {
    let mut text = format!("{INDEX_FIRST_LINE}\nimport type * as schema from \"./schema.ts\";\n");
    if relations {
        text.push_str("import type * as relations from \"./relations.ts\";\n");
    }
    let structure = if relations {
        "typeof schema & typeof relations"
    } else {
        "typeof schema"
    };
    text.push_str(&format!(
        "\ndeclare module \"@vm/sdk\" {{\n  interface SharedStructures {{\n    \"{name}\": {structure};\n  }}\n}}\n"
    ));
    text
}

/// The text of `storage.json` (blackbox/CONTRACT.md, "Pulling a Storage
/// Resource, checking and deploying"): the four fields, two spaces a level,
/// and a line end.
fn storage_file(name: &str, contact: &str) -> String {
    let body = json!({
        "generated": STORAGE_GENERATED,
        "resource": name,
        "kind": "storage",
        "contact": contact,
    });
    let mut text = serde_json::to_string_pretty(&body).unwrap_or_default();
    text.push('\n');
    text
}

/// Whether `bytes` are a JSON object whose `generated` is the one the tool
/// writes: how a `storage.json` shows that the tool wrote it.
pub(super) fn storage_generated(bytes: &[u8]) -> bool {
    serde_json::from_slice::<Value>(bytes)
        .ok()
        .and_then(|body| {
            body.get("generated")
                .and_then(Value::as_str)
                .map(|generated| generated == STORAGE_GENERATED)
        })
        .unwrap_or(false)
}

/// That none of the files this pull writes, nor `resources`, nor
/// `resources/<name>`, nor `vibe.dev.json` when it writes it, is a symbolic
/// link (each looked at itself, never followed), so that the tool writes
/// inside the project only. What is not there is not a link.
fn no_link<'f>(
    project: &Path,
    name: &str,
    files: impl IntoIterator<Item = &'f Generated>,
    test_users: bool,
    command: &str,
) -> Result<(), Ending> {
    let mut shown = vec!["resources".to_owned(), format!("resources/{name}")];
    for file in files {
        shown.push(file.shown.clone());
    }
    if test_users {
        shown.push(test_users::FILE.to_owned());
    }
    for path in &shown {
        match fs::symlink_metadata(project.join(path)) {
            Ok(meta) if meta.file_type().is_symlink() => {
                return Err(not_a_project(path, command));
            }
            Ok(_) => {}
            Err(error) if error.kind() == ErrorKind::NotFound => {}
            Err(error) => return Err(file_problem(path, "cannot be read", &error, command)),
        }
    }
    Ok(())
}

/// The ending for a symbolic link at `shown`, which the tool writes nothing
/// through.
fn not_a_project(shown: &str, command: &str) -> Ending {
    Ending::new(
        1,
        "not-a-project",
        format!(
            "{shown} is a symbolic link: {command} writes inside the project only. Replace it with a folder or file of the project's own, then run {command} again; nothing was written"
        ),
    )
}

/// What is at `file`'s path: nothing, or a file the tool wrote (its bytes,
/// when it is small enough to compare). Anything else is `not-generated`;
/// a link is `not-a-project` and is never followed.
fn generated_or_none(file: &Generated, command: &str) -> Result<Option<Vec<u8>>, Ending> {
    let meta = match fs::symlink_metadata(&file.path) {
        Ok(meta) => meta,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(file_problem(&file.shown, "cannot be read", &error, command)),
    };
    if meta.file_type().is_symlink() {
        return Err(not_a_project(&file.shown, command));
    }
    let not_written = |how: &str| {
        Ending::new(
            1,
            "not-generated",
            format!(
                "{} was not written by vibe pull ({how}): move it away or remove it, then run {command} again; nothing was written",
                file.shown,
            ),
        )
    };
    if !meta.is_file() {
        return Err(not_written("it is not a regular file"));
    }
    // A `storage.json` larger than any the tool writes is not one, whatever
    // its beginning says, and is not read: it is left as it is
    // (blackbox/CONTRACT.md, "Pulling a Storage Resource, checking and
    // deploying").
    let too_large = format!("it is larger than the {STORAGE_FILE_BYTES} bytes a pull writes");
    if meta.len() > STORAGE_FILE_BYTES && matches!(file.marker, Marker::Generated(_)) {
        return Err(not_written(&too_large));
    }
    let opened = match File::open(&file.path) {
        Ok(opened) => opened,
        Err(error) if error.kind() == ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(file_problem(&file.shown, "cannot be read", &error, command)),
    };
    let mut bytes = Vec::new();
    opened
        .take(MAX_FILE_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(|error| file_problem(&file.shown, "cannot be read", &error, command))?;
    let whole = u64::try_from(bytes.len()).is_ok_and(|n| n <= MAX_FILE_BYTES);
    let begins = match &file.marker {
        Marker::FirstLine(line) => bytes
            .strip_prefix(line.as_bytes())
            .is_some_and(|rest| rest.is_empty() || rest.starts_with(b"\n")),
        Marker::Generated(_) => {
            u64::try_from(bytes.len()).is_ok_and(|n| n <= STORAGE_FILE_BYTES)
                && storage_generated(&bytes)
        }
    };
    if !begins {
        let how = match &file.marker {
            Marker::FirstLine(line) => format!("it does not begin with `{line}`"),
            Marker::Generated(generated) => {
                if whole {
                    format!("it does not hold \"generated\": \"{generated}\"")
                } else {
                    too_large
                }
            }
        };
        return Err(not_written(&how));
    }
    // A database's file too large to compare is rewritten: it differs from
    // any answer. (A Storage Resource's was refused above.)
    Ok(Some(if whole { bytes } else { Vec::new() }))
}

/// The text of `standin.sql`: three lines (the contact on one, each control
/// character of it a space), an empty line, and each statement with an
/// empty line after it.
fn standin_file(name: &str, fingerprint: &str, contact: &str, statements: &[String]) -> String {
    let contact: String = contact
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect();
    let mut text = format!(
        "{STANDIN_FIRST_LINE}\n-- Resource: {name}  Fingerprint: {fingerprint}\n-- Contact: {contact}\n\n"
    );
    for statement in statements {
        text.push_str(statement);
        text.push_str("\n\n");
    }
    text
}

fn file_problem(what: &str, how: &str, error: &io::Error, command: &str) -> Ending {
    project_file(what, how, error, command)
}
